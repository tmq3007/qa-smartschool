        /// <summary>
        /// Zoom In button click handler (external control panel)
        /// </summary>
        private void BtnGoogleMapsZoomIn_Click(object sender, RoutedEventArgs e)
        {
            try
            {
                var button = sender as Button;
                var innerPanel = button?.Parent as StackPanel;
                var borderWrapper = innerPanel?.Parent as Border;
                var controlPanel = borderWrapper?.Parent as StackPanel;
                var border = controlPanel?.Tag as Border;

                if (border != null)
                {
                    // Get current size
                    double currentWidth = border.Width;
                    double currentHeight = border.Height;

                    // Calculate new size (increase by 20%)
                    double newWidth = currentWidth * 1.2;
                    double newHeight = currentHeight * 1.2;

                    // Limit max size
                    if (newWidth <= 1600 && newHeight <= 1200)
                    {
                        border.Width = newWidth;
                        border.Height = newHeight;

                        // Update WebView size
                        var webView = border.Child as Microsoft.Web.WebView2.Wpf.WebView2;
                        if (webView != null)
                        {
                            webView.Width = newWidth;
                            webView.Height = newHeight;
                        }

                        // Get drag handles from border's Tag
                        dynamic simData = border.Tag;
                        if (simData != null)
                        {
                            Border topDragHandle = simData.TopDragHandle;
                            Border bottomDragHandle = simData.BottomDragHandle;
                            Border leftDragHandle = simData.LeftDragHandle;
                            Border rightDragHandle = simData.RightDragHandle;

                            // Update drag handle sizes
                            topDragHandle.Width = newWidth;
                            bottomDragHandle.Width = newWidth;
                            leftDragHandle.Height = newHeight;
                            rightDragHandle.Height = newHeight;

                            // Update drag handle positions
                            double borderLeft = Canvas.GetLeft(border);
                            double borderTop = Canvas.GetTop(border);

                            Canvas.SetLeft(topDragHandle, borderLeft);
                            Canvas.SetTop(topDragHandle, borderTop - 15);

                            Canvas.SetLeft(bottomDragHandle, borderLeft);
                            Canvas.SetTop(bottomDragHandle, borderTop + newHeight);

                            Canvas.SetLeft(leftDragHandle, borderLeft - 15);
                            Canvas.SetTop(leftDragHandle, borderTop);

                            Canvas.SetLeft(rightDragHandle, borderLeft + newWidth);
                            Canvas.SetTop(rightDragHandle, borderTop);

                            // Update control panel position
                            Canvas.SetLeft(controlPanel, borderLeft + newWidth + 8);
                            Canvas.SetTop(controlPanel, borderTop);
                        }

                        System.Diagnostics.Debug.WriteLine($"🔍 Google Maps zoomed in: {newWidth}×{newHeight}");
                    }
                }
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"❌ Zoom in error: {ex.Message}");
            }
        }

