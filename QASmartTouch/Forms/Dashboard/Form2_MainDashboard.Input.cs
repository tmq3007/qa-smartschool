                return true;
            }

            return false;
        }

        private void MainInteractiveBoard_MouseDown(object sender, MouseButtonEventArgs e)
        {
            // Tự động kích hoạt lại Focus cho MainDashboard nếu đang bị trình duyệt nhúng chiếm Focus
            if (!this.IsActive)
            {
                this.Activate();
                this.Focus();
            }

            if (_isPointerModeActive)
            {
                Point pos = e.GetPosition(MainInteractiveBoard);
                UpdatePointerPosition(pos);
                e.Handled = true;
                return;
            }

            // QC_4.2_DRAG_HANDLE_GUARD: Nếu chạm vào DragHandle hoặc khung nhúng (Google Maps, YouTube...), ngắt ngay chế độ vẽ nét
            if (IsDragHandleOrEmbeddedWidget(e.OriginalSource))
            {
                _isDrawing = false;
                _currentStroke = null;
                System.Diagnostics.Debug.WriteLine("🖱️ MouseDown on DragHandle/Embedded Widget - Skipping drawing handling");
                return;
            }
            // Check if click is on a child button or control that should handle its own event
            if (QASmartTouch.Utilities.InputValidationHelper.IsEventFromInteractiveControl(e.OriginalSource, MainInteractiveBoard))
            {
                _isDraggingSelection = false;
                _draggedSelectionObject = null;
                if (MainInteractiveBoard.IsMouseCaptured)
                    MainInteractiveBoard.ReleaseMouseCapture();
                System.Diagnostics.Debug.WriteLine("🖱️ Click on child Button/Interactive control - releasing drag state and skipping canvas mouse down handling");
                return;
            }
            
            // ✅ Auto-close any open SubMenu when user clicks/touches on the canvas
            // (Replaces Deactivated handler which is incompatible with touch input)
            if (_activeSubMenu != null)
            {
                CloseAllSubmenus();
            }

            // QC_4.2_TOUCH_ERASER_FIX: Skip mouse events promoted from touch/stylus
            // cho CẢ drawing VÀ eraser (Stroke mode) để tránh xung đột capture kép
            // Guard 1: e.StylusDevice != null → standard WPF stylus→mouse promotion
            // Guard 2: _touchHandler.HasActiveTouches → IR/HID screens send mouse WITHOUT StylusDevice
            // Drag eraser được phép qua vì TouchHandler đã return sớm cho Drag mode (L203)
            if ((_drawingEnabled || _eraserEnabled) && IsTouchPromotedMouseEvent(e))
                return;

            // Hide welcome state when user starts interacting with canvas
            HideWelcomeState();

            // Middle Mouse Button Pan: Kéo bảng bằng chuột giữa tức thời (kể cả khi đang chọn Bút)
            if (e.MiddleButton == MouseButtonState.Pressed)
            {
                _isMiddleMousePanning = true;
                _panStartPoint = e.GetPosition(this);
                EnsurePanTransformExists();
                MainInteractiveBoard.Cursor = Cursors.SizeAll;
                MainInteractiveBoard.CaptureMouse();
                e.Handled = true;
                System.Diagnostics.Debug.WriteLine($"🖐️ Middle mouse pan started at ({_panStartPoint.X:F0}, {_panStartPoint.Y:F0})");
                return;
            }

            // Spacebar Pan: Giữ phím Space + Chuột trái để kéo bảng
            if (_isSpacebarDown && e.LeftButton == MouseButtonState.Pressed)
            {
                _isPanning = true;
                _panStartPoint = e.GetPosition(this);
                EnsurePanTransformExists();
                MainInteractiveBoard.Cursor = Cursors.SizeAll;
                MainInteractiveBoard.CaptureMouse();
                e.Handled = true;
                System.Diagnostics.Debug.WriteLine($"🖐️ Spacebar pan started at ({_panStartPoint.X:F0}, {_panStartPoint.Y:F0})");
                return;
            }
            
            // PRIORITY CHECK: If any picker/menu is visible, check if click is outside them
            if (e.LeftButton == MouseButtonState.Pressed)
            {
                // ✅ N25 FIX: Auto-refresh selectable objects if canvas children exist but SelectionManager is empty
            if (_selectionManager.AllObjects.Count == 0 && MainInteractiveBoard.Children.Count > 0)
            {
                RefreshSelectableObjects();
            }

            Point clickPoint = e.GetPosition(MainInteractiveBoard);
                bool shouldClosePickerAndReturn = false;
                
                // Check ColorPicker
                if (_colorPicker != null && _colorPicker.Visibility == Visibility.Visible)
                {
                    Rect pickerBounds = new Rect(
                        Canvas.GetLeft(_colorPicker),
                        Canvas.GetTop(_colorPicker),
                        _colorPicker.ActualWidth,
                        _colorPicker.ActualHeight
                    );
                    
                    if (pickerBounds.Contains(clickPoint))
                    {
                        // Click inside ColorPicker - let it handle the event
                        System.Diagnostics.Debug.WriteLine("🎨 Click inside ColorPicker - event handled by picker");
                        return;
                    }
                    else
                    {
                        // Click outside - close picker and prevent further processing
                        _colorPicker.Hide();
                        System.Diagnostics.Debug.WriteLine("❌ ColorPicker closed - clicked outside");
                        shouldClosePickerAndReturn = true;
                    }
                }
                
                // Check ThicknessPicker
                if (_thicknessPicker != null && _thicknessPicker.Visibility == Visibility.Visible)
                {
                    Rect pickerBounds = new Rect(
                        Canvas.GetLeft(_thicknessPicker),
                        Canvas.GetTop(_thicknessPicker),
                        _thicknessPicker.ActualWidth,
                        _thicknessPicker.ActualHeight
                    );
                    
                    if (pickerBounds.Contains(clickPoint))
                    {
                        // Click inside ThicknessPicker - let it handle the event
                        System.Diagnostics.Debug.WriteLine("📏 Click inside ThicknessPicker - event handled by picker");
                        return;
                    }
                    else
                    {
                        // Click outside - close picker and prevent further processing
                        _thicknessPicker.Hide();
                        System.Diagnostics.Debug.WriteLine("❌ ThicknessPicker closed - clicked outside");
                        shouldClosePickerAndReturn = true;
                    }
                }
                
                // Check MoreMenu
                if (_moreMenu != null && _moreMenu.Visibility == Visibility.Visible)
                {
                    Rect menuBounds = new Rect(
                        Canvas.GetLeft(_moreMenu),
                        Canvas.GetTop(_moreMenu),
                        _moreMenu.ActualWidth,
                        _moreMenu.ActualHeight
                    );
                    
                    if (menuBounds.Contains(clickPoint))
                    {
                        // Click inside MoreMenu - let it handle the event
                        System.Diagnostics.Debug.WriteLine("📋 Click inside MoreMenu - event handled by menu");
                        return;
                    }
                    else
                    {
                        // Click outside - close menu and prevent further processing
                        _moreMenu.Hide();
                        System.Diagnostics.Debug.WriteLine("❌ MoreMenu closed - clicked outside");
                        shouldClosePickerAndReturn = true;
                    }
                }
                
                // If we closed any picker/menu, return without processing selection
                if (shouldClosePickerAndReturn)
                {
                    e.Handled = true;
                    return;
                }
            }
            
            // Paste mode - if clipboard has content, paste at clicked position
            // QC_4.2_PASTE_GUARD: Chỉ xử lý dán khi đang ở Chế độ Chọn (Selection Mode) và KHÔNG ở chế độ vẽ/tẩy
            if (_objectSelectionMode && !_drawingEnabled && !_eraserEnabled && !_shapeDrawingEnabled &&
                _selectionManager?.HasClipboardContent() == true && e.LeftButton == MouseButtonState.Pressed)
            {
                Point clickPoint = e.GetPosition(MainInteractiveBoard);
                var pasted = _selectionManager?.PasteAtPosition(clickPoint);
                
                if (pasted != null)
                {
                    System.Diagnostics.Debug.WriteLine($"📋 Pasted at ({clickPoint.X:F0}, {clickPoint.Y:F0})");
                    
                    if (pasted.Element is Canvas canvas)
                    {
                        Enable3DShapeDragging(canvas);
                    }

                    // Add to undo stack
                    if (pasted.Stroke != null)
                    {
                        RecordAddStrokeAction(pasted.Stroke, $"Paste {pasted.Type}");
                    }
                    else if (pasted.Element != null)
                    {
                        RecordAddAction(pasted.Element, $"Paste {pasted.Type}");
                        // Visual feedback
                        AnimateFadeIn(pasted.Element);
                    }
                }
                
                // Auto-clear clipboard after paste attempt to exit paste mode safely
                _selectionManager?.ClearClipboard();
                System.Diagnostics.Debug.WriteLine("✅ Clipboard cleared - Paste mode ended");
                return;
            }
            
            // Object Selection Mode - delegate to full selection handler
            // Supports: click select, drag to move, rectangle area selection
            if (_objectSelectionMode && e.LeftButton == MouseButtonState.Pressed)
            {
                // CRITICAL FIX: Nếu SelectionBox đang xử lý kéo rê/resize/rotate,
                // KHÔNG gọi MainBoard_SelectionMouseDown và KHÔNG cướp mouse capture.
                // Tránh xung đột kép gây state leak _isMoving bị kẹt true vĩnh viễn.
                if (_selectionBox != null && _selectionBox.IsTransforming)
                {
                    return;
                }
                
                // Reset trạng thái SelectionBox trước khi MainDashboard xử lý
                _selectionBox?.ResetMoveState();
                
                MainBoard_SelectionMouseDown(sender, e);
                // ✅ QC_4.2_CAPTURE_FIX: Chỉ capture mouse khi SelectionMouseDown
                // thực sự khởi tạo hành động (kéo đối tượng hoặc chờ chọn/vẽ khung chọn).
                // Tránh capture vô nghĩa khi chạm vào nút bấm/thân bảng StackPanel.
                if (_draggedSelectionObject != null || _pendingHitObject != null || _isPreparingRectangleSelection || (_isLassoMode && _lassoTool?.IsDrawing == true))
                {
                    // ✅ TOUCH-FIX: Chỉ capture cho Chuột thật. Touch/Stylus đã tự động capture bởi cơ chế implicit của WPF.
                    // Việc gọi CaptureMouse cho Touch sẽ làm hỏng promotion pipeline, nuốt mất sự kiện MouseUp.
                    if (e.StylusDevice == null) 
                    {
                        MainInteractiveBoard.CaptureMouse();
                    }
                    else
                    {
                        System.Diagnostics.Debug.WriteLine("👆 Touch/Stylus detected: Bỏ qua CaptureMouse để tránh Touch Leak");
                    }
                }
                return;
            }
            
            // Pan mode - drag canvas when zoomed and no tools active
            if (_currentZoomLevel > 1.0 && !_drawingEnabled && !_eraserEnabled && !_shapeDrawingEnabled && 
                !_textToolEnabled && !_selectionToolEnabled && !_zoomAreaSelectionEnabled && !_objectSelectionMode &&
                e.LeftButton == MouseButtonState.Pressed)
            {
                _isPanning = true;
                _panStartPoint = e.GetPosition(this);
                MainInteractiveBoard.Cursor = Cursors.SizeAll; // Change to move cursor
                MainInteractiveBoard.CaptureMouse();
                System.Diagnostics.Debug.WriteLine($"🖐️ Pan mode started at ({_panStartPoint.X:F0}, {_panStartPoint.Y:F0})");
                return;
            }
            
            // Zoom Area Selection mode - drag to select region
            if (_zoomAreaSelectionEnabled && e.LeftButton == MouseButtonState.Pressed)
            {
                _zoomAreaStartPoint = e.GetPosition(MainInteractiveBoard);
                _isDrawing = true;
                
                // Create preview rectangle for selection
                _zoomAreaPreview = new Rectangle
                {
                    Stroke = Brushes.DodgerBlue,
                    StrokeThickness = 2,
                    StrokeDashArray = new DoubleCollection { 5, 5 },
                    Fill = new SolidColorBrush(Color.FromArgb(30, 33, 150, 243))
                };
                
                MainInteractiveBoard.Children.Add(_zoomAreaPreview);
                Canvas.SetZIndex(_zoomAreaPreview, 9999);
                MainInteractiveBoard.CaptureMouse();
                
                System.Diagnostics.Debug.WriteLine("🎯 Zoom Area: Started selecting region");
                return;
            }
            
            // Selection tool mode - select element on click
            if (_selectionToolEnabled && e.LeftButton == MouseButtonState.Pressed)
            {
                Point clickPoint = e.GetPosition(MainInteractiveBoard);
                SelectElementAt(clickPoint);
                
                if (_selectedElement != null)
                {
                    _selectionStartPoint = clickPoint;
                    _isDraggingElement = true;
                    MainInteractiveBoard.CaptureMouse();
                }
            }
            // Text tool mode - insert text box on click
            else if (_textToolEnabled && e.LeftButton == MouseButtonState.Pressed)
            {
                Point clickPoint = e.GetPosition(MainInteractiveBoard);
                InsertTextBox(clickPoint);
            }
            // Table drawing mode - drag to draw table
            else if (_isTableDrawingMode && e.LeftButton == MouseButtonState.Pressed)
            {
                _tableDrawStartPoint = e.GetPosition(MainInteractiveBoard);
                StartTableDrawing(_tableDrawStartPoint);
                MainInteractiveBoard.CaptureMouse();
                e.Handled = true;
            }
            // Shape drawing mode
            else if (_shapeDrawingEnabled && e.LeftButton == MouseButtonState.Pressed)
            {
                // QC_4.2_TOUCH_SHAPE_DIRECT: Phiên vẽ hình đã do Touch/Stylus khởi tạo (chuột ảo promote đến sau)
                // → KHÔNG tạo đè preview thứ 2, KHÔNG reset điểm gốc, KHÔNG CaptureMouse tranh chấp TouchCapture.
                if (_activeShapeTouchId != -1 || (_isDrawing && _previewShape != null))
                {
                    return;
                }

                DiscardStaleShapePreview();
                _shapeStartPoint = e.GetPosition(MainInteractiveBoard);
                _isDrawing = true;
                
                // Create preview shape based on selected shape type
                _previewShape = CreateShapePreview(_currentShape);
                
                if (_previewShape != null)
                {
                    MainInteractiveBoard.Children.Add(_previewShape);
                }
                
                // Capture mouse
                MainInteractiveBoard.CaptureMouse();
            }
            // Eraser mode
            else if (_eraserEnabled && IsPrimaryPenOrMousePressed(e))
            {
                Point clickPoint = e.GetPosition(MainInteractiveBoard);
                _isDrawing = true;
                _lastMouseEraserPoint = clickPoint;
                UpdateEraserCursorPreview(clickPoint);
                MainInteractiveBoard.CaptureMouse();
                _eraserEngine?.StartMouseSession();
                _whiteboardManager?.ToolManager.EraserTool.StartSession("mouse");
                
                if (_eraserMode == "Point" || _eraserMode == "Drag")
                {
                    EraseByPointAt(clickPoint, null);
                }
                else // Stroke
                {
                    EraseStrokeAt(clickPoint);
                }
            }
            // Drawing mode
            else if (_drawingEnabled && IsPrimaryPenOrMousePressed(e))
            {
                _objectSelectionMode = false;
                _isDraggingElement = false;
                _draggedSelectionObject = null;
                if (_selectionManager?.SelectedObjects.Count > 0)
                {
                    _selectionManager.DeselectAll();
                }

                _isDrawing = true;
                _lastPoint = e.GetPosition(MainInteractiveBoard);
                
                // âœ¨ Multi-user mode: Override color based on zone
                Color drawingColor = _currentPenColor;
                StudentProfile? assignedStudent = null;
                
                if (_isMultiUserModeActive)
                {
                    assignedStudent = GetStudentByPosition(_lastPoint);
                    
                    // 🔒 Zone Isolation: Block drawing outside assigned zone
                    if (_zoneIsolationEnabled && assignedStudent == null)
                    {
                        System.Diagnostics.Debug.WriteLine($"🚫 Zone isolation: Drawing blocked outside zones");
                        return;
                    }
                    
                    if (assignedStudent != null)
                    {
                        drawingColor = assignedStudent.Color;
                        System.Diagnostics.Debug.WriteLine($"✏️ {assignedStudent.Name} drawing at ({_lastPoint.X:F0}, {_lastPoint.Y:F0})");
                    }
                }
                
                // âœ¨ OPTIMIZATION: Initialize temporary point collection
                _tempStrokePoints.Clear();
                _tempStrokePoints.Add(_lastPoint);
                
                // Create new stroke based on brush type
                _currentStroke = CreateStrokeByBrushType();
                
                // âœ¨ Override stroke color for multi-user mode
                if (_isMultiUserModeActive && assignedStudent != null)
                {
                    _currentStroke.Stroke = new SolidColorBrush(drawingColor);
                }
                
                // Add first point
                _currentStroke.Points.Add(_lastPoint);
                // ✨ DOT SUPPORT: Thêm ngay điểm vi mô (+0.01px) để WPF render ngay lập tức một chấm tròn hoàn hảo
                _currentStroke.Points.Add(new Point(_lastPoint.X + 0.01, _lastPoint.Y));
                
                // Add stroke to canvas
                MainInteractiveBoard.Children.Add(_currentStroke);
                // Nét vẽ khi đang vẽ live nằm trên tầng ActiveStrokeLayer (3000)
                Panel.SetZIndex(_currentStroke, ZIndexConstants.ActiveStrokeLayer);
                
                // Capture mouse to continue tracking even if it leaves the canvas
                MainInteractiveBoard.CaptureMouse();
            }
        }

        private void MainInteractiveBoard_MouseMove(object sender, MouseEventArgs e)
        {
            Point currentPoint = e.GetPosition(MainInteractiveBoard);

            if (_isPointerModeActive)
            {
                UpdatePointerPosition(currentPoint);
                return;
            }
            
            // Middle Mouse Pan mode - drag canvas
            if (_isMiddleMousePanning && e.MiddleButton == MouseButtonState.Pressed && _panTransform != null)
            {
                Point currentWindowPoint = e.GetPosition(this);
                double deltaX = currentWindowPoint.X - _panStartPoint.X;
                double deltaY = currentWindowPoint.Y - _panStartPoint.Y;
                
                _panTransform.X += deltaX;
                _panTransform.Y += deltaY;
                
                _panStartPoint = currentWindowPoint;
                return;
            }

            // Pan mode - drag canvas (Spacebar or zoomed mode)
            if (_isPanning && e.LeftButton == MouseButtonState.Pressed && _panTransform != null)
            {
                Point currentWindowPoint = e.GetPosition(this);
                double deltaX = currentWindowPoint.X - _panStartPoint.X;
                double deltaY = currentWindowPoint.Y - _panStartPoint.Y;
                
                _panTransform.X += deltaX;
                _panTransform.Y += deltaY;
                
                _panStartPoint = currentWindowPoint;
                System.Diagnostics.Debug.WriteLine($"📍 Panning: ({_panTransform.X:F0}, {_panTransform.Y:F0})");
                return;
            }
            
            // Zoom Area Selection - update preview rectangle
            if (_zoomAreaSelectionEnabled && _isDrawing && _zoomAreaPreview != null && e.LeftButton == MouseButtonState.Pressed)
            {
                UpdateZoomAreaPreview(_zoomAreaPreview, _zoomAreaStartPoint, currentPoint);
                return;
            }
            
            // Object Selection Mode - delegate to selection handler for drag/rectangle
            if (_objectSelectionMode && e.LeftButton == MouseButtonState.Pressed)
            {
                MainBoard_SelectionMouseMove(sender, e);
                return;
            }
            
            // Update eraser cursor preview position
            if (_eraserEnabled)
            {
                UpdateEraserCursorPreview(currentPoint);
            }
            
            // Selection tool - drag selected element
            if (_selectionToolEnabled && _isDraggingElement && _selectedElement != null && e.LeftButton == MouseButtonState.Pressed)
            {
                MoveElement(_selectedElement, currentPoint);
            }
            // Table drawing mode - update preview box with live rows & columns
            else if (_isTableDrawingMode && _isDrawingTable && _tablePreviewBorder != null && e.LeftButton == MouseButtonState.Pressed)
            {
                UpdateTableDrawing(currentPoint);
                e.Handled = true;
            }
            // Shape drawing mode - update preview
            else if (_shapeDrawingEnabled && _isDrawing && _previewShape != null && e.LeftButton == MouseButtonState.Pressed)
            {
                UpdateShapePreview(_previewShape, _shapeStartPoint, currentPoint);
            }
            // Eraser mode: erase while mouse is held & dragged
            else if (_eraserEnabled && _isDrawing && IsPrimaryPenOrMousePressed(e))
            {
                UpdateEraserCursorPreview(currentPoint);

                if (_eraserMode == "Point" || _eraserMode == "Drag")
                {
                    EraseByPointAt(currentPoint, _lastMouseEraserPoint);
                    _lastMouseEraserPoint = currentPoint;
                }
                else // Stroke
                {
                    EraseStrokeAt(currentPoint);
                }
            }
            // Continue drawing if mouse is pressed and drawing is enabled
            else if (_isDrawing && IsPrimaryPenOrMousePressed(e) && _currentStroke != null)
            {
                // âœ¨ OPTIMIZATION: Use StrokeOptimizer to filter points
                // Only add point if it's far enough from last point (reduces jitter)
                if (_strokeOptimizer != null && _strokeOptimizer.ShouldAddPoint(currentPoint, _lastPoint))
                {
                    // ✨ Nếu trước đó mới có 1 điểm gốc và 1 điểm vi mô phục vụ hiển thị dấu chấm tức thì,
                    // thay thế điểm vi mô đó bằng điểm di chuyển thực tế đầu tiên.
                    if (_tempStrokePoints.Count == 1 && _currentStroke.Points.Count == 2)
                    {
                        _currentStroke.Points[1] = currentPoint;
                    }
                    else
                    {
                        // Add point to current stroke for real-time preview
                        _currentStroke.Points.Add(currentPoint);
                    }

                    // Add to temporary collection
                    _tempStrokePoints.Add(currentPoint);
                    
                    _lastPoint = currentPoint;
                }
                // If point is too close, skip it (this reduces jitter significantly)
            }
        }

        private void MainInteractiveBoard_MouseUp(object sender, MouseButtonEventArgs e)
        {
            // QC_4.2_TOUCH_ERASER_FIX: Thống nhất guard với MouseDown
            // Chặn touch-promoted mouse events cho CẢ drawing VÀ eraser (Stroke mode)
            if ((_drawingEnabled || _eraserEnabled) && IsTouchPromotedMouseEvent(e))
                return;

            // Middle Mouse Pan mode - finish panning
            if (_isMiddleMousePanning)
            {
                _isMiddleMousePanning = false;
                MainInteractiveBoard.ReleaseMouseCapture();
                RestoreCurrentToolCursor();
                e.Handled = true;
                System.Diagnostics.Debug.WriteLine("🖐️ Middle mouse pan ended");
                return;
            }

            // Pan mode - finish panning (from spacebar or regular pan)
            if (_isPanning)
            {
                _isPanning = false;
                MainInteractiveBoard.ReleaseMouseCapture();
                if (_isSpacebarDown)
                {
                    MainInteractiveBoard.Cursor = Cursors.Hand;
                }
                else
                {
                    RestoreCurrentToolCursor();
                }
                System.Diagnostics.Debug.WriteLine("🖐️ Pan mode ended");
                return;
            }
            
            // Object Selection Mode - delegate to selection handler for completing drag/rectangle
            if (_objectSelectionMode)
            {
                MainBoard_SelectionMouseUp(sender, e);
                MainInteractiveBoard.ReleaseMouseCapture();
                // Đảm bảo SelectionBox không bị kẹt trạng thái _isMoving sau khi MainDashboard xử lý xong
                _selectionBox?.ResetMoveState();
                return;
            }
            
            // Zoom Area Selection - finalize and zoom to selected region
            if (_zoomAreaSelectionEnabled && _isDrawing && _zoomAreaPreview != null)
            {
                Point endPoint = e.GetPosition(MainInteractiveBoard);
                
                // Calculate selected area bounds
                double left = Math.Min(_zoomAreaStartPoint.X, endPoint.X);
                double top = Math.Min(_zoomAreaStartPoint.Y, endPoint.Y);
                double width = Math.Abs(endPoint.X - _zoomAreaStartPoint.X);
                double height = Math.Abs(endPoint.Y - _zoomAreaStartPoint.Y);
                
                // Remove preview rectangle
                MainInteractiveBoard.Children.Remove(_zoomAreaPreview);
                _zoomAreaPreview = null;
                
                // Apply zoom to selected area (if area is large enough)
                if (width > 50 && height > 50)
                {
                    ZoomToArea(left, top, width, height);
                }
                
                // Disable zoom area selection mode
                _zoomAreaSelectionEnabled = false;
                _isDrawing = false;
                MainInteractiveBoard.ReleaseMouseCapture();
                MainInteractiveBoard.Cursor = Cursors.Arrow;
                
                System.Diagnostics.Debug.WriteLine($"🎯 Zoom Area: Completed selection ({width:F0}x{height:F0})");
                return;
            }
            
            // Selection tool - finish dragging
            if (_selectionToolEnabled && _isDraggingElement)
            {
                _isDraggingElement = false;
                MainInteractiveBoard.ReleaseMouseCapture();
            }
            // Eraser mode - release capture and reset drawing state
            else if (_eraserEnabled)
            {
                _isDrawing = false;
                _lastMouseEraserPoint = null;
                if (MainInteractiveBoard.IsMouseCaptured)
                    MainInteractiveBoard.ReleaseMouseCapture();

                var session = _eraserEngine?.EndMouseSession();
                FinalizeEraseSession(session, "Mouse erase");

                var nativeSession = _whiteboardManager?.ToolManager.EraserTool.EndSession("mouse");
                FinalizeNativeEraseSession(nativeSession, "Mouse erase");
            }
            // Table drawing mode - finalize table
            else if (_isTableDrawingMode && _isDrawingTable)
            {
                FinalizeTableDrawing();
                e.Handled = true;
            }
            // Shape drawing mode - finalize shape
            else if (_shapeDrawingEnabled && _isDrawing && _previewShape != null)
            {
                FinalizeShapeDrawing();
            }
            // Stop drawing and add to undo stack
            else if (_isDrawing && _currentStroke != null)
            {
                // ✨ DOT FALLBACK: Đảm bảo nếu nét vẽ chỉ có 1 điểm duy nhất thì luôn có điểm vi mô thứ hai để WPF render
                if (_currentStroke.Points.Count == 1)
                {
                    Point pt = _currentStroke.Points[0];
                    _currentStroke.Points.Add(new Point(pt.X + 0.01, pt.Y));
                }

                // ✨ BALANCED OPTIMIZATION: Apply RDP Decimation + light smoothing
                // Reduces 40-60% redundant points while preserving natural stroke curvature
                if (_strokeOptimizer != null && _tempStrokePoints.Count > 2)
                {
                    int originalCount = _tempStrokePoints.Count;
                    
                    // Step 1: Apply Ramer-Douglas-Peucker decimation to eliminate redundant collinear points
                    var decimatedPoints = _strokeOptimizer.DecimatePoints(_tempStrokePoints);
                    
                    // Step 2: Apply light smoothing to reduce hardware jitter
                    var smoothedPoints = _strokeOptimizer.SmoothPoints(decimatedPoints);
                    
                    // Step 3: Replace stroke points with optimized version
                    _currentStroke.Points.Clear();
                    foreach (var point in smoothedPoints)
                    {
                        _currentStroke.Points.Add(point);
                    }
                    
                    // Debug output
                    System.Diagnostics.Debug.WriteLine($"✨ Stroke optimized: {originalCount} → {smoothedPoints.Count} points (Decimation + 20% smoothing)");
                }

                // Đưa nét vẽ hoàn thành về tầng nội dung chuẩn
                if (_currentBrushType == "Laser")
                {
                    AnimateAndRemoveLaserStroke(_currentStroke);
                }
                else if (_currentBrushType == "Shape")
                {
                    var recognizedShape = ShapeRecognizer.TryRecognizeShape(_currentStroke, _currentPenColor, _currentPenSize);
                    if (recognizedShape != null)
                    {
                        MainInteractiveBoard.Children.Remove(_currentStroke);
                        Panel.SetZIndex(recognizedShape, _currentInkingZIndex);
                        MainInteractiveBoard.Children.Add(recognizedShape);
                        RecordAddAction(recognizedShape, "Recognized Shape");
                        RegisterNewObjectWithSelectionManager(recognizedShape);
                    }
                    else
                    {
                        // Không nhận diện được hình -> chuyển sang Native Ink
                        FinalizeNativeMouseStroke(_currentStroke);
                    }
                }
                else
                {
                    // 🚀 NATIVE INK ACCELERATION: Đưa nét vẽ chuột vào GPU MilCore
                    FinalizeNativeMouseStroke(_currentStroke);
                }
                
                _isDrawing = false;
                _currentStroke = null;
                _tempStrokePoints.Clear(); // Clear temporary collection
                MainInteractiveBoard.ReleaseMouseCapture();
            }
        }

        /// <summary>
        /// Chuyển đổi nét vẽ tự do chuột (Polyline) thành Native Inking Stroke (WPF System.Windows.Ink.Stroke)
        /// giải phóng Polyline tạm khỏi visual tree và nạp vào MainInkPresenter để tăng tốc phần cứng 60 FPS.
