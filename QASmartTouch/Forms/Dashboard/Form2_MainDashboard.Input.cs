        /// Cancel dismiss nếu chạm vào TextBlock khác (chuyển focus, giữ keyboard mở).
        /// </summary>
        private void AutoDismissKeyboardIfNeeded(object originalSource)
        {
            if (_editingSmartNoteCard != null)
            {
                var srcDep = originalSource as DependencyObject;
                if (srcDep == null || !IsDescendantOf(srcDep, _editingSmartNoteCard))
                {
                    CompleteInPlaceSmartNoteEditing();
                    Keyboard.ClearFocus();
                    MainInteractiveBoard?.Focus();
                }
            }

            if (_floatingTouchKeyboard == null || !_floatingTouchKeyboard.IsKeyboardVisible)
                return;

            // Kiểm tra xem target có phải là TextBlock/TextBox hay keyboard
            var source = originalSource as DependencyObject;
            if (source == null) return;

            // Duyệt lên visual tree để tìm xem có chạm vào keyboard hay TextBlock không
            var current = source;
            while (current != null)
            {
                if (current is QASmartTouch.Controls.FloatingTouchKeyboard)
                {
                    // Chạm vào keyboard → không dismiss
                    _floatingTouchKeyboard.CancelAutoDismiss();
                    return;
                }
                if (current is System.Windows.Controls.TextBlock)
                {
                    // Chạm vào TextBlock khác → cancel dismiss (sẽ chuyển focus)
                    _floatingTouchKeyboard.CancelAutoDismiss();
                    return;
                }
                if (current is System.Windows.Controls.TextBox)
                {
                    _floatingTouchKeyboard.CancelAutoDismiss();
                    return;
                }
                current = VisualTreeHelper.GetParent(current);
            }

            // Chạm vào Canvas (ngoài TextBox và Keyboard) → auto-dismiss với debounce
            _floatingTouchKeyboard.RequestAutoDismiss();
        }

