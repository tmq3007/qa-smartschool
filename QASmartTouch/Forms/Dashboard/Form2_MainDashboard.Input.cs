        private void MainInteractiveBoard_MouseLeave(object sender, MouseEventArgs e)
        {
            // Hide eraser preview when mouse leaves canvas
            if (_eraserEnabled && _eraserPreview != null)
            {
                _eraserPreview.Visibility = Visibility.Collapsed;
            }
        }

        private void MainInteractiveBoard_MouseEnter(object sender, MouseEventArgs e)
        {
            // Show eraser preview when mouse enters canvas
            if (_eraserEnabled && _eraserPreview != null)
            {
                _eraserPreview.Visibility = Visibility.Visible;
            }
        }

        private void EnableShapeDrawingMode(string shapeName)
        {
            // QC_4.2_MODE_GUARD: Tắt hoàn toàn Pan Mode nếu đang di chuyển bảng
            if (_isPanModeActive)
                DisablePanMode();

            // Giải phóng MouseCapture
            if (MainScrollViewer.IsMouseCaptured)
                MainScrollViewer.ReleaseMouseCapture();
            if (MainInteractiveBoard.IsMouseCaptured)
                MainInteractiveBoard.ReleaseMouseCapture();

            // Dọn dẹp trạng thái vẽ dở dang
            _isDrawing = false;
            _currentStroke = null;
            _activeShapeTouchId = -1;

            // Store shape settings
            _currentShape = shapeName;
            _shapeDrawingEnabled = true;

            // ── WhiteboardCore FSM: Chuyển sang Shape Mode ──
            _whiteboardManager?.ToolManager.SwitchTo(QASmartTouch.WhiteboardCore.Enums.ToolMode.Shape);
            _drawingEnabled = false; // Disable pen drawing
            
            // Disable eraser with proper cleanup
            if (_eraserEnabled)
                DisableEraserMode();
            
            _textToolEnabled = false; // Disable text tool
            _selectionToolEnabled = false; // Disable selection
            _selectionManager?.DeselectAll();
            _selectionManager?.ClearClipboard();
            
            // Set TouchHandler to None tool mode to prevent drawing freehand lines when drawing shapes
            if (_touchHandler != null)
            {
                _touchHandler.SetToolMode(QASmartTouch.Handlers.TouchToolMode.None);
            }
            
            // Change cursor to crosshair for precise shape drawing
            MainInteractiveBoard.Cursor = Cursors.Cross;
            MainScrollViewer.Cursor = Cursors.Cross;

            if (!string.IsNullOrWhiteSpace(shapeName))
            {
                string capturedShape = shapeName;
                var (shortTitle, iconPath, accentColor) = QASmartTouch.Services.Tools.RecentToolsManager.GetShapeMetadata(capturedShape);
                RegisterRecentTool(
                    $"shape:{capturedShape}",
                    shortTitle,
                    iconPath,
                    accentColor,
                    () =>
                    {
                        DeactivateAllTools();
                        CloseAllSubmenus();
                        SelectTool(btn5_Shapes);
                        HideWelcomeState();
                        EnableShapeDrawingMode(capturedShape);
                    },
                    $"Dùng lại: Vẽ {shortTitle}");
            }
        }

