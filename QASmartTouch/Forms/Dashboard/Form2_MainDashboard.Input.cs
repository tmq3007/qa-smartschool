        private void EnableEraserMode(int eraserSize, string eraserMode)
        {
            if (_isPointerModeActive) DisablePointerMode();
            if (_isPanModeActive) DisablePanMode();

            // Giải phóng MouseCapture nếu ScrollViewer hoặc Board đang giữ capture
            if (MainScrollViewer.IsMouseCaptured)
                MainScrollViewer.ReleaseMouseCapture();
            if (MainInteractiveBoard.IsMouseCaptured)
                MainInteractiveBoard.ReleaseMouseCapture();

            // Dọn dẹp trạng thái vẽ dở dang
            _isDrawing = false;
            _currentStroke = null;

            System.Diagnostics.Debug.WriteLine($"🧹 EnableEraserMode called - Size: {eraserSize}, Mode: {eraserMode}");
            
            // Store eraser settings
            _eraserSize = eraserSize;
            _eraserMode = eraserMode;
            _eraserEnabled = true;

            // ── WhiteboardCore FSM: Chuyển sang Eraser Mode ──
            _whiteboardManager?.ToolManager.SwitchTo(QASmartTouch.WhiteboardCore.Enums.ToolMode.Eraser);
            _whiteboardManager?.ToolManager.EraserTool.Configure(eraserSize, eraserMode);
            _drawingEnabled = false; // Disable drawing
            _shapeDrawingEnabled = false; // Disable shape drawing
            _textToolEnabled = false; // Disable text tool
            _selectionToolEnabled = false; // Disable selection
            _objectSelectionMode = false; // BUGFIX: Disable object selection mode
            
            System.Diagnostics.Debug.WriteLine($"   _eraserEnabled = {_eraserEnabled}");
            System.Diagnostics.Debug.WriteLine($"   _objectSelectionMode = {_objectSelectionMode}");
            
            // Deselect any selected objects, hide selection UI & clear clipboard
            _selectionManager?.DeselectAll();
            _selectionManager?.ClearClipboard();
            HideSmartStatusBadge(); // ✅ G4.2: Ẩn chỉ dẫn khi đổi công cụ
            
            // Create visual eraser cursor preview
            CreateEraserCursorPreview();
            
            // Hide default cursor, we'll use the circular preview instead
            MainInteractiveBoard.Cursor = Cursors.None;

            // QC_4.2_TOUCH_HITTEST_FIX: Giữ ScrollViewer cha có con trỏ Mũi tên (Arrow)
            // để không làm ẩn/ảnh hưởng tới hit-testing cảm ứng của các nút bấm trên thanh công cụ toolbar
            MainScrollViewer.Cursor = Cursors.Arrow;

            // ✨ Sync touch handler to eraser mode
            if (_touchHandler != null)
            {
                _touchHandler.SetToolMode(QASmartTouch.Handlers.TouchToolMode.Eraser);
                _touchHandler.SetEraserProperties(eraserSize, eraserMode);
            }
        }

        private void DisableEraserMode()
        {
            if (_eraserEngine != null)
            {
                var session = _eraserEngine.EndMouseSession();
                if (session != null && session.HasChanges)
                {
                    FinalizeEraseSession(session, "Mouse erase");
                }
            }
            _eraserEnabled = false;
            RemoveEraserCursorPreview();
            MainInteractiveBoard.Cursor = Cursors.Arrow;
            MainScrollViewer.Cursor = Cursors.Arrow;

            // ✨ Reset touch handler to no active tool
            if (_touchHandler != null)
            {
                _touchHandler.SetToolMode(QASmartTouch.Handlers.TouchToolMode.None);
            }
        }

        private void CreateEraserCursorPreview()
        {
            // Remove existing preview if any
            RemoveEraserCursorPreview();
            
            // Create a circular preview showing eraser size (used for Stroke and Point mode)
            _eraserPreview = new Ellipse
            {
                Width = _eraserSize * 2,
                Height = _eraserSize * 2,
                Stroke = Brushes.Red,
                StrokeThickness = 2,
                Fill = new SolidColorBrush(Color.FromArgb(30, 255, 0, 0)), // Semi-transparent red
                IsHitTestVisible = false, // Don't interfere with mouse/touch events
                StrokeDashArray = new DoubleCollection { 3, 2 }, // Dashed border
                Visibility = Visibility.Collapsed // ✅ Start hidden until first touch/mouse move
            };
            
            MainInteractiveBoard.Children.Add(_eraserPreview);
            Canvas.SetZIndex(_eraserPreview, ZIndexConstants.EraserPreview); // Layer 5: Tool Previews
            Canvas.SetLeft(_eraserPreview, -100); // ✅ Off-screen initially
            Canvas.SetTop(_eraserPreview, -100);
        }

        private void UpdateEraserCursorPreview(Point mousePosition)
        {
            if (_eraserPreview == null || !_eraserEnabled) return;
            
            // Center the preview on mouse position
            double left = mousePosition.X - _eraserSize;
            double top = mousePosition.Y - _eraserSize;
            
            // Keep preview within canvas bounds
            left = Math.Max(BoundsHelper.VirtualBoardBounds.Left, Math.Min(left, BoundsHelper.VirtualBoardBounds.Right - _eraserSize * 2));
            top = Math.Max(BoundsHelper.VirtualBoardBounds.Top, Math.Min(top, BoundsHelper.VirtualBoardBounds.Bottom - _eraserSize * 2));
            
            Canvas.SetLeft(_eraserPreview, left);
            Canvas.SetTop(_eraserPreview, top);
            
            // ✅ Show preview once positioned correctly (avoids flash at 0,0)
            if (_eraserPreview.Visibility != Visibility.Visible)
            {
                _eraserPreview.Visibility = Visibility.Visible;
            }
            
            // Update size if it changed
            if (_eraserPreview.Width != _eraserSize * 2)
            {
                _eraserPreview.Width = _eraserSize * 2;
                _eraserPreview.Height = _eraserSize * 2;
            }
        }

