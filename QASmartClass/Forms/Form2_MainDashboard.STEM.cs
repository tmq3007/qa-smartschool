        /// <summary>
        /// Helper method to draw line chart on a canvas
        /// </summary>
        private void DrawLineChartOnCanvas(Canvas canvas, Form2_9_LineChartEditor editor)
        {
            try
            {
                // Get editor data through reflection
                var labelsField = editor.GetType().GetField("labels", 
                    System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance);
                var seriesField = editor.GetType().GetField("lineSeries", 
                    System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance);

                if (labelsField == null || seriesField == null) return;

                var labels = labelsField.GetValue(editor) as List<string>;
                var series = seriesField.GetValue(editor) as System.Collections.IList;

                if (labels == null || series == null || labels.Count == 0 || series.Count == 0) return;

                double width = canvas.Width;
                double height = canvas.Height;
                double marginLeft = 80;
                double marginRight = 50;
                double marginTop = 80;
                double marginBottom = 80;

                double plotWidth = width - marginLeft - marginRight;
                double plotHeight = height - marginTop - marginBottom;

                // Get all data to find min/max
                var allData = new List<double>();
                foreach (var s in series)
                {
                    var dataProperty = s.GetType().GetProperty("Data");
                    if (dataProperty != null)
                    {
                        var data = dataProperty.GetValue(s) as List<double>;
                        if (data != null) allData.AddRange(data);
                    }
                }

                if (allData.Count == 0) return;

                double minValue = Math.Min(0, allData.Min());
                double maxValue = allData.Max();
                double range = maxValue - minValue;
                if (range == 0) range = 1;

                // Draw title
                var titleText = new TextBlock
                {
                    Text = "Biểu đồ đường",
                    FontSize = 20,
                    FontWeight = FontWeights.Bold,
                    Foreground = new SolidColorBrush(Color.FromRgb(44, 62, 80))
                };
                Canvas.SetLeft(titleText, marginLeft + (plotWidth / 2) - 80);
                Canvas.SetTop(titleText, 20);
                canvas.Children.Add(titleText);

                // Draw grid
                for (int i = 0; i <= 10; i++)
                {
                    double y = marginTop + (plotHeight * i / 10);
                    var gridLine = new Line
                    {
                        X1 = marginLeft,
                        Y1 = y,
                        X2 = marginLeft + plotWidth,
                        Y2 = y,
                        Stroke = new SolidColorBrush(Color.FromRgb(230, 230, 230)),
                        StrokeThickness = 1
                    };
                    canvas.Children.Add(gridLine);
                }

                // Draw axes
                var xAxis = new Line
                {
                    X1 = marginLeft,
                    Y1 = marginTop + plotHeight,
                    X2 = marginLeft + plotWidth,
                    Y2 = marginTop + plotHeight,
                    Stroke = Brushes.Black,
                    StrokeThickness = 2
                };
                canvas.Children.Add(xAxis);

                var yAxis = new Line
                {
                    X1 = marginLeft,
                    Y1 = marginTop,
                    X2 = marginLeft,
                    Y2 = marginTop + plotHeight,
                    Stroke = Brushes.Black,
                    StrokeThickness = 2
                };
                canvas.Children.Add(yAxis);

                // Draw Y-axis labels
                for (int i = 0; i <= 10; i++)
                {
                    double value = maxValue - (range * i / 10);
                    double y = marginTop + (plotHeight * i / 10);
                    var label = new TextBlock
                    {
                        Text = value.ToString("N0"),
                        FontSize = 11,
                        Foreground = Brushes.Black
                    };
                    Canvas.SetLeft(label, marginLeft - 60);
                    Canvas.SetTop(label, y - 10);
                    canvas.Children.Add(label);
                }

                // Draw X-axis labels
                for (int i = 0; i < labels.Count; i++)
                {
                    double x = marginLeft + (plotWidth * i / (labels.Count - 1));
                    var label = new TextBlock
                    {
                        Text = labels[i],
                        FontSize = 11,
                        Foreground = Brushes.Black
                    };
                    Canvas.SetLeft(label, x - 15);
                    Canvas.SetTop(label, marginTop + plotHeight + 10);
                    canvas.Children.Add(label);
                }

                // Draw lines
                int lineIndex = 0;
                foreach (var s in series)
                {
                    var nameProperty = s.GetType().GetProperty("Name");
                    var dataProperty = s.GetType().GetProperty("Data");
                    var colorProperty = s.GetType().GetProperty("Color");

                    if (dataProperty == null || colorProperty == null) continue;

                    var data = dataProperty.GetValue(s) as List<double>;
                    var color = (Color)colorProperty.GetValue(s);
                    var name = nameProperty?.GetValue(s) as string ?? $"Line {lineIndex + 1}";

                    if (data == null || data.Count != labels.Count) continue;

                    var points = new List<Point>();
                    for (int i = 0; i < data.Count; i++)
                    {
                        double x = marginLeft + (plotWidth * i / (labels.Count - 1));
                        double normalizedValue = (data[i] - minValue) / range;
                        double y = marginTop + plotHeight - (normalizedValue * plotHeight);
                        points.Add(new Point(x, y));
                    }

                    // Draw line
                    var pathGeometry = new PathGeometry();
                    var figure = new PathFigure { StartPoint = points[0] };
                    for (int i = 1; i < points.Count; i++)
                    {
                        figure.Segments.Add(new LineSegment(points[i], true));
                    }
                    pathGeometry.Figures.Add(figure);

                    var path = new System.Windows.Shapes.Path
                    {
                        Data = pathGeometry,
                        Stroke = new SolidColorBrush(color),
                        StrokeThickness = 3
                    };
                    canvas.Children.Add(path);

                    // Draw points
                    foreach (var point in points)
                    {
                        var ellipse = new Ellipse
                        {
                            Width = 8,
                            Height = 8,
                            Fill = new SolidColorBrush(color),
                            Stroke = Brushes.White,
                            StrokeThickness = 2
                        };
                        Canvas.SetLeft(ellipse, point.X - 4);
                        Canvas.SetTop(ellipse, point.Y - 4);
                        canvas.Children.Add(ellipse);
                    }

                    // Draw legend
                    double legendY = marginTop + 20 + (lineIndex * 25);
                    var legendLine = new Line
                    {
                        X1 = marginLeft + 20,
                        Y1 = legendY,
                        X2 = marginLeft + 50,
                        Y2 = legendY,
                        Stroke = new SolidColorBrush(color),
                        StrokeThickness = 3
                    };
                    canvas.Children.Add(legendLine);

                    var legendText = new TextBlock
                    {
                        Text = name,
                        FontSize = 12,
                        FontWeight = FontWeights.SemiBold,
                        Foreground = Brushes.Black
                    };
                    Canvas.SetLeft(legendText, marginLeft + 60);
                    Canvas.SetTop(legendText, legendY - 8);
                    canvas.Children.Add(legendText);

                    lineIndex++;
                }
            }
            catch (Exception ex)
            {
                // If drawing fails, show error message on canvas
                var errorText = new TextBlock
                {
                    Text = $"Lỗi vẽ biểu đồ: {ex.Message}",
                    FontSize = 14,
                    Foreground = Brushes.Red
                };
                Canvas.SetLeft(errorText, 20);
                Canvas.SetTop(errorText, 20);
                canvas.Children.Add(errorText);
            }
        }

