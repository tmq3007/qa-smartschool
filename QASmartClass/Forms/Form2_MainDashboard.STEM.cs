        /// <summary>
        /// Applies the configured radar chart to the canvas
        /// </summary>
        public void ApplyRadarChartToCanvas(Form2_14_RadarChartEditor editor)
        {
            if (editor == null)
                return;

            // Create a canvas with size 800x700 for the radar chart
            Canvas chartCanvas = new Canvas
            {
                Width = 800,
                Height = 700,
                Background = Brushes.White
            };

            // Draw the configured radar chart on the canvas
            DrawRadarChartOnCanvas(chartCanvas, editor);

            // Add the canvas to MainInteractiveBoard centered
            MainInteractiveBoard.Children.Add(chartCanvas);
            Canvas.SetLeft(chartCanvas, (MainInteractiveBoard.ActualWidth - 800) / 2);
            Canvas.SetTop(chartCanvas, (MainInteractiveBoard.ActualHeight - 700) / 2);
        }

        /// <summary>
        /// Draws the radar chart on the specified canvas
        /// </summary>
        private void DrawRadarChartOnCanvas(Canvas canvas, Form2_14_RadarChartEditor editor)
        {
            if (editor.Axes == null || editor.Axes.Count < 3 || editor.Datasets == null || editor.Datasets.Count == 0)
                return;

            double canvasWidth = canvas.Width;
            double canvasHeight = canvas.Height;
            double centerX = canvasWidth / 2;
            double centerY = canvasHeight / 2;
            double padding = 120;
            double maxRadius = Math.Min(canvasWidth, canvasHeight) / 2 - padding;

            // Background
            var bgRect = new System.Windows.Shapes.Rectangle
            {
                Width = canvasWidth,
                Height = canvasHeight,
                Fill = Brushes.White
            };
            Canvas.SetLeft(bgRect, 0);
            Canvas.SetTop(bgRect, 0);
            canvas.Children.Add(bgRect);

            // Title
            var titleText = new TextBlock
            {
                Text = editor.ChartTitle,
                FontSize = 20,
                FontWeight = FontWeights.Bold,
                Foreground = new SolidColorBrush(Color.FromRgb(44, 62, 80))
            };
            Canvas.SetLeft(titleText, (canvasWidth - titleText.Text.Length * 10) / 2);
            Canvas.SetTop(titleText, 20);
            canvas.Children.Add(titleText);

            int axisCount = editor.Axes.Count;
            double angleStep = (2 * Math.PI) / axisCount;
            double startAngleRad = (editor.StartAngle * Math.PI) / 180;

            // Calculate angle for each axis
            List<double> angles = new List<double>();
            for (int i = 0; i < axisCount; i++)
            {
                double angle = editor.Clockwise
                    ? startAngleRad + (i * angleStep)
                    : startAngleRad - (i * angleStep);
                angles.Add(angle);
            }

            // Draw grid levels
            if (editor.ShowGrid)
            {
                for (int level = 1; level <= editor.GridLevels; level++)
                {
                    double radius = (maxRadius / editor.GridLevels) * level;
                    var polygon = new Polygon
                    {
                        Stroke = new SolidColorBrush(Color.FromRgb(224, 224, 224)),
                        StrokeThickness = 1,
                        Fill = Brushes.Transparent
                    };

                    var points = new PointCollection();
                    for (int i = 0; i < axisCount; i++)
                    {
                        double x = centerX + radius * Math.Cos(angles[i]);
                        double y = centerY + radius * Math.Sin(angles[i]);
                        points.Add(new Point(x, y));
                    }
                    polygon.Points = points;
                    canvas.Children.Add(polygon);

                    // Grid labels (percentage)
                    if (editor.ShowGridLabels && level > 0)
                    {
                        double percentage = (100.0 / editor.GridLevels) * level;
                        var labelText = new TextBlock
                        {
                            Text = $"{percentage:F0}%",
                            FontSize = 9,
                            Foreground = new SolidColorBrush(Color.FromRgb(150, 150, 150))
                        };
                        Canvas.SetLeft(labelText, centerX + 5);
                        Canvas.SetTop(labelText, centerY - radius - 5);
                        canvas.Children.Add(labelText);
                    }
                }
            }

            // Draw axes
            if (editor.ShowAxes)
            {
                for (int i = 0; i < axisCount; i++)
                {
                    double x = centerX + maxRadius * Math.Cos(angles[i]);
                    double y = centerY + maxRadius * Math.Sin(angles[i]);

                    var axisLine = new Line
                    {
                        X1 = centerX,
                        Y1 = centerY,
                        X2 = x,
                        Y2 = y,
                        Stroke = new SolidColorBrush(Color.FromRgb(153, 153, 153)),
                        StrokeThickness = 1
                    };
                    canvas.Children.Add(axisLine);
                }
            }

            // Draw labels
            if (editor.ShowLabels)
            {
                for (int i = 0; i < axisCount; i++)
                {
                    double labelRadius = maxRadius + 20;
                    double x = centerX + labelRadius * Math.Cos(angles[i]);
                    double y = centerY + labelRadius * Math.Sin(angles[i]);

                    var labelText = new TextBlock
                    {
                        Text = editor.Axes[i].Name,
                        FontSize = 12,
                        FontWeight = FontWeights.SemiBold,
                        Foreground = new SolidColorBrush(Color.FromRgb(60, 60, 60))
                    };

                    // Adjust label position based on angle
                    double angleDeg = angles[i] * 180 / Math.PI;
                    if (angleDeg > -90 && angleDeg < 90)
                    {
                        Canvas.SetLeft(labelText, x + 5);
                    }
                    else
                    {
                        Canvas.SetLeft(labelText, x - labelText.Text.Length * 6 - 5);
                    }
                    Canvas.SetTop(labelText, y - 8);

                    canvas.Children.Add(labelText);
                }
            }

            // Draw datasets
            foreach (var dataset in editor.Datasets)
            {
                if (dataset.Data.Count != axisCount)
                {
                    // Adjust data count to match axes
                    while (dataset.Data.Count < axisCount)
                        dataset.Data.Add(0);
                    while (dataset.Data.Count > axisCount)
                        dataset.Data.RemoveAt(dataset.Data.Count - 1);
                }

                var polygon = new Polygon
                {
                    Stroke = new SolidColorBrush(dataset.Color),
                    StrokeThickness = editor.LineWidth,
                    Fill = new SolidColorBrush(dataset.Color) { Opacity = editor.FillOpacity }
                };

                var points = new PointCollection();
                for (int i = 0; i < axisCount; i++)
                {
                    double value = dataset.Data[i];
                    double maxValue = editor.Axes[i].Max;
                    double normalized = Math.Max(0, Math.Min(1, value / maxValue));
                    double radius = maxRadius * normalized;

                    double x = centerX + radius * Math.Cos(angles[i]);
                    double y = centerY + radius * Math.Sin(angles[i]);
                    points.Add(new Point(x, y));
                }
                polygon.Points = points;
                canvas.Children.Add(polygon);

                // Draw points
                for (int i = 0; i < axisCount; i++)
                {
                    double value = dataset.Data[i];
                    double maxValue = editor.Axes[i].Max;
                    double normalized = Math.Max(0, Math.Min(1, value / maxValue));
                    double radius = maxRadius * normalized;

                    double x = centerX + radius * Math.Cos(angles[i]);
                    double y = centerY + radius * Math.Sin(angles[i]);

                    var point = new Ellipse
                    {
                        Width = editor.PointSize * 2,
                        Height = editor.PointSize * 2,
                        Fill = new SolidColorBrush(dataset.Color),
                        Stroke = Brushes.White,
                        StrokeThickness = 2
                    };
                    Canvas.SetLeft(point, x - editor.PointSize);
                    Canvas.SetTop(point, y - editor.PointSize);
                    canvas.Children.Add(point);

                    // Draw values
                    if (editor.ShowValues)
                    {
                        var valueText = new TextBlock
                        {
                            Text = value.ToString("F1"),
                            FontSize = 9,
                            Foreground = new SolidColorBrush(dataset.Color),
                            FontWeight = FontWeights.Bold
                        };
                        Canvas.SetLeft(valueText, x + editor.PointSize + 3);
                        Canvas.SetTop(valueText, y - editor.PointSize - 3);
                        canvas.Children.Add(valueText);
                    }
                }
            }

            // Draw legend
            if (editor.ShowLegend)
            {
                double legendX = 50;
                double legendY = canvasHeight - 50 - (editor.Datasets.Count * 25);

                for (int i = 0; i < editor.Datasets.Count; i++)
                {
                    var dataset = editor.Datasets[i];

                    var colorBox = new System.Windows.Shapes.Rectangle
                    {
                        Width = 20,
                        Height = 15,
                        Fill = new SolidColorBrush(dataset.Color),
                        Stroke = new SolidColorBrush(dataset.Color),
                        StrokeThickness = 1
                    };
                    Canvas.SetLeft(colorBox, legendX);
                    Canvas.SetTop(colorBox, legendY + i * 25);
                    canvas.Children.Add(colorBox);

                    var legendText = new TextBlock
                    {
                        Text = dataset.Label,
                        FontSize = 12,
                        Foreground = new SolidColorBrush(Color.FromRgb(60, 60, 60))
                    };
                    Canvas.SetLeft(legendText, legendX + 30);
                    Canvas.SetTop(legendText, legendY + i * 25);
                    canvas.Children.Add(legendText);
                }
            }
        }

