        private void DrawAreaChartOnCanvas(Canvas canvas, Form2_12_AreaChartEditor editor)
        {
            double canvasWidth = canvas.Width;
            double canvasHeight = canvas.Height;

            double margin = 60;
            double chartWidth = canvasWidth - 2 * margin;
            double chartHeight = canvasHeight - 2 * margin - (editor.ShowLegend ? 40 : 0);

            // Draw background
            var bgRect = new Rectangle
            {
                Width = canvasWidth,
                Height = canvasHeight,
                Fill = Brushes.White
            };
            canvas.Children.Add(bgRect);

            // Draw title
            var title = new TextBlock
            {
                Text = editor.ChartTitle,
                FontSize = 20,
                FontWeight = FontWeights.Bold,
                Foreground = new SolidColorBrush(Color.FromRgb(44, 62, 80))
            };
            Canvas.SetLeft(title, (canvasWidth - title.Text.Length * 10) / 2);
            Canvas.SetTop(title, 15);
            canvas.Children.Add(title);

            // Calculate max value
            double maxValue = 0;
            if (editor.AreaType == "normal")
            {
                maxValue = editor.Series.SelectMany(s => s.Data).DefaultIfEmpty(0).Max();
            }
            else if (editor.AreaType == "stacked")
            {
                for (int i = 0; i < editor.Labels.Count; i++)
                {
                    double sum = editor.Series.Sum(s => i < s.Data.Count ? s.Data[i] : 0);
                    maxValue = Math.Max(maxValue, sum);
                }
            }
            else // percentage
            {
                maxValue = 100;
            }

            maxValue = Math.Ceiling(maxValue / 10) * 10;
            if (maxValue == 0) maxValue = 100;

            // Draw grid
            if (editor.ShowGrid)
            {
                for (int i = 0; i <= 5; i++)
                {
                    double y = margin + (chartHeight / 5) * i;
                    var line = new Line
                    {
                        X1 = margin,
                        Y1 = y,
                        X2 = margin + chartWidth,
                        Y2 = y,
                        Stroke = new SolidColorBrush(Color.FromRgb(230, 230, 230)),
                        StrokeThickness = 1
                    };
                    canvas.Children.Add(line);

                    var valueLabel = new TextBlock
                    {
                        Text = ((maxValue / 5) * (5 - i)).ToString("F0"),
                        FontSize = 11,
                        Foreground = new SolidColorBrush(Color.FromRgb(120, 120, 120))
                    };
                    Canvas.SetLeft(valueLabel, margin - 35);
                    Canvas.SetTop(valueLabel, y - 7);
                    canvas.Children.Add(valueLabel);
                }
            }

            // Draw axes
            if (editor.ShowAxes)
            {
                var xAxis = new Line
                {
                    X1 = margin,
                    Y1 = margin + chartHeight,
                    X2 = margin + chartWidth,
                    Y2 = margin + chartHeight,
                    Stroke = new SolidColorBrush(Color.FromRgb(100, 100, 100)),
                    StrokeThickness = 2
                };
                canvas.Children.Add(xAxis);

                var yAxis = new Line
                {
                    X1 = margin,
                    Y1 = margin,
                    X2 = margin,
                    Y2 = margin + chartHeight,
                    Stroke = new SolidColorBrush(Color.FromRgb(100, 100, 100)),
                    StrokeThickness = 2
                };
                canvas.Children.Add(yAxis);
            }

            // Draw labels
            for (int i = 0; i < editor.Labels.Count; i++)
            {
                double x = margin + (chartWidth / (editor.Labels.Count - 1)) * i;
                var label = new TextBlock
                {
                    Text = editor.Labels[i],
                    FontSize = 12,
                    FontWeight = FontWeights.SemiBold,
                    Foreground = new SolidColorBrush(Color.FromRgb(80, 80, 80))
                };
                Canvas.SetLeft(label, x - 15);
                Canvas.SetTop(label, margin + chartHeight + 10);
                canvas.Children.Add(label);
            }

            // Draw area charts
            double[] stackedValues = new double[editor.Labels.Count];

            for (int seriesIndex = editor.Series.Count - 1; seriesIndex >= 0; seriesIndex--)
            {
                var series = editor.Series[seriesIndex];
                if (series.Data.Count == 0) continue;

                var points = new PointCollection();
                var linePoints = new PointCollection();

                for (int i = 0; i < editor.Labels.Count && i < series.Data.Count; i++)
                {
                    double x = margin + (chartWidth / (editor.Labels.Count - 1)) * i;
                    double value = series.Data[i];

                    if (editor.AreaType == "percentage")
                    {
                        double total = editor.Series.Sum(s => i < s.Data.Count ? s.Data[i] : 0);
                        value = total > 0 ? (value / total) * 100 : 0;
                    }

                    double y;
                    if (editor.AreaType == "stacked")
                    {
                        y = margin + chartHeight - ((stackedValues[i] + value) / maxValue * chartHeight);
                        stackedValues[i] += value;
                    }
                    else
                    {
                        y = margin + chartHeight - (value / maxValue * chartHeight);
                    }

                    points.Add(new Point(x, y));
                    linePoints.Add(new Point(x, y));
                }

                // Close the area polygon
                if (editor.AreaType == "stacked" && seriesIndex < editor.Series.Count - 1)
                {
                    for (int i = editor.Labels.Count - 1; i >= 0; i--)
                    {
                        double x = margin + (chartWidth / (editor.Labels.Count - 1)) * i;
                        double value = series.Data[i < series.Data.Count ? i : series.Data.Count - 1];
                        if (editor.AreaType == "percentage")
                        {
                            double total = editor.Series.Sum(s => i < s.Data.Count ? s.Data[i] : 0);
                            value = total > 0 ? (value / total) * 100 : 0;
                        }
                        double y = margin + chartHeight - ((stackedValues[i] - value) / maxValue * chartHeight);
                        points.Add(new Point(x, y));
                    }
                }
                else
                {
                    points.Add(new Point(margin + chartWidth, margin + chartHeight));
                    points.Add(new Point(margin, margin + chartHeight));
                }

                // Draw area
                Brush areaBrush;
                if (editor.UseGradient)
                {
                    var gradient = new LinearGradientBrush();
                    gradient.StartPoint = new Point(0, 0);
                    gradient.EndPoint = new Point(0, 1);
                    gradient.GradientStops.Add(new GradientStop(Color.FromArgb((byte)(series.Opacity * 255), series.Color.R, series.Color.G, series.Color.B), 0));
                    gradient.GradientStops.Add(new GradientStop(Color.FromArgb((byte)(series.Opacity * 128), series.Color.R, series.Color.G, series.Color.B), 0.5));
                    gradient.GradientStops.Add(new GradientStop(Color.FromArgb(20, series.Color.R, series.Color.G, series.Color.B), 1));
                    areaBrush = gradient;
                }
                else
                {
                    areaBrush = new SolidColorBrush(Color.FromArgb((byte)(series.Opacity * 255), series.Color.R, series.Color.G, series.Color.B));
                }

                var polygon = new Polygon
                {
                    Points = points,
                    Fill = areaBrush,
                    Stroke = new SolidColorBrush(series.Color),
                    StrokeThickness = editor.LineWidth
                };
                canvas.Children.Add(polygon);

                // Draw points
                if (editor.ShowPoints && editor.PointSize > 0)
                {
                    foreach (var point in linePoints)
                    {
                        var ellipse = new Ellipse
                        {
                            Width = editor.PointSize * 2,
                            Height = editor.PointSize * 2,
                            Fill = new SolidColorBrush(series.Color),
                            Stroke = Brushes.White,
                            StrokeThickness = 2
                        };
                        Canvas.SetLeft(ellipse, point.X - editor.PointSize);
                        Canvas.SetTop(ellipse, point.Y - editor.PointSize);
                        canvas.Children.Add(ellipse);
                    }
                }

                // Draw values
                if (editor.ShowValues)
                {
                    for (int i = 0; i < linePoints.Count && i < series.Data.Count; i++)
                    {
                        var value = series.Data[i];
                        var valueLabel = new TextBlock
                        {
                            Text = value.ToString("F0"),
                            FontSize = 10,
                            FontWeight = FontWeights.Bold,
                            Foreground = new SolidColorBrush(series.Color)
                        };
                        Canvas.SetLeft(valueLabel, linePoints[i].X - 12);
                        Canvas.SetTop(valueLabel, linePoints[i].Y - 20);
                        canvas.Children.Add(valueLabel);
                    }
                }
            }

            // Draw legend
            if (editor.ShowLegend)
            {
                double legendY = margin + chartHeight + 50;
                double legendX = margin;

                for (int i = 0; i < editor.Series.Count; i++)
                {
                    var series = editor.Series[i];

                    var legendRect = new Rectangle
                    {
                        Width = 20,
                        Height = 15,
                        Fill = new SolidColorBrush(series.Color)
                    };
                    Canvas.SetLeft(legendRect, legendX);
                    Canvas.SetTop(legendRect, legendY);
                    canvas.Children.Add(legendRect);

                    var legendText = new TextBlock
                    {
                        Text = series.Name,
                        FontSize = 11,
                        Foreground = new SolidColorBrush(Color.FromRgb(80, 80, 80))
                    };
                    Canvas.SetLeft(legendText, legendX + 25);
                    Canvas.SetTop(legendText, legendY);
                    canvas.Children.Add(legendText);

                    legendX += 25 + series.Name.Length * 7 + 20;
                }
            }
        }

