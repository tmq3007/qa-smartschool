        private void DrawScatterChartOnCanvas(Canvas canvas, Form2_13_ScatterChartEditor editor)
        {
            double canvasWidth = canvas.Width;
            double canvasHeight = canvas.Height;
            double padding = 80;
            double chartWidth = canvasWidth - 2 * padding;
            double chartHeight = canvasHeight - 2 * padding;

            // Background
            var bgRect = new Rectangle
            {
                Width = canvasWidth,
                Height = canvasHeight,
                Fill = Brushes.White
            };
            Canvas.SetLeft(bgRect, 0);
            Canvas.SetTop(bgRect, 0);
            canvas.Children.Add(bgRect);

            // Title
            var titleText = new TextBlock
            {
                Text = editor.ChartTitle,
                FontSize = 18,
                FontWeight = FontWeights.Bold,
                Foreground = new SolidColorBrush(Color.FromRgb(44, 62, 80))
            };
            Canvas.SetLeft(titleText, (canvasWidth - titleText.Text.Length * 9) / 2);
            Canvas.SetTop(titleText, 20);
            canvas.Children.Add(titleText);

            if (editor.DataPoints.Count == 0)
                return;

            // Find min/max for scaling
            double minX = editor.DataPoints.Min(p => p.X);
            double maxX = editor.DataPoints.Max(p => p.X);
            double minY = editor.DataPoints.Min(p => p.Y);
            double maxY = editor.DataPoints.Max(p => p.Y);

            double rangeX = maxX - minX;
            double rangeY = maxY - minY;

            // Add 10% padding
            minX -= rangeX * 0.1;
            maxX += rangeX * 0.1;
            minY -= rangeY * 0.1;
            maxY += rangeY * 0.1;
            rangeX = maxX - minX;
            rangeY = maxY - minY;

            // Draw grid
            if (editor.ShowGrid)
            {
                for (int i = 0; i <= 5; i++)
                {
                    double y = padding + (chartHeight / 5) * i;
                    var gridLine = new Line
                    {
                        X1 = padding,
                        Y1 = y,
                        X2 = padding + chartWidth,
                        Y2 = y,
                        Stroke = new SolidColorBrush(Color.FromRgb(230, 230, 230)),
                        StrokeThickness = 1
                    };
                    canvas.Children.Add(gridLine);

                    double value = maxY - (rangeY / 5) * i;
                    var valueText = new TextBlock
                    {
                        Text = value.ToString("F1"),
                        FontSize = 10,
                        Foreground = new SolidColorBrush(Color.FromRgb(100, 100, 100))
                    };
                    Canvas.SetLeft(valueText, padding - 40);
                    Canvas.SetTop(valueText, y - 8);
                    canvas.Children.Add(valueText);
                }

                for (int i = 0; i <= 5; i++)
                {
                    double x = padding + (chartWidth / 5) * i;
                    var gridLine = new Line
                    {
                        X1 = x,
                        Y1 = padding,
                        X2 = x,
                        Y2 = padding + chartHeight,
                        Stroke = new SolidColorBrush(Color.FromRgb(230, 230, 230)),
                        StrokeThickness = 1
                    };
                    canvas.Children.Add(gridLine);

                    double value = minX + (rangeX / 5) * i;
                    var valueText = new TextBlock
                    {
                        Text = value.ToString("F1"),
                        FontSize = 10,
                        Foreground = new SolidColorBrush(Color.FromRgb(100, 100, 100))
                    };
                    Canvas.SetLeft(valueText, x - 15);
                    Canvas.SetTop(valueText, padding + chartHeight + 10);
                    canvas.Children.Add(valueText);
                }
            }

            // Draw axes
            if (editor.ShowAxes)
            {
                var xAxis = new Line
                {
                    X1 = padding,
                    Y1 = padding + chartHeight,
                    X2 = padding + chartWidth,
                    Y2 = padding + chartHeight,
                    Stroke = Brushes.Black,
                    StrokeThickness = 2
                };
                canvas.Children.Add(xAxis);

                var yAxis = new Line
                {
                    X1 = padding,
                    Y1 = padding,
                    X2 = padding,
                    Y2 = padding + chartHeight,
                    Stroke = Brushes.Black,
                    StrokeThickness = 2
                };
                canvas.Children.Add(yAxis);

                // Axis labels
                var xLabel = new TextBlock
                {
                    Text = editor.XAxisLabel,
                    FontSize = 12,
                    FontWeight = FontWeights.SemiBold,
                    Foreground = new SolidColorBrush(Color.FromRgb(60, 60, 60))
                };
                Canvas.SetLeft(xLabel, padding + chartWidth / 2 - xLabel.Text.Length * 3);
                Canvas.SetTop(xLabel, padding + chartHeight + 35);
                canvas.Children.Add(xLabel);

                var yLabel = new TextBlock
                {
                    Text = editor.YAxisLabel,
                    FontSize = 12,
                    FontWeight = FontWeights.SemiBold,
                    Foreground = new SolidColorBrush(Color.FromRgb(60, 60, 60)),
                    RenderTransform = new RotateTransform(-90)
                };
                Canvas.SetLeft(yLabel, padding - 60);
                Canvas.SetTop(yLabel, padding + chartHeight / 2);
                canvas.Children.Add(yLabel);
            }

            // Draw trend line
            if (editor.ShowTrendLine && editor.DataPoints.Count >= 2)
            {
                var (correlation, slope, intercept) = CalculateCorrelationForScatter(editor.DataPoints);

                double x1Canvas = padding;
                double x2Canvas = padding + chartWidth;
                double x1Value = minX;
                double x2Value = maxX;
                double y1Value = slope * x1Value + intercept;
                double y2Value = slope * x2Value + intercept;

                double y1Canvas = padding + chartHeight - ((y1Value - minY) / rangeY) * chartHeight;
                double y2Canvas = padding + chartHeight - ((y2Value - minY) / rangeY) * chartHeight;

                var trendLine = new Line
                {
                    X1 = x1Canvas,
                    Y1 = y1Canvas,
                    X2 = x2Canvas,
                    Y2 = y2Canvas,
                    Stroke = new SolidColorBrush(Color.FromRgb(255, 100, 100)),
                    StrokeThickness = 2,
                    StrokeDashArray = new DoubleCollection { 5, 3 },
                    Opacity = 0.7
                };
                canvas.Children.Add(trendLine);
            }

            // Draw data points
            foreach (var point in editor.DataPoints)
            {
                double x = padding + ((point.X - minX) / rangeX) * chartWidth;
                double y = padding + chartHeight - ((point.Y - minY) / rangeY) * chartHeight;

                var categoryInfo = editor.Categories.ContainsKey(point.Category)
                    ? editor.Categories[point.Category]
                    : new CategoryInfo
                    {
                        Color = Color.FromRgb(102, 126, 234),
                        Shape = editor.DefaultPointShape
                    };

                var pointColor = categoryInfo.Color;
                var pointShape = categoryInfo.Shape;
                var pointSize = point.Size > 0 ? point.Size : editor.DefaultPointSize;

                DrawScatterPoint(canvas, x, y, pointSize, pointColor, pointShape, editor.PointOpacity);

                // Draw label
                if (editor.ShowLabels && !string.IsNullOrEmpty(point.Label))
                {
                    var labelText = new TextBlock
                    {
                        Text = point.Label,
                        FontSize = 9,
                        Foreground = new SolidColorBrush(Color.FromRgb(60, 60, 60))
                    };
                    Canvas.SetLeft(labelText, x + pointSize + 3);
                    Canvas.SetTop(labelText, y - pointSize - 3);
                    canvas.Children.Add(labelText);
                }
            }

            // Draw correlation info
            if (editor.ShowCorrelation && editor.DataPoints.Count >= 2)
            {
                var (correlation, _, _) = CalculateCorrelationForScatter(editor.DataPoints);
                var corrText = new TextBlock
                {
                    Text = $"r = {correlation:F3}",
                    FontSize = 12,
                    FontWeight = FontWeights.Bold,
                    Foreground = new SolidColorBrush(Color.FromRgb(102, 126, 234))
                };
                Canvas.SetLeft(corrText, padding + chartWidth - 80);
                Canvas.SetTop(corrText, padding + 10);
                canvas.Children.Add(corrText);
            }

            // Draw legend
            if (editor.ShowLegend && editor.Categories.Count > 0)
            {
                double legendX = padding + chartWidth - 150;
                double legendY = padding + 40;
                int index = 0;

                foreach (var kvp in editor.Categories)
                {
                    var categoryName = kvp.Key;
                    var categoryInfo = kvp.Value;

                    DrawScatterPoint(canvas, legendX, legendY + index * 25, 5, categoryInfo.Color, categoryInfo.Shape, editor.PointOpacity);

                    var legendText = new TextBlock
                    {
                        Text = categoryName,
                        FontSize = 11,
                        Foreground = new SolidColorBrush(Color.FromRgb(60, 60, 60))
                    };
                    Canvas.SetLeft(legendText, legendX + 15);
                    Canvas.SetTop(legendText, legendY + index * 25 - 6);
                    canvas.Children.Add(legendText);

                    index++;
                }
            }
        }

        private void DrawScatterPoint(Canvas canvas, double x, double y, double size, Color color, string shape, double opacity)
        {
            var brush = new SolidColorBrush(color) { Opacity = opacity };

            switch (shape)
            {
                case "circle":
                    var circle = new Ellipse
                    {
                        Width = size * 2,
                        Height = size * 2,
                        Fill = brush,
                        Stroke = new SolidColorBrush(color),
                        StrokeThickness = 1
                    };
                    Canvas.SetLeft(circle, x - size);
                    Canvas.SetTop(circle, y - size);
                    canvas.Children.Add(circle);
                    break;

                case "square":
                    var square = new Rectangle
                    {
                        Width = size * 2,
                        Height = size * 2,
                        Fill = brush,
                        Stroke = new SolidColorBrush(color),
                        StrokeThickness = 1
                    };
                    Canvas.SetLeft(square, x - size);
                    Canvas.SetTop(square, y - size);
                    canvas.Children.Add(square);
                    break;

                case "triangle":
                    var triangle = new Polygon
                    {
                        Points = new PointCollection
                        {
                            new Point(0, -size),
                            new Point(-size, size),
                            new Point(size, size)
                        },
                        Fill = brush,
                        Stroke = new SolidColorBrush(color),
                        StrokeThickness = 1
                    };
                    Canvas.SetLeft(triangle, x);
                    Canvas.SetTop(triangle, y);
                    canvas.Children.Add(triangle);
                    break;

                case "diamond":
                    var diamond = new Polygon
                    {
                        Points = new PointCollection
                        {
                            new Point(0, -size),
                            new Point(size, 0),
                            new Point(0, size),
                            new Point(-size, 0)
                        },
                        Fill = brush,
                        Stroke = new SolidColorBrush(color),
                        StrokeThickness = 1
                    };
                    Canvas.SetLeft(diamond, x);
                    Canvas.SetTop(diamond, y);
                    canvas.Children.Add(diamond);
                    break;

                case "cross":
                    var crossLine1 = new Line
                    {
                        X1 = x - size,
                        Y1 = y,
                        X2 = x + size,
                        Y2 = y,
                        Stroke = new SolidColorBrush(color) { Opacity = opacity },
                        StrokeThickness = 2
                    };
                    var crossLine2 = new Line
                    {
                        X1 = x,
                        Y1 = y - size,
                        X2 = x,
                        Y2 = y + size,
                        Stroke = new SolidColorBrush(color) { Opacity = opacity },
                        StrokeThickness = 2
                    };
                    canvas.Children.Add(crossLine1);
                    canvas.Children.Add(crossLine2);
                    break;

                case "star":
                    var star = new Polygon
                    {
                        Points = CreateScatterStarPoints(size),
                        Fill = brush,
                        Stroke = new SolidColorBrush(color),
                        StrokeThickness = 1
                    };
                    Canvas.SetLeft(star, x);
                    Canvas.SetTop(star, y);
                    canvas.Children.Add(star);
                    break;

                default:
                    var defaultCircle = new Ellipse
                    {
                        Width = size * 2,
                        Height = size * 2,
                        Fill = brush,
                        Stroke = new SolidColorBrush(color),
                        StrokeThickness = 1
                    };
                    Canvas.SetLeft(defaultCircle, x - size);
                    Canvas.SetTop(defaultCircle, y - size);
                    canvas.Children.Add(defaultCircle);
                    break;
            }
        }

        private PointCollection CreateScatterStarPoints(double size)
        {
            var points = new PointCollection();
            double outerRadius = size;
            double innerRadius = size * 0.4;

            for (int i = 0; i < 10; i++)
            {
                double angle = (i * 36 - 90) * Math.PI / 180;
                double radius = i % 2 == 0 ? outerRadius : innerRadius;
                points.Add(new Point(radius * Math.Cos(angle), radius * Math.Sin(angle)));
            }

            return points;
        }

        private (double correlation, double slope, double intercept) CalculateCorrelationForScatter(List<ScatterDataPoint> points)
        {
            if (points.Count < 2) return (0, 0, 0);

            int n = points.Count;
            double sumX = points.Sum(p => p.X);
            double sumY = points.Sum(p => p.Y);
            double sumXY = points.Sum(p => p.X * p.Y);
            double sumX2 = points.Sum(p => p.X * p.X);
            double sumY2 = points.Sum(p => p.Y * p.Y);

            double numerator = (n * sumXY) - (sumX * sumY);
            double denominator = Math.Sqrt((n * sumX2 - sumX * sumX) * (n * sumY2 - sumY * sumY));

            double correlation = denominator == 0 ? 0 : numerator / denominator;

            // Linear regression
            double slope = (n * sumXY - sumX * sumY) / (n * sumX2 - sumX * sumX);
            double intercept = (sumY - slope * sumX) / n;

            return (correlation, slope, intercept);
        }

