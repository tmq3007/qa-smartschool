        private void DrawPieChartOnCanvas(Canvas canvas, Form2_10_PieChartEditor editor)
        {
            try
            {
                if (editor.Values.Count == 0 || editor.Values.Sum() == 0)
                    return;

                double canvasWidth = canvas.Width;
                double canvasHeight = canvas.Height;
                double centerX = canvasWidth / 2;
                double centerY = canvasHeight / 2;
                double radius = Math.Min(canvasWidth, canvasHeight) * (editor.ChartSize / 100.0) * 0.35;

                double total = editor.Values.Sum();
                double startAngleRad = editor.StartAngle * Math.PI / 180;

                // Draw title
                if (!string.IsNullOrWhiteSpace(editor.ChartTitle))
                {
                    var title = new TextBlock
                    {
                        Text = editor.ChartTitle,
                        FontSize = 20,
                        FontWeight = FontWeights.Bold,
                        Foreground = new SolidColorBrush(Color.FromRgb(44, 62, 80))
                    };
                    Canvas.SetLeft(title, centerX - 150);
                    Canvas.SetTop(title, 20);
                    canvas.Children.Add(title);
                }

                // Adjust center for semi-circle
                if (editor.ChartType == "Semi")
                {
                    centerY = canvasHeight * 0.65;
                    startAngleRad = Math.PI;
                }

                // Draw slices
                double currentAngle = startAngleRad;

                for (int i = 0; i < editor.Values.Count; i++)
                {
                    double sweepAngle = editor.ChartType == "Semi"
                        ? (editor.Values[i] / total) * Math.PI
                        : (editor.Values[i] / total) * 2 * Math.PI;

                    // Calculate explode offset
                    double explodeX = 0, explodeY = 0;
                    if (editor.DisplayStyle == "Exploded")
                    {
                        double midAngle = currentAngle + sweepAngle / 2;
                        explodeX = Math.Cos(midAngle) * editor.ExplodeDistance;
                        explodeY = Math.Sin(midAngle) * editor.ExplodeDistance;
                    }

                    // Draw shadow for 3D effect
                    if (editor.DisplayStyle == "3D" || editor.ShowShadow)
                    {
                        DrawPieSlice(canvas, centerX + explodeX + 5, centerY + explodeY + 5, radius,
                                    currentAngle, sweepAngle,
                                    Color.FromArgb(50, 0, 0, 0),
                                    editor.ChartType == "Donut" ? radius * (editor.DonutHoleSize / 100.0) : 0);
                    }

                    // Draw main slice
                    DrawPieSlice(canvas, centerX + explodeX, centerY + explodeY, radius,
                                currentAngle, sweepAngle,
                                editor.Colors[i],
                                editor.ChartType == "Donut" ? radius * (editor.DonutHoleSize / 100.0) : 0);

                    // Draw labels
                    if (editor.ShowLabels || editor.ShowPercentages || editor.ShowValues)
                    {
                        double midAngle = currentAngle + sweepAngle / 2;
                        double labelRadius = editor.ChartType == "Donut"
                            ? radius * (1 - editor.DonutHoleSize / 200.0)
                            : radius * 0.7;

                        double labelX = centerX + explodeX + Math.Cos(midAngle) * labelRadius;
                        double labelY = centerY + explodeY + Math.Sin(midAngle) * labelRadius;

                        string labelText = "";
                        if (editor.ShowLabels) labelText += editor.Labels[i];
                        if (editor.ShowPercentages)
                        {
                            double percent = (editor.Values[i] / total) * 100;
                            labelText += (labelText.Length > 0 ? "\n" : "") + percent.ToString("F1") + "%";
                        }
                        if (editor.ShowValues)
                        {
                            labelText += (labelText.Length > 0 ? "\n" : "") + editor.Values[i].ToString("N0");
                        }

                        if (!string.IsNullOrWhiteSpace(labelText))
                        {
                            var label = new TextBlock
                            {
                                Text = labelText,
                                FontSize = 11,
                                FontWeight = FontWeights.Bold,
                                Foreground = Brushes.White,
                                TextAlignment = TextAlignment.Center,
                                Background = new SolidColorBrush(Color.FromArgb(180, 0, 0, 0)),
                                Padding = new Thickness(6, 3, 6, 3)
                            };

                            Canvas.SetLeft(label, labelX - 40);
                            Canvas.SetTop(label, labelY - 20);
                            canvas.Children.Add(label);
                        }
                    }

                    currentAngle += sweepAngle;
                }

                // Draw legend
                if (editor.ShowLegend)
                {
                    DrawPieChartLegend(canvas, editor, canvasWidth, canvasHeight);
                }
            }
            catch (Exception ex)
            {
                var errorText = new TextBlock
                {
                    Text = $"Lỗi vẽ biểu đồ: {ex.Message}",
                    FontSize = 14,
                    Foreground = Brushes.Red
                };
                Canvas.SetLeft(errorText, 20);
                Canvas.SetTop(errorText, 20);
                canvas.Children.Add(errorText);
            }
        }

        private void DrawPieSlice(Canvas canvas, double centerX, double centerY, double radius,
                                  double startAngle, double sweepAngle,
                                  Color color, double innerRadius = 0)
        {
            if (sweepAngle <= 0) return;

            // Limit sweep angle to avoid full circle rendering issues
            if (sweepAngle >= 2 * Math.PI - 0.001)
            {
                if (innerRadius > 0)
                {
                    // Draw donut with ellipse geometry
                    var outerEllipse = new EllipseGeometry(new Point(centerX, centerY), radius, radius);
                    var innerEllipse = new EllipseGeometry(new Point(centerX, centerY), innerRadius, innerRadius);
                    var combinedGeo = new CombinedGeometry(GeometryCombineMode.Exclude, outerEllipse, innerEllipse);

                    var donutPath = new Path
                    {
                        Fill = new SolidColorBrush(color),
                        Stroke = Brushes.White,
                        StrokeThickness = 2,
                        Data = combinedGeo
                    };
                    canvas.Children.Add(donutPath);
                }
                else
                {
                    // Draw full circle
                    var ellipse = new Ellipse
                    {
                        Width = radius * 2,
                        Height = radius * 2,
                        Fill = new SolidColorBrush(color),
                        Stroke = Brushes.White,
                        StrokeThickness = 2
                    };
                    Canvas.SetLeft(ellipse, centerX - radius);
                    Canvas.SetTop(ellipse, centerY - radius);
                    canvas.Children.Add(ellipse);
                }
                return;
            }

            double endAngle = startAngle + sweepAngle;

            // Outer arc points
            Point startPointOuter = new Point(
                centerX + radius * Math.Cos(startAngle),
                centerY + radius * Math.Sin(startAngle)
            );

            Point endPointOuter = new Point(
                centerX + radius * Math.Cos(endAngle),
                centerY + radius * Math.Sin(endAngle)
            );

            PathFigure figure = new PathFigure { StartPoint = startPointOuter };

            // Outer arc
            figure.Segments.Add(new ArcSegment
            {
                Point = endPointOuter,
                Size = new Size(radius, radius),
                SweepDirection = SweepDirection.Clockwise,
                IsLargeArc = sweepAngle > Math.PI
            });

            if (innerRadius > 0)
            {
                // Inner arc points for donut
                Point endPointInner = new Point(
                    centerX + innerRadius * Math.Cos(endAngle),
                    centerY + innerRadius * Math.Sin(endAngle)
                );

                Point startPointInner = new Point(
                    centerX + innerRadius * Math.Cos(startAngle),
                    centerY + innerRadius * Math.Sin(startAngle)
                );

                figure.Segments.Add(new LineSegment { Point = endPointInner });
                figure.Segments.Add(new ArcSegment
                {
                    Point = startPointInner,
                    Size = new Size(innerRadius, innerRadius),
                    SweepDirection = SweepDirection.Counterclockwise,
                    IsLargeArc = sweepAngle > Math.PI
                });
                figure.Segments.Add(new LineSegment { Point = startPointOuter });
            }
            else
            {
                // Line to center for pie
                figure.Segments.Add(new LineSegment { Point = new Point(centerX, centerY) });
                figure.Segments.Add(new LineSegment { Point = startPointOuter });
            }

            PathGeometry geometry = new PathGeometry();
            geometry.Figures.Add(figure);

            Path path = new Path
            {
                Fill = new SolidColorBrush(color),
                Stroke = Brushes.White,
                StrokeThickness = 2,
                Data = geometry
            };

            canvas.Children.Add(path);
        }

