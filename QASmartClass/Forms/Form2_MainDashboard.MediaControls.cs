                            isPlaying = false;
                            btnPlayPause.Content = "▶";
                            btnPlayPause.ToolTip = "Phát video";
                        }
                        else
                        {
                            mediaElement.Play();
                            isPlaying = true;
                            btnPlayPause.Content = "⏸";
                            btnPlayPause.ToolTip = "Tạm dừng video";
                        }
                    });
                actionPanel.Children.Add(btnPlayPause);

                // Nút Phát lại từ đầu (🔄)
