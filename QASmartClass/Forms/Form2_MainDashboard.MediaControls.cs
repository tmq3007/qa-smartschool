                        Background = new SolidColorBrush(Color.FromArgb(51, 66, 133, 244)), // #4285F4 with 20% opacity
                        BorderBrush = new SolidColorBrush(Color.FromArgb(204, 66, 133, 244)), // #4285F4 with 80% opacity
