                {
                    var btn = new Button
                    {
                        Content = text,
                        Width = 32,
                        Height = 26,
                        Margin = new Thickness(3, 0, 0, 0),
                        Background = new SolidColorBrush(normalColor),
                        Foreground = Brushes.White,
                        FontSize = 12,
                        FontWeight = FontWeights.Bold,
                        BorderThickness = new Thickness(0),
                        Cursor = Cursors.Hand,
