        /// <summary>
        /// Enable drag-to-move functionality for Google Maps (via all 4 drag handles)
        /// </summary>
        private void EnableGoogleMapsDragToMove(Border border, StackPanel controlPanel, Border topDragHandle, Border leftDragHandle, Border rightDragHandle, Border bottomDragHandle)
        {
            bool isDragging = false;
            Point dragStartPoint = new Point();
            double originalLeft = 0;
            double originalTop = 0;
            double originalControlLeft = 0;
            double originalControlTop = 0;

            // Mouse down on ANY DRAG HANDLE - start dragging
            MouseButtonEventHandler dragHandleMouseDown = (s, e) =>
            {
                _isDrawing = false;
                _currentStroke = null;
                isDragging = true;
                dragStartPoint = e.GetPosition(MainInteractiveBoard);
                originalLeft = Canvas.GetLeft(border);
                originalTop = Canvas.GetTop(border);
                originalControlLeft = Canvas.GetLeft(controlPanel);
                originalControlTop = Canvas.GetTop(controlPanel);
                MainInteractiveBoard.CaptureMouse(); // Capture on canvas, not border
                e.Handled = true;

                System.Diagnostics.Debug.WriteLine("🖱️ Started dragging Google Maps");
            };

            // Attach to all 4 drag handles
            topDragHandle.MouseLeftButtonDown += dragHandleMouseDown;
            leftDragHandle.MouseLeftButtonDown += dragHandleMouseDown;
            rightDragHandle.MouseLeftButtonDown += dragHandleMouseDown;
            bottomDragHandle.MouseLeftButtonDown += dragHandleMouseDown;

            // Mouse move - dragging (on canvas, not border)
            MouseEventHandler canvasMouseMove = (s, e) =>
            {
                if (isDragging)
                {
                    Point currentPoint = e.GetPosition(MainInteractiveBoard);
                    double deltaX = currentPoint.X - dragStartPoint.X;
                    double deltaY = currentPoint.Y - dragStartPoint.Y;

                    double newLeft = originalLeft + deltaX;
                    double newTop = originalTop + deltaY;

                    // Constrain to canvas bounds (account for drag handles)
                    newLeft = Math.Max(15, Math.Min(newLeft, MainInteractiveBoard.ActualWidth - border.Width - 15 - 60)); // 15px for handles, 60px for control panel
                    newTop = Math.Max(15, Math.Min(newTop, MainInteractiveBoard.ActualHeight - border.Height - 15)); // 15px for handles

                    // Update border position
                    Canvas.SetLeft(border, newLeft);
                    Canvas.SetTop(border, newTop);

                    // Update drag handles positions
                    Canvas.SetLeft(topDragHandle, newLeft);
                    Canvas.SetTop(topDragHandle, newTop - 15);

                    Canvas.SetLeft(bottomDragHandle, newLeft);
                    Canvas.SetTop(bottomDragHandle, newTop + border.Height);

                    Canvas.SetLeft(leftDragHandle, newLeft - 15);
                    Canvas.SetTop(leftDragHandle, newTop);

                    Canvas.SetLeft(rightDragHandle, newLeft + border.Width);
                    Canvas.SetTop(rightDragHandle, newTop);

                    // Move control panel along with border
                    Canvas.SetLeft(controlPanel, newLeft + border.Width + 8);
                    Canvas.SetTop(controlPanel, newTop);
                }
            };
            MainInteractiveBoard.MouseMove += canvasMouseMove;

            // Mouse up - stop dragging (on canvas, not border)
            MouseButtonEventHandler canvasMouseUp = (s, e) =>
            {
                if (isDragging)
                {
                    isDragging = false;
                    MainInteractiveBoard.ReleaseMouseCapture();
                    e.Handled = true;

                    System.Diagnostics.Debug.WriteLine($"📍 Google Maps moved to: ({Canvas.GetLeft(border)}, {Canvas.GetTop(border)})");
                }
            };
            MainInteractiveBoard.MouseLeftButtonUp += canvasMouseUp;

            // Mouse leave - cancel dragging if mouse leaves canvas
            MainInteractiveBoard.MouseLeave += (s, e) =>
            {
                if (isDragging)
                {
                    isDragging = false;
                    MainInteractiveBoard.ReleaseMouseCapture();
                }
            };
        }

        /// <summary>
        /// Insert image to canvas (used for PhET screenshots and other images)
        /// </summary>
        public void InsertImageToCanvas(System.Windows.Media.Imaging.BitmapImage image)
        {
            try
            {
                if (image == null)
                {
                    System.Diagnostics.Debug.WriteLine("âš ï¸ Cannot insert null image");
                    return;
                }

                // Create Image control
                var imageControl = new Image
                {
                    Source = image,
                    Width = Math.Min(image.PixelWidth, 800), // Max width 800px
                    Height = Math.Min(image.PixelHeight, 600), // Max height 600px
                    Stretch = Stretch.Uniform
                };

                // Wrap in Border for styling
                var border = new Border
                {
                    Child = imageControl,
                    BorderBrush = new SolidColorBrush(Color.FromRgb(33, 150, 243)), // #2196F3
                    BorderThickness = new Thickness(2),
                    CornerRadius = new CornerRadius(4),
                    Background = Brushes.White,
                    Tag = "InsertedImage"
                };

                // Position at center of visible canvas area
                double centerX = MainScrollViewer.HorizontalOffset + (MainScrollViewer.ViewportWidth / 2) - (border.Width / 2);
                double centerY = MainScrollViewer.VerticalOffset + (MainScrollViewer.ViewportHeight / 2) - (border.Height / 2);

                Canvas.SetLeft(border, Math.Max(0, centerX));
                Canvas.SetTop(border, Math.Max(0, centerY));

                // Add to canvas
                MainInteractiveBoard.Children.Add(border);

                // Register with selection manager
                RegisterNewObjectWithSelectionManager(border);

                // Record undo action
                RecordAddAction(border, "Inserted Image");

                System.Diagnostics.Debug.WriteLine($"✅ Image inserted to canvas: {image.PixelWidth}x{image.PixelHeight}");
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"❌ Insert image error: {ex.Message}");
                MessageBox.Show($"Lỗi chèn ảnh:\n{ex.Message}", "Lỗi",
                              MessageBoxButton.OK, MessageBoxImage.Error);
            }
        }

