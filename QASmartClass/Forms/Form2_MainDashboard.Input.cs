                dragHandleBar.TouchUp += (s, e) =>
                {
                    endMove();
                    if (e.TouchDevice.Captured == dragHandleBar)
                        dragHandleBar.ReleaseTouchCapture(e.TouchDevice);
                    e.Handled = true;
                };

                // ✅ Issue #2: Xử lý mất touch capture bất ngờ
                dragHandleBar.LostTouchCapture += (s, e) =>
                {
                    endMove();
                };

                // Position at center of canvas
                double leftPos = (MainInteractiveBoard.ActualWidth - totalWidth) / 2;
                double topPos = (MainInteractiveBoard.ActualHeight - totalHeight) / 2;

                Canvas.SetLeft(finalContainer, Math.Max(0, leftPos));
                Canvas.SetTop(finalContainer, Math.Max(0, topPos));

