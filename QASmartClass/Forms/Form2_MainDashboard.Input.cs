                {
                    if (isDragging)
                    {
                        double oldLeft = Canvas.GetLeft(finalContainer);
                        double oldTop = Canvas.GetTop(finalContainer);

                        double newLeft = oldLeft + (currentPoint.X - dragStartPoint.X);
                        double newTop = oldTop + (currentPoint.Y - dragStartPoint.Y);

