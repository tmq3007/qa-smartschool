                        newLeft = Math.Max(0, Math.Min(newLeft, MainInteractiveBoard.ActualWidth - totalWidth));
                        newTop = Math.Max(0, Math.Min(newTop, MainInteractiveBoard.ActualHeight - totalHeight));

