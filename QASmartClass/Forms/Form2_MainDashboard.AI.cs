        private (BitmapSource? bitmap, byte[]? bytes) CaptureCleanSelectionArea(Rect selectionBounds)
        {
            var selectedObjs = _selectionManager?.GetSelectedObjects();
            if (selectedObjs != null && selectedObjs.Count > 0)
            {
                var res = CaptureStrokesAsBlackOnWhite(selectedObjs, selectionBounds);
                if (res.bitmap != null && res.bytes != null) return res;
