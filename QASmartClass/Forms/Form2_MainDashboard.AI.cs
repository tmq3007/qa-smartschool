                {
                    Content = "â¹ï¸ Stop",
                    Width = 100,
                    Height = 35,
                    Margin = new Thickness(5)
                };
                stopButton.Click += (s, args) =>
                {
                    synthesizer.SpeakAsyncCancelAll();
                    System.Diagnostics.Debug.WriteLine("â¹ï¸ Speech stopped");
                };

                var closeButton = new System.Windows.Controls.Button
                {
                    Content = "Close",
                    Width = 100,
                    Height = 35,
                    Margin = new Thickness(5)
                };
                closeButton.Click += (s, args) =>
                {
                    synthesizer.SpeakAsyncCancelAll();
                    synthesizer.Dispose();
                    ttsDialog.Close();
                };

                buttonsPanel.Children.Add(speakButton);
                buttonsPanel.Children.Add(stopButton);
                buttonsPanel.Children.Add(closeButton);
                stackPanel.Children.Add(buttonsPanel);

                ttsDialog.Content = stackPanel;
                ttsDialog.Closed += (s, args) => synthesizer.Dispose();
                ttsDialog.ShowDialog();
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"❌ TTS Error: {ex.Message}");
                MessageBox.Show($"Failed to initialize Text-to-Speech: {ex.Message}", "Error", 
                    MessageBoxButton.OK, MessageBoxImage.Error);
            }
            finally
            {
                _moreMenu?.Hide();
            }
        }

