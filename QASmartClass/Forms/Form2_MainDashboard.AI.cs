                var voicePanel = new StackPanel
                {
                    Orientation = Orientation.Horizontal,
                    Margin = new Thickness(0, 10, 0, 10)
                };
                
                var voiceLabel = new Label { Content = "Voice:", Width = 80 };
                var voiceCombo = new ComboBox { Width = 250 };
                
                foreach (var voice in synthesizer.GetInstalledVoices())
                {
                    voiceCombo.Items.Add(new ComboBoxItem 
                    { 
                        Content = voice.VoiceInfo.Name,
                        Tag = voice.VoiceInfo
                    });
                }
                if (voiceCombo.Items.Count > 0)
                    voiceCombo.SelectedIndex = 0;

                voicePanel.Children.Add(voiceLabel);
                voicePanel.Children.Add(voiceCombo);
                stackPanel.Children.Add(voicePanel);

                // Speed control
                var speedPanel = new StackPanel
                {
                    Orientation = Orientation.Horizontal,
                    Margin = new Thickness(0, 5, 0, 15)
                };
                
                var speedLabel = new Label { Content = "Speed:", Width = 80 };
                var speedSlider = new Slider
                {
                    Width = 150,
                    Minimum = -10,
                    Maximum = 10,
                    Value = 0,
                    TickFrequency = 1,
                    IsSnapToTickEnabled = true
                };
                var speedValueLabel = new Label { Content = "Normal", Width = 100 };
                
                speedSlider.ValueChanged += (s, args) =>
                {
                    int speed = (int)speedSlider.Value;
                    speedValueLabel.Content = speed == 0 ? "Normal" : 
                        (speed > 0 ? $"+{speed}" : speed.ToString());
                };

                speedPanel.Children.Add(speedLabel);
                speedPanel.Children.Add(speedSlider);
                speedPanel.Children.Add(speedValueLabel);
                stackPanel.Children.Add(speedPanel);

