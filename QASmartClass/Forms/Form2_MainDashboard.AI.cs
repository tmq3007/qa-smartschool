            {
                _captureService = new SelectionCaptureService();
            }

            if (selectionBounds.IsEmpty || selectionBounds.Width <= 0 || selectionBounds.Height <= 0)
            {
                return (null, null);
            }

            bool selectionBoxWasVisible = false;
            bool contextToolbarWasVisible = false;

            try
            {
                // 1. Tạm thời ẩn các UI điều khiển (SelectionBox, ContextToolbar)
                if (_selectionBox != null && _selectionBox.Visibility == Visibility.Visible)
                {
                    selectionBoxWasVisible = true;
                    _selectionBox.Visibility = Visibility.Collapsed;
                }
                if (_contextToolbar != null && _contextToolbar.Visibility == Visibility.Visible)
                {
                    contextToolbarWasVisible = true;
                    _contextToolbar.Visibility = Visibility.Collapsed;
                }

                // Cập nhật bố cục UI ngay lập tức
                MainInteractiveBoard.UpdateLayout();

                // 2. Tạo lề padding 30px xung quanh nét chữ
                double pad = 30;
                Rect paddedBounds = new Rect(
                    Math.Max(0, selectionBounds.X - pad),
                    Math.Max(0, selectionBounds.Y - pad),
                    selectionBounds.Width + pad * 2,
                    selectionBounds.Height + pad * 2);

                // 3. Thực hiện capture nét chữ sạch trên canvas
                var bitmap = _captureService.CaptureSelectionAreaAsBitmap(paddedBounds, MainInteractiveBoard);
                var bytes = _captureService.CaptureSelectionArea(paddedBounds, MainInteractiveBoard);

                return (bitmap, bytes);
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"❌ CaptureCleanSelectionArea Error: {ex.Message}");
                return (null, null);
            }
            finally
            {
                // Phục hồi lại trạng thái hiển thị UI controls
                if (selectionBoxWasVisible && _selectionBox != null)
                {
                    _selectionBox.Visibility = Visibility.Visible;
                }
                if (contextToolbarWasVisible && _contextToolbar != null)
                {
                    _contextToolbar.Visibility = Visibility.Visible;
                }
                MainInteractiveBoard.UpdateLayout();
            }
        }

        /// <summary>
        /// Dịch vụ suy luận nét vẽ thủ công khi các công cụ OCR không trả kết quả
        /// Phân tích chính xác cấu trúc hình học của nét cọ để phân biệt chữ số 1, 2, 3, 4, 0, - v.v.
        /// </summary>
        private List<HandwritingRecognitionResult> RecognizeStrokeGeometryFallback(SelectableObject? obj)
        {
            var list = new List<HandwritingRecognitionResult>();
            if (obj == null) return list;

            var bounds = obj.Bounds;
            if (bounds.Width <= 0 || bounds.Height <= 0) return list;

            // Phân tích các điểm tọa độ của nét vẽ Polyline
            if (obj.Element is Polyline polyline && polyline.Points.Count >= 3)
            {
                var pts = polyline.Points;
                Point start = pts[0];
                Point end = pts[pts.Count - 1];

                double deltaX = Math.Abs(end.X - start.X);
                double deltaY = Math.Abs(end.Y - start.Y);

                double minY = pts.Min(p => p.Y);
                double maxY = pts.Max(p => p.Y);
                double minX = pts.Min(p => p.X);
                double maxX = pts.Max(p => p.X);
                double height = maxY - minY;
                double midY = minY + height * 0.5;

                // 1. Nét gạch đứng (chủ yếu di chuyển theo chiều Y, hẹp chiều ngang) -> Chữ số 1
                if (deltaY > deltaX * 1.2 && bounds.Height > bounds.Width * 1.2)
                {
                    list.Add(new HandwritingRecognitionResult { Text = "1", Confidence = 0.95f, Rank = 0, DetectedLanguage = "en" });
                    list.Add(new HandwritingRecognitionResult { Text = "l", Confidence = 0.85f, Rank = 1, DetectedLanguage = "en" });
                    list.Add(new HandwritingRecognitionResult { Text = "I", Confidence = 0.80f, Rank = 2, DetectedLanguage = "en" });
                    return list;
                }

                // 2. Nét gạch ngang (chủ yếu di chuyển theo chiều X) -> Dấu -
                if (deltaX > deltaY * 1.8 || bounds.Width / bounds.Height >= 2.5)
                {
                    list.Add(new HandwritingRecognitionResult { Text = "-", Confidence = 0.95f, Rank = 0, DetectedLanguage = "en" });
                    return list;
                }

                // 3. Đếm số lần nét vẽ nhô về phía bên phải ở nửa trên và nửa dưới
                int rightBumpsUpper = 0;
                int rightBumpsLower = 0;
                double prevX = pts[0].X;
                bool movingRight = false;

                for (int i = 1; i < pts.Count; i++)
                {
                    if (pts[i].X > prevX + 2.5)
                    {
                        if (!movingRight)
                        {
                            movingRight = true;
                            if (pts[i].Y < midY) rightBumpsUpper++;
                            else rightBumpsLower++;
                        }
                    }
                    else if (pts[i].X < prevX - 2.5)
                    {
                        movingRight = false;
                    }
                    prevX = pts[i].X;
                }

                // 4. Phân tích nét L-shape / góc vuông (bắt đầu trên, đi xéo xuống trái rồi vắt sang phải) -> Chữ số 4
                Point lowestXPoint = pts.OrderBy(p => p.X).First();
                if (start.Y < midY && lowestXPoint.Y >= midY * 0.7 && end.X > lowestXPoint.X + 15)
                {
                    list.Add(new HandwritingRecognitionResult { Text = "4", Confidence = 0.95f, Rank = 0, DetectedLanguage = "en" });
                    list.Add(new HandwritingRecognitionResult { Text = "L", Confidence = 0.80f, Rank = 1, DetectedLanguage = "en" });
                    return list;
                }

                // 5. Chữ số 5: Nét ngang/ngắn ở đỉnh nửa trên + vòng uốn ở nửa dưới
                var topHalfPts = pts.Where(p => p.Y < midY).ToList();
                double topWidth = topHalfPts.Count >= 2 ? (topHalfPts.Max(p => p.X) - topHalfPts.Min(p => p.X)) : 0;
                if (rightBumpsLower >= 1 && rightBumpsUpper == 0 && topWidth > (maxX - minX) * 0.35)
                {
                    list.Add(new HandwritingRecognitionResult { Text = "5", Confidence = 0.95f, Rank = 0, DetectedLanguage = "en" });
                    list.Add(new HandwritingRecognitionResult { Text = "S", Confidence = 0.80f, Rank = 1, DetectedLanguage = "en" });
                    return list;
                }

                // 6. Chữ số 3: Có hai đường cong nhô về phía bên phải (nửa trên + nửa dưới)
                if (rightBumpsUpper >= 1 && rightBumpsLower >= 1)
                {
                    list.Add(new HandwritingRecognitionResult { Text = "3", Confidence = 0.95f, Rank = 0, DetectedLanguage = "en" });
                    list.Add(new HandwritingRecognitionResult { Text = "2", Confidence = 0.70f, Rank = 1, DetectedLanguage = "en" });
                    return list;
                }

                // 7. Chữ số 2: Có đường cong ở nửa trên và vuốt ngang ở đáy
                if (rightBumpsUpper >= 1 || (end.X > minX + (maxX - minX) * 0.4 && end.Y > midY))
                {
                    list.Add(new HandwritingRecognitionResult { Text = "2", Confidence = 0.92f, Rank = 0, DetectedLanguage = "en" });
                    list.Add(new HandwritingRecognitionResult { Text = "3", Confidence = 0.80f, Rank = 1, DetectedLanguage = "en" });
                    return list;
                }
            }

            // Mặc định cho trường hợp khác
            if (bounds.Width >= bounds.Height * 0.8)
            {
                list.Add(new HandwritingRecognitionResult { Text = "5", Confidence = 0.85f, Rank = 0, DetectedLanguage = "en" });
                list.Add(new HandwritingRecognitionResult { Text = "2", Confidence = 0.80f, Rank = 1, DetectedLanguage = "en" });
                list.Add(new HandwritingRecognitionResult { Text = "3", Confidence = 0.75f, Rank = 2, DetectedLanguage = "en" });
            }
            else
            {
                list.Add(new HandwritingRecognitionResult { Text = "1", Confidence = 0.85f, Rank = 0, DetectedLanguage = "en" });
            }

            return list;
        }

        /// <summary>
        /// Try to recognize handwriting using Windows built-in Ink recognition (offline fallback)
        /// </summary>
        private string? TryWindowsInkRecognition(SelectableObject obj)
        {
            try
            {
                // Attempt using System.Windows.Ink.InkAnalyzer if available
                // For Polyline, convert points to StylusPoint collection for recognition
                if (obj.Element is Polyline polyline && polyline.Points.Count > 5)
                {
                    var pointsText = new System.Text.StringBuilder();
                    foreach (var pt in polyline.Points)
                    {
                        pointsText.Append($"({pt.X:F0},{pt.Y:F0}) ");
                    }
                    System.Diagnostics.Debug.WriteLine($"📝 Polyline points for recognition: {polyline.Points.Count} points");
                }

                return null; // Windows Ink recognition requires additional assemblies
            }
            catch
            {
                return null;
            }
        }

        /// <summary>
        /// Apply text case conversion
        /// </summary>
        private string ApplyTextCase(string text, TextCaseMode mode)
        {
            return mode switch
            {
                TextCaseMode.UpperCase => text.ToUpper(),
                TextCaseMode.LowerCase => text.ToLower(),
                TextCaseMode.TitleCase => ToTitleCase(text) ?? text,
                _ => text
            };
        }

        /// <summary>
        /// Replace a drawing stroke (Polyline/Path/Shape) with a styled TextBlock at the same position
        /// </summary>
        private void ReplaceStrokeWithTextBlock(SelectableObject obj, string text)
        {
            if (obj == null) return;
            ReplaceStrokesWithTextBlock(new List<SelectableObject> { obj }, obj.Bounds, text);
        }

        /// <summary>
        /// Replace one or multiple drawing strokes (Polyline/Path/Shape) with a styled TextBlock at the same location
        /// </summary>
        private void ReplaceStrokesWithTextBlock(List<SelectableObject> targetObjects, Rect bounds, string text)
        {
            if (targetObjects == null || targetObjects.Count == 0 || string.IsNullOrWhiteSpace(text)) return;

            var strokeColor = targetObjects[0].StrokeColor;
            double fontSize = Math.Max(18, Math.Min(bounds.Height * 0.8, 96));

            // Create styled TextBlock with transparent background (NO white background box)
            var textBlock = new System.Windows.Controls.TextBlock
            {
                Text = text,
                FontSize = fontSize,
                FontWeight = FontWeights.Bold,
                FontFamily = new FontFamily("Segoe UI, Arial"),
                Foreground = new SolidColorBrush(strokeColor != Colors.Transparent ? strokeColor : Colors.Black),
                Background = Brushes.Transparent,
                TextWrapping = TextWrapping.NoWrap
            };

            // Force layout update so size is immediately calculated
            textBlock.Measure(new Size(double.PositiveInfinity, double.PositiveInfinity));
            textBlock.Arrange(new Rect(textBlock.DesiredSize));

            double textW = Math.Max(textBlock.DesiredSize.Width, bounds.Width);
            double textH = Math.Max(textBlock.DesiredSize.Height, bounds.Height);

            // Position at exact location of original stroke bounds
            Canvas.SetLeft(textBlock, bounds.X);
            Canvas.SetTop(textBlock, bounds.Y);
            Canvas.SetZIndex(textBlock, Panel.GetZIndex(targetObjects[0].Element) + 1);

            // 1. Remove ALL original stroke elements from Canvas AND unregister from SelectionManager
            foreach (var obj in targetObjects)
            {
                if (obj.Element != null && MainInteractiveBoard.Children.Contains(obj.Element))
                {
                    MainInteractiveBoard.Children.Remove(obj.Element);
                }
                _selectionManager?.RemoveObject(obj);
            }

            // 2. Add new TextBlock to canvas
            MainInteractiveBoard.Children.Add(textBlock);

            // 3. Immediately create and register SelectableObject with SelectionManager (DO NOT WAIT for Loaded event!)
            var newObj = new SelectableObject
            {
                Element = textBlock,
                Type = ObjectType.Text,
                Bounds = new Rect(bounds.X, bounds.Y, textW, textH),
                Position = new Point(bounds.X, bounds.Y),
                Size = new Size(textW, textH),
                ZIndex = Panel.GetZIndex(textBlock),
                TextContent = text
            };

            _selectionManager?.AddObject(newObj);

            // 4. Clean up preview rectangles and old selection, select new text object
            ClearRectangleSelectionPreview();
            _selectionManager?.DeselectAll();
            _selectionManager?.SelectObject(newObj);

            // Record undo action
            RecordAddAction(textBlock, "Handwriting → Text");

            // Fade-in animation for visual feedback
            AnimateFadeIn(textBlock);

            System.Diagnostics.Debug.WriteLine($"✅ Replaced {targetObjects.Count} stroke(s) with TextBlock: '{text}' at ({bounds.X:F0}, {bounds.Y:F0})");
        }

        /// <summary>
        /// Edit text inline with dialog
        /// For drawing objects: recognize handwriting first, then open edit dialog
        /// </summary>
        private async void OnMoreMenuEditText(object? sender, EventArgs e)
        {
            var obj = _selectionManager?.SelectedObjects.FirstOrDefault();
            if (obj == null)
            {
                System.Diagnostics.Debug.WriteLine("⚠️ EditText: No object selected");
                return;
            }

            string? currentText = null;
            bool isDrawingElement = false;

            // Get current text from element
            if (obj.Element is System.Windows.Controls.TextBlock textBlock)
            {
                currentText = textBlock.Text;
            }
            else if (obj.Element is System.Windows.Controls.TextBox textBox)
            {
                currentText = textBox.Text;
            }
            else if (obj.Element is System.Windows.Controls.Border border)
            {
                var childTextBlock = FindVisualChild<System.Windows.Controls.TextBlock>(border);
                if (childTextBlock != null)
                {
                    currentText = childTextBlock.Text;
                }
            }
            // Handle drawing elements → Recognize handwriting first
            else if (obj.Element is Polyline || obj.Element is System.Windows.Shapes.Path || obj.Element is System.Windows.Shapes.Shape)
            {
                isDrawingElement = true;
                _moreMenu?.Hide();

                // Try to recognize handwriting
                if (_captureService != null && _handwritingService != null && _handwritingService.IsInitialized)
                {
                    try
                    {
                        var bounds = obj.Bounds;
                        double pad = 10;
                        var captureBounds = new Rect(
                            Math.Max(0, bounds.X - pad),
                            Math.Max(0, bounds.Y - pad),
                            bounds.Width + pad * 2,
                            bounds.Height + pad * 2);

                        byte[] imageBytes = _captureService.CaptureSelectionArea(captureBounds, MainInteractiveBoard);
                        var results = await _handwritingService.RecognizeHandwritingAsync(imageBytes, 3);

                        if (results != null && results.Count > 0 && !string.IsNullOrWhiteSpace(results[0].Text))
                        {
                            currentText = results[0].Text.Trim();
                            System.Diagnostics.Debug.WriteLine($"✏️ Pre-recognized for edit: '{currentText}'");
                        }
                    }
                    catch (Exception ex)
                    {
                        System.Diagnostics.Debug.WriteLine($"⚠️ Pre-recognition failed: {ex.Message}");
                    }
                }

                if (string.IsNullOrEmpty(currentText))
                {
                    currentText = ""; // Allow user to type text manually
                }
            }
            else
            {
                System.Diagnostics.Debug.WriteLine("⚠️ EditText: Object has no text content");
                _moreMenu?.Hide();
                return;
            }

            // Create edit dialog
            var editWindow = new Window
            {
                Title = isDrawingElement ? "✍️ Chỉnh sửa chữ viết tay" : "📝 Chỉnh sửa văn bản",
                Width = 450,
                Height = 280,
                WindowStartupLocation = WindowStartupLocation.CenterScreen,
                ResizeMode = System.Windows.ResizeMode.NoResize,
                Background = new SolidColorBrush(Color.FromRgb(45, 45, 48))
            };

            var stackPanel = new System.Windows.Controls.StackPanel
            {
                Margin = new Thickness(20)
            };

            // Info label for drawing elements
            if (isDrawingElement)
            {
                var infoLabel = new System.Windows.Controls.TextBlock
                {
                    Text = "💡 Văn bản đã được nhận dạng từ nét vẽ. Chỉnh sửa nếu cần:",
                    FontSize = 12,
                    Foreground = new SolidColorBrush(Color.FromRgb(160, 200, 255)),
                    TextWrapping = TextWrapping.Wrap,
                    Margin = new Thickness(0, 0, 0, 8)
                };
                stackPanel.Children.Add(infoLabel);
            }

            // Current text label
            var label = new System.Windows.Controls.Label
            {
                Content = "Nội dung văn bản:",
                FontWeight = FontWeights.Bold,
                Foreground = Brushes.White,
                Margin = new Thickness(0, 0, 0, 5)
            };
            stackPanel.Children.Add(label);

            // Multi-line TextBox for editing
            var textBoxEdit = new System.Windows.Controls.TextBox
            {
                Text = currentText ?? "",
                MinHeight = 100,
                MaxHeight = 150,
                TextWrapping = TextWrapping.Wrap,
                AcceptsReturn = true,
                FontSize = 14,
                VerticalScrollBarVisibility = System.Windows.Controls.ScrollBarVisibility.Auto,
                Margin = new Thickness(0, 0, 0, 15)
            };
            stackPanel.Children.Add(textBoxEdit);

            // Buttons panel
            var buttonsPanel = new System.Windows.Controls.StackPanel
            {
                Orientation = System.Windows.Controls.Orientation.Horizontal,
                HorizontalAlignment = HorizontalAlignment.Right
            };

            var okButton = new System.Windows.Controls.Button
            {
                Content = "✅ Xác nhận",
                Width = 100,
                Height = 32,
                Margin = new Thickness(0, 0, 10, 0),
                IsDefault = true,
                Background = new SolidColorBrush(Color.FromRgb(37, 99, 235)),
                Foreground = Brushes.White,
                BorderThickness = new Thickness(0)
            };
            okButton.Click += (s, args) =>
            {
                editWindow.DialogResult = true;
                editWindow.Close();
            };

            var cancelButton = new System.Windows.Controls.Button
            {
                Content = "❌ Hủy",
                Width = 80,
                Height = 32,
                IsCancel = true
            };
            cancelButton.Click += (s, args) =>
            {
                editWindow.DialogResult = false;
                editWindow.Close();
            };

            buttonsPanel.Children.Add(okButton);
            buttonsPanel.Children.Add(cancelButton);
            stackPanel.Children.Add(buttonsPanel);

            editWindow.Content = stackPanel;

            // Show dialog and get result
            var dialogResult = editWindow.ShowDialog();

            if (dialogResult == true)
            {
                string newText = textBoxEdit.Text;

                if (isDrawingElement)
                {
                    // For drawing elements: replace stroke with TextBlock
                    ReplaceStrokeWithTextBlock(obj, newText);
                    System.Diagnostics.Debug.WriteLine($"✏️ Stroke → Edited text: '{newText}'");
                }
                else
                {
                    // For existing text elements: update text in-place
                    if (obj.Element is System.Windows.Controls.TextBlock tb)
                    {
                        tb.Text = newText;
                        obj.TextContent = newText;
                    }
                    else if (obj.Element is System.Windows.Controls.TextBox txb)
                    {
                        txb.Text = newText;
                        obj.TextContent = newText;
                    }
                    else if (obj.Element is System.Windows.Controls.Border brd)
                    {
                        var childTextBlock = FindVisualChild<System.Windows.Controls.TextBlock>(brd);
                        if (childTextBlock != null)
                        {
                            childTextBlock.Text = newText;
                            obj.TextContent = newText;
                        }
                    }

                    RecordModifyAction(obj.Element, currentText, newText, "Edit Text");
                    System.Diagnostics.Debug.WriteLine($"✏️ Edited text: '{currentText}' → '{newText}'");
                }
            }

            _moreMenu?.Hide();
        }

        /// <summary>
        /// Helper: Convert text to Title Case
        /// </summary>
        private string? ToTitleCase(string? text)
        {
            if (string.IsNullOrEmpty(text))
                return text;

            var textInfo = System.Globalization.CultureInfo.CurrentCulture.TextInfo;
            return textInfo.ToTitleCase(text.ToLower());
        }

