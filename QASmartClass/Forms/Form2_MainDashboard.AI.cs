                {
                    Text = textToSpeak,
                    Height = 80,
                    TextWrapping = TextWrapping.Wrap,
                    VerticalScrollBarVisibility = ScrollBarVisibility.Auto,
                    IsReadOnly = true,
                    Margin = new Thickness(0, 5, 0, 15)
                };
                stackPanel.Children.Add(textBox);

