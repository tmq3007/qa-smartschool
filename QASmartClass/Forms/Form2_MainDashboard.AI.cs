        /// <summary>
        /// Helper method to extract text from various object types
        /// </summary>
        private string? ExtractTextFromObject(SelectableObject obj)
        {
            if (obj == null || obj.Element == null)
                return null;

            // Extract from TextBlock
            if (obj.Element is TextBlock textBlock)
                return textBlock.Text;

            // Extract from TextBox
            if (obj.Element is TextBox textBox)
                return textBox.Text;

            // Extract from Border with TextBlock child
            if (obj.Element is Border border)
            {
                var childTextBlock = FindVisualChild<TextBlock>(border);
                if (childTextBlock != null)
                    return childTextBlock.Text;
            }

            // Fallback to stored TextContent
            if (!string.IsNullOrEmpty(obj.TextContent))
                return obj.TextContent;

            return null;
        }

