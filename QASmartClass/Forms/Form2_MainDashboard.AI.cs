        /// <summary>
        /// Làm sạch và tạo biến thể chuẩn hóa chữ số cho chuỗi nhận dạng OCR (ví dụ: "d 2345" -> "12345")
        /// </summary>
        private List<string> GenerateDigitSanitizedVariants(string raw)
        {
            var list = new List<string>();
            if (string.IsNullOrWhiteSpace(raw)) return list;

            string s = raw.Trim();
            list.Add(s);

            // 1. Sửa lỗi OCR hay đọc mỏ chéo của chữ số 1 thành chữ "d", "cl", "I", "l", "|" ở đầu chuỗi số
            if (System.Text.RegularExpressions.Regex.IsMatch(s, @"^(d|cl|I|l|\|)\s*\d+", System.Text.RegularExpressions.RegexOptions.IgnoreCase))
            {
                string fixedHead = System.Text.RegularExpressions.Regex.Replace(s, @"^(d|cl|I|l|\|)\s*", "1", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
                string fixedHeadNoSpaces = fixedHead.Replace(" ", "");
                list.Add(fixedHeadNoSpaces);
                list.Add(fixedHead);
            }

            // 2. Tự động tạo biến thể bỏ khoảng trắng cho toàn chuỗi chữ số (ví dụ: "1 2 3 4 5" -> "12345")
            string noSpaces = s.Replace(" ", "");
            if (noSpaces != s)
            {
                list.Add(noSpaces);
            }

            return list;
        }

        /// <summary>
        /// Tổng hợp danh sách tất cả các ứng viên nhận dạng chuỗi chữ từ 3 tầng (Google Vision + Windows OCR + Geometric String Fallback)
        /// </summary>
        private async System.Threading.Tasks.Task<List<HandwritingRecognitionResult>> AggregateAllCandidates(List<SelectableObject> targetObjects, Rect bounds)
        {
            var candidateList = new List<HandwritingRecognitionResult>();
            var seenTexts = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            var (bitmap, imageBytes) = CaptureStrokesAsBlackOnWhite(targetObjects, bounds);

            // 1. Phân tích chuỗi hình học từng nét/cụm nét trước tiên (Geometric String Clustering) -> Trả về "12345" & "1 2 3 4 5" chuẩn xác ở Rank 0
            if (targetObjects != null && targetObjects.Count > 0)
            {
                var clusters = ClusterDrawingObjects(targetObjects);
                var geomCharsWithSpaces = new List<string>();
                var geomCharsNoSpaces = new List<string>();

                foreach (var cluster in clusters)
                {
                    var gRes = RecognizeStrokeGeometryFallback(cluster[0]);
                    if (gRes.Count > 0 && !string.IsNullOrWhiteSpace(gRes[0].Text))
                    {
                        geomCharsWithSpaces.Add(gRes[0].Text);
                        geomCharsNoSpaces.Add(gRes[0].Text);
                    }
                }

                if (geomCharsNoSpaces.Count > 0)
                {
                    string joinedNoSpaces = string.Join("", geomCharsNoSpaces);
                    string joinedWithSpaces = string.Join(" ", geomCharsWithSpaces);

                    if (seenTexts.Add(joinedNoSpaces))
                    {
                        candidateList.Add(new HandwritingRecognitionResult
                        {
                            Text = joinedNoSpaces,
                            Confidence = 0.98f,
                            Rank = candidateList.Count,
                            DetectedLanguage = "en"
                        });
                    }

                    if (joinedWithSpaces != joinedNoSpaces && seenTexts.Add(joinedWithSpaces))
                    {
                        candidateList.Add(new HandwritingRecognitionResult
                        {
                            Text = joinedWithSpaces,
                            Confidence = 0.95f,
                            Rank = candidateList.Count,
                            DetectedLanguage = "en"
                        });
                    }

                    // Thêm các chuỗi con phổ biến (ví dụ: "1234", "2345")
                    if (geomCharsNoSpaces.Count >= 4)
                    {
                        string sub1 = string.Join("", geomCharsNoSpaces.Take(geomCharsNoSpaces.Count - 1));
                        string sub2 = string.Join("", geomCharsNoSpaces.Skip(1));
                        if (seenTexts.Add(sub1))
                        {
                            candidateList.Add(new HandwritingRecognitionResult { Text = sub1, Confidence = 0.90f, Rank = candidateList.Count, DetectedLanguage = "en" });
                        }
                        if (seenTexts.Add(sub2))
                        {
                            candidateList.Add(new HandwritingRecognitionResult { Text = sub2, Confidence = 0.88f, Rank = candidateList.Count, DetectedLanguage = "en" });
                        }
                    }
                }
            }

            // 2. Google Cloud Vision API (Nhận diện nguyên chuỗi chữ/số)
            if (_handwritingService != null && _handwritingService.IsInitialized && imageBytes != null)
            {
                try
                {
                    var gResults = await _handwritingService.RecognizeHandwritingAsync(imageBytes, 5);
                    if (gResults != null)
                    {
                        foreach (var res in gResults)
                        {
                            if (!string.IsNullOrWhiteSpace(res.Text))
                            {
                                var variants = GenerateDigitSanitizedVariants(res.Text);
                                foreach (var v in variants)
                                {
                                    if (seenTexts.Add(v))
                                    {
                                        candidateList.Add(new HandwritingRecognitionResult
                                        {
                                            Text = v,
                                            Confidence = res.Confidence,
                                            Rank = candidateList.Count,
                                            DetectedLanguage = res.DetectedLanguage
                                        });
                                    }
                                }
                            }
                        }
                    }
                }
                catch (Exception gEx)
                {
                    System.Diagnostics.Debug.WriteLine($"⚠️ Google Vision API error: {gEx.Message}");
                }
            }

            // 3. Windows Offline OCR Engine (Nhận diện nguyên chuỗi chữ/số)
            if (bitmap != null)
            {
                try
                {
                    if (_windowsOcrService == null)
                    {
                        _windowsOcrService = new WindowsOCRService();
                    }
                    var ocrRes = await _windowsOcrService.RecognizeTextAsync(bitmap);
                    if (ocrRes != null && ocrRes.IsSuccess && !string.IsNullOrWhiteSpace(ocrRes.Text))
                    {
                        var variants = GenerateDigitSanitizedVariants(ocrRes.Text);
                        foreach (var v in variants)
                        {
                            if (seenTexts.Add(v))
                            {
                                candidateList.Add(new HandwritingRecognitionResult
                                {
                                    Text = v,
                                    Confidence = 0.85f,
                                    Rank = candidateList.Count,
                                    DetectedLanguage = "en"
                                });
                            }
                        }
                    }
                }
                catch (Exception wEx)
                {
                    System.Diagnostics.Debug.WriteLine($"⚠️ Windows OCR error: {wEx.Message}");
                }
            }

            return candidateList;
        }

        private async System.Threading.Tasks.Task RecognizeAndReplaceWithText(List<SelectableObject> targetObjects, TextCaseMode caseMode)
        {
            if (targetObjects == null || targetObjects.Count == 0) return;

            Rect bounds = targetObjects.Count == 1
                ? targetObjects[0].Bounds
                : (_selectionManager?.GetMultiSelectionBounds() ?? targetObjects[0].Bounds);

            if (bounds.IsEmpty || bounds.Width <= 0 || bounds.Height <= 0) return;

            // 1. Tổng hợp danh sách ứng viên nhận diện tiềm năng từ 3 tầng
            var results = await AggregateAllCandidates(targetObjects, bounds);
            if (results == null || results.Count == 0) return;

            // 2. Mở HandwritingRecognitionDialog hiển thị danh sách ứng viên cho giáo viên chọn
            var dialog = new HandwritingRecognitionDialog
            {
                Owner = this
            };

            dialog.ShowResults(results);

            bool? dialogResult = dialog.ShowDialog();

            if (dialogResult == true || dialog.UserAccepted || dialog.SelectedResult != null)
            {
                var selectedCandidate = dialog.SelectedResult ?? results.FirstOrDefault();
                string? textToUse = selectedCandidate?.Text;

                if (!string.IsNullOrWhiteSpace(textToUse))
                {
                    string convertedText = ApplyTextCase(textToUse, caseMode);
                    ReplaceStrokesWithTextBlock(targetObjects, bounds, convertedText);
                    ShowSmartStatusBadge($"✅ Đã chèn chữ viết → '{convertedText}'");
                    return;
                }
            }
        }

        /// <summary>
        /// Capture nét vẽ của các đối tượng thành hình ảnh NÉT ĐEN TRÊN NỀN TRẮNG TINH KHIẾT (Black on White),
        /// loại bỏ hoàn toàn nền caro xanh, không dính viền chọn hay toolbar, tối ưu 100% cho các công cụ OCR.
        /// Tính toán chính xác tọa độ tuyệt đối của nét vẽ trên canvas.
        /// </summary>
        private (BitmapSource? bitmap, byte[]? bytes) CaptureStrokesAsBlackOnWhite(List<SelectableObject> targetObjects, Rect bounds)
        {
            if (targetObjects == null || targetObjects.Count == 0 || bounds.Width <= 0 || bounds.Height <= 0)
            {
                return (null, null);
            }

            try
            {
                double pad = 35;
                Rect paddedBounds = new Rect(
                    Math.Max(0, bounds.X - pad),
                    Math.Max(0, bounds.Y - pad),
                    bounds.Width + pad * 2,
                    bounds.Height + pad * 2);

                double maxDim = Math.Max(paddedBounds.Width, paddedBounds.Height);
                double scaleFactor = maxDim < 400.0 ? (400.0 / maxDim) : 1.0;

                int width = (int)(paddedBounds.Width * scaleFactor);
                int height = (int)(paddedBounds.Height * scaleFactor);

                var renderBitmap = new RenderTargetBitmap(
                    width,
                    height,
                    96 * scaleFactor,
                    96 * scaleFactor,
                    PixelFormats.Pbgra32);

                var drawingVisual = new DrawingVisual();
                using (var dc = drawingVisual.RenderOpen())
                {
                    // 1. Vẽ nền trắng tinh khiết (Pure White Background)
                    dc.DrawRectangle(Brushes.White, null, new Rect(0, 0, paddedBounds.Width, paddedBounds.Height));

                    // 2. Dịch chuyển tọa độ theo lề padding
                    dc.PushTransform(new TranslateTransform(-paddedBounds.X, -paddedBounds.Y));

                    // 3. Vẽ từng nét chữ bằng màu ĐEN đậm (Pure Black Ink) dựa trên tọa độ tuyệt đối
                    foreach (var obj in targetObjects)
                    {
                        if (obj.Element is Polyline polyline && polyline.Points.Count > 1)
                        {
                            double elemLeft = Canvas.GetLeft(polyline);
                            if (double.IsNaN(elemLeft)) elemLeft = 0;
                            double elemTop = Canvas.GetTop(polyline);
                            if (double.IsNaN(elemTop)) elemTop = 0;

                            var absPoints = polyline.Points.Select(p => new Point(p.X + elemLeft, p.Y + elemTop)).ToList();

                            var streamGeometry = new StreamGeometry();
                            using (var ctx = streamGeometry.Open())
                            {
                                ctx.BeginFigure(absPoints[0], false, false);
                                ctx.PolyLineTo(absPoints.Skip(1).ToList(), true, false);
                            }
                            streamGeometry.Freeze();

                            var pen = new Pen(Brushes.Black, Math.Max(polyline.StrokeThickness * 1.5, 5.0))
                            {
                                StartLineCap = PenLineCap.Round,
                                EndLineCap = PenLineCap.Round,
                                LineJoin = PenLineJoin.Round
                            };
                            dc.DrawGeometry(null, pen, streamGeometry);
                        }
                        else if (obj.Element is System.Windows.Shapes.Path pathElement && pathElement.Data != null)
                        {
                            double elemLeft = Canvas.GetLeft(pathElement);
                            if (double.IsNaN(elemLeft)) elemLeft = 0;
                            double elemTop = Canvas.GetTop(pathElement);
                            if (double.IsNaN(elemTop)) elemTop = 0;

                            dc.PushTransform(new TranslateTransform(elemLeft, elemTop));
                            var pen = new Pen(Brushes.Black, Math.Max(pathElement.StrokeThickness * 1.5, 5.0))
                            {
                                StartLineCap = PenLineCap.Round,
                                EndLineCap = PenLineCap.Round,
                                LineJoin = PenLineJoin.Round
                            };
                            dc.DrawGeometry(pathElement.Fill != null ? Brushes.Black : null, pen, pathElement.Data);
                            dc.Pop();
                        }
                        else if (obj.Element is System.Windows.Shapes.Shape shape)
                        {
                            var pen = new Pen(Brushes.Black, Math.Max(shape.StrokeThickness * 1.5, 5.0))
                            {
                                StartLineCap = PenLineCap.Round,
                                EndLineCap = PenLineCap.Round,
                                LineJoin = PenLineJoin.Round
                            };
                            dc.DrawRectangle(shape.Fill != null ? Brushes.Black : null, pen, obj.Bounds);
                        }
                        else if (obj.Element != null)
                        {
                            var vb = new VisualBrush(obj.Element) { Stretch = Stretch.None };
                            dc.DrawRectangle(vb, null, obj.Bounds);
                        }
                    }

                    dc.Pop();
                }

                renderBitmap.Render(drawingVisual);

                // Chuyển thành mảng byte PNG
                byte[] pngBytes;
                var encoder = new PngBitmapEncoder();
                encoder.Frames.Add(BitmapFrame.Create(renderBitmap));
                using (var ms = new System.IO.MemoryStream())
                {
                    encoder.Save(ms);
                    pngBytes = ms.ToArray();
                }

                return (renderBitmap, pngBytes);
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"❌ CaptureStrokesAsBlackOnWhite Error: {ex.Message}");
                return (null, null);
            }
        }

        /// <summary>
        /// Capture vùng được chọn một cách sạch vẽ: Tạm ẩn SelectionBox và ContextToolbar
        /// để ảnh chụp nét chữ hoàn toàn không chứa nét chấm đứt hay núm kéo điều hướng.
        /// Thêm lề (padding) 30px xung quanh để nét chữ không bị mép sát lề.
