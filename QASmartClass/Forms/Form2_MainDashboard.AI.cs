                    Width = 100,
                    Height = 35,
                    Margin = new Thickness(5)
                };
                speakButton.Click += (s, args) =>
                {
                    try
                    {
                        synthesizer.SpeakAsyncCancelAll();
                        
                        // Set voice
                        var selectedVoice = voiceCombo.SelectedItem as ComboBoxItem;
                        if (selectedVoice != null)
                        {
                            var voiceInfo = selectedVoice.Tag as System.Speech.Synthesis.VoiceInfo;
                            if (voiceInfo != null)
                                synthesizer.SelectVoice(voiceInfo.Name);
                        }
                        
                        // Set speed
                        synthesizer.Rate = (int)speedSlider.Value;
                        
                        // Speak
                        synthesizer.SpeakAsync(textToSpeak);
                        System.Diagnostics.Debug.WriteLine($"🔊 Speaking: '{textToSpeak}'");
                    }
                    catch (Exception ex)
                    {
                        MessageBox.Show($"Failed to speak: {ex.Message}", "Error");
