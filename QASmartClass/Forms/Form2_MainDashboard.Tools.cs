        /// <summary>
        /// Thực thi các tính năng Nhận diện thông minh (OCR, Dịch, Đọc, Tìm kiếm, AI Chat)
        /// Tự động xử lý khoanh vùng chọn khi chưa chọn đối tượng
        /// </summary>
        public async System.Threading.Tasks.Task ExecuteSmartActionAsync(SmartActionType actionType, string initialText = "")
        {
            try
            {
                string text = initialText;

                // Nếu chưa truyền text -> Lấy từ OCR các đối tượng đang chọn
                if (string.IsNullOrWhiteSpace(text))
                {
                    var selectedObjects = _selectionManager?.SelectedObjects;
                    if (selectedObjects == null || selectedObjects.Count == 0)
                    {
                        // Chưa có đối tượng chọn -> Đặt cờ pending action & bật chế độ kéo khoanh vùng Chữ nhật
                        _pendingSmartAction = actionType;
                        ActivateRectangleSelectionMode();

                        string actionPrompt = actionType switch
                        {
                            SmartActionType.Translate => "🔤 Hãy khoanh vùng chữ viết trên bảng để DỊCH VĂN BẢN",
                            SmartActionType.Read => "🔊 Hãy khoanh vùng chữ viết trên bảng để ĐỌC VĂN BẢN",
                            SmartActionType.Search => "🔍 Hãy khoanh vùng chữ viết trên bảng để TÌM KIẾM GOOGLE",
                            SmartActionType.AIChat => "🤖 Hãy khoanh vùng chữ viết trên bảng để HỎI AI CHAT",
                            _ => "📝 Hãy khoanh vùng chữ viết trên bảng để NHẬN DIỆN OCR"
                        };
                        ShowSmartStatusBadge(actionPrompt);
                        return;
                    }

                    text = await PerformOCRAsync();
                }

                if (string.IsNullOrWhiteSpace(text))
                {
                    ShowSmartStatusBadge("⚠️ Không tìm thấy văn bản hợp lệ để xử lý");
                    return;
                }

                // Thực hiện tính năng theo actionType
                switch (actionType)
                {
                    case SmartActionType.OCR:
                        {
                            try { Clipboard.SetText(text); } catch { }
                            var result = MessageBox.Show(
                                $"☑ Nhận diện chữ (OCR) thành công:\n\n\"{text.Trim()}\"\n\n(Đã sao chép vào bộ nhớ tạm)\n\nBạn có muốn CHÈN THẺ CHỮ IN NÀY LÊN BẢNG không?",
                                "Nhận diện chữ OCR - SMART TOUCH",
                                MessageBoxButton.YesNo,
                                MessageBoxImage.Information);

                            if (result == MessageBoxResult.Yes)
                            {
                                InsertTextFromOCR(text);
                            }
                        }
                        break;

                    case SmartActionType.Translate:
                        {
                            if (string.IsNullOrWhiteSpace(text) || text.Length < 2)
                            {
                                ShowSmartStatusBadge("⚠️ Vui lòng khoanh chọn văn bản hợp lệ để dịch.");
                                return;
                            }

                            bool isOnline = System.Net.NetworkInformation.NetworkInterface.GetIsNetworkAvailable();
                            if (isOnline)
                            {
                                var bingTranslator = new Form2_24_BingTranslator(text)
                                {
                                    Owner = this
                                };
                                bingTranslator.Show();
                                ShowSmartStatusBadge($"🌐 Đã mở công cụ Dịch văn bản cho: \"{text.Trim()}\"");
                            }
                            else
                            {
                                string offlineResult = QASmartTouch.Services.VocabularyService.LookupOffline(text);
                                ShowSmartStatusBadge($"📖 Tra từ điển Offline: \"{text}\" -> \"{offlineResult}\"");
                                MessageBox.Show($"📖 Kết quả Dịch thuật Offline:\n\nTừ gốc: {text}\nBản dịch: {offlineResult}", "Dịch thuật Offline - SMART TOUCH", MessageBoxButton.OK, MessageBoxImage.Information);
                            }
                        }
                        break;

                    case SmartActionType.Read:
                        {
                            if (string.IsNullOrWhiteSpace(text) || text.Length < 2)
                            {
                                ShowSmartStatusBadge("⚠️ Vui lòng khoanh chọn văn bản hợp lệ để phát âm.");
                                return;
                            }

                            if (_speechService == null)
                            {
                                _speechService = new QASmartTouch.Services.SpeechSynthesizerService();
                            }

                            string cleanText = text.Trim();
                            _speechService.SpeakText(cleanText);
                            ShowSmartStatusBadge($"🔊 Đang phát âm văn bản: \"{cleanText}\"");
                        }
                        break;

                    case SmartActionType.Search:
                        {
                            if (string.IsNullOrWhiteSpace(text) || text.Length < 2)
                            {
                                ShowSmartStatusBadge("⚠️ Vui lòng khoanh chọn từ khóa hợp lệ để tìm kiếm.");
                                return;
                            }

                            bool isOnline = System.Net.NetworkInformation.NetworkInterface.GetIsNetworkAvailable();
                            if (isOnline)
                            {
                                try
                                {
                                    var searchBrowser = new Form2_26_GoogleSearchBrowser
                                    {
                                        Owner = this
                                    };
                                    searchBrowser.Show();

                                    string encoded = Uri.EscapeDataString(text.Trim());
                                    searchBrowser.webView.Source = new Uri($"https://www.google.com/search?q={encoded}");

                                    ShowSmartStatusBadge($"🔍 Đang tìm kiếm Google nhúng cho: \"{text.Trim()}\"");
                                }
                                catch (Exception ex)
                                {
                                    ShowSmartStatusBadge($"❌ Không thể mở trình duyệt nhúng: {ex.Message}");
                                }
                            }
                            else
                            {
                                string offlineResult = QASmartTouch.Services.VocabularyService.LookupOffline(text);
                                ShowSmartStatusBadge($"📖 Trụ sở Mạng Offline - Tra từ điển tri thức: \"{text.Trim()}\"");
                                MessageBox.Show($"📖 Kết quả Tra cứu Tri thức Offline:\n\nTừ khóa: {text}\nThông tin tra cứu: {offlineResult}", "Tra cứu Tri thức Offline - SMART TOUCH", MessageBoxButton.OK, MessageBoxImage.Information);
                            }
                        }
                        break;

                    case SmartActionType.AIChat:
                        {
                            var askAI = new AskAIWindow(text);
                            WindowHelper.ShowChildDialog(askAI, this);
                            ShowSmartStatusBadge($"🤖 Đã mở Trợ lý AI cho văn bản: \"{text.Trim()}\"");
                        }
                        break;
                }
            }
            catch (Exception ex)
            {
                ShowSmartStatusBadge($"❌ Lỗi xử lý nhận diện thông minh: {ex.Message}");
            }
        }

