        private void btn10_WindowMode_Click(object sender, RoutedEventArgs e)
        {
            var button = sender as Button;
            
            // Toggle: If window mode is active, exit it
            if (_isWindowMode)
            {
                _windowModeController?.ExitWindowMode();
                
                // Reset button appearance
                if (button != null)
                {
                    button.Background = new SolidColorBrush(Color.FromRgb(241, 242, 246)); // #F1F2F6
                }
                
                _selectedTool = null;
                return;
            }
            
            // ✅ PHASE 2: Close submenus before entering window mode
            CloseAllSubmenus();
            
            SelectTool(button);
            
            // Enter Window Mode using controller
            _isWindowMode = true;
            _windowModeController?.EnterWindowMode();
        }

