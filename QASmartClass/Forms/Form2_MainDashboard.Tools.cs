        /// <summary>
        /// [QC_4.2_TOUCH_ZOOM_AREA] Xử lý multi-touch gesture trên overlay:
        /// - 1 ngón tay: Translation (kéo di chuyển overlay)
        /// - 2 ngón tay: Pinch-to-Zoom (phóng to/thu nhỏ overlay)
        /// </summary>
        private void ZoomAreaOverlay_ManipulationDelta(object sender, ManipulationDeltaEventArgs e)
        {
            if (_zoomAreaOverlay == null) return;

            // --- 1-finger: Translation (kéo di chuyển) ---
            double tx = e.DeltaManipulation.Translation.X;
            double ty = e.DeltaManipulation.Translation.Y;

            if (Math.Abs(tx) > 0.5 || Math.Abs(ty) > 0.5)
            {
                double curLeft = Canvas.GetLeft(_zoomAreaOverlay);
                double curTop = Canvas.GetTop(_zoomAreaOverlay);

                // Bảo vệ NaN nếu Canvas.Left/Top chưa được set
                if (double.IsNaN(curLeft)) curLeft = 0;
                if (double.IsNaN(curTop)) curTop = 0;

                Canvas.SetLeft(_zoomAreaOverlay, curLeft + tx);
                Canvas.SetTop(_zoomAreaOverlay, curTop + ty);

                System.Diagnostics.Debug.WriteLine($"👆 Touch dragging overlay to ({curLeft + tx:F0}, {curTop + ty:F0})");
            }

            // --- 2-finger: Pinch-to-Zoom ---
            double scaleFactor = (e.DeltaManipulation.Scale.X + e.DeltaManipulation.Scale.Y) / 2.0;

            if (scaleFactor != 1.0 && scaleFactor > 0.1 && scaleFactor < 5.0)
            {
                _zoomAreaOverlayScale *= scaleFactor;
                _zoomAreaOverlayScale = Math.Clamp(_zoomAreaOverlayScale, 0.5, 3.0);

                ApplyZoomAreaOverlayScale();

                System.Diagnostics.Debug.WriteLine($"🔍 Touch pinch overlay scale: {_zoomAreaOverlayScale:F2}x");
            }

            e.Handled = true;
        }

