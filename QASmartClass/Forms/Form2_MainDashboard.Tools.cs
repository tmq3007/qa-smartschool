        }

        public async System.Threading.Tasks.Task<string> PerformOCRAsync(Rect? customBounds = null)
        {
            try
            {
                if (_selectionManager == null) return string.Empty;

                var selectedObjects = _selectionManager.SelectedObjects;
                string searchText = string.Empty;
                Rect bounds = Rect.Empty;

                if (selectedObjects != null && selectedObjects.Count > 0)
                {
                    // 1. Thử trích xuất text trực tiếp (đối với TextBlock/TextBox)
                    foreach (var obj in selectedObjects)
                    {
                        string? text = ExtractTextFromObject(obj);
                        if (!string.IsNullOrWhiteSpace(text))
                        {
                            searchText += text + " ";
                        }
                        bounds.Union(obj.Bounds);
                    }
                    searchText = searchText.Trim();
                }

                // Nếu chưa có bounds từ selectedObjects, kiểm tra customBounds hoặc vùng kéo chữ nhật gần nhất
                if (bounds.IsEmpty || bounds.Width <= 0 || bounds.Height <= 0)
                {
                    if (customBounds.HasValue && customBounds.Value.Width > 5 && customBounds.Value.Height > 5)
                    {
                        bounds = customBounds.Value;
                    }
                    else if (!_lastDraggedSelectionRect.IsEmpty && _lastDraggedSelectionRect.Width > 5 && _lastDraggedSelectionRect.Height > 5)
                    {
                        bounds = _lastDraggedSelectionRect;
                    }
                }

                // 2. Nếu không có text trực tiếp (nét vẽ tay Polyline/Hình ảnh/vùng canvas) -> Dùng Windows OCR Offline
                if (string.IsNullOrWhiteSpace(searchText) && !bounds.IsEmpty && bounds.Width > 5 && bounds.Height > 5)
                {
                    System.Diagnostics.Debug.WriteLine($"Attempting offline Windows OCR for bounds ({bounds.X:F0},{bounds.Y:F0},{bounds.Width:F0},{bounds.Height:F0})...");
                    if (_windowsOcrService == null)
                    {
                        _windowsOcrService = new WindowsOCRService();
                    }
                    if (_captureService == null)
                    {
                        _captureService = new SelectionCaptureService();
                    }

                    bounds.Inflate(15, 15);
                    double maxW = Math.Max(MainInteractiveBoard.ActualWidth, 1000);
                    double maxH = Math.Max(MainInteractiveBoard.ActualHeight, 1000);
                    bounds.Intersect(new Rect(0, 0, maxW, maxH));

                    if (bounds.Width > 5 && bounds.Height > 5)
                    {
                        var bitmap = _captureService.CaptureSelectionAreaAsBitmap(bounds, MainInteractiveBoard);
                        var ocrRes = await _windowsOcrService.RecognizeTextAsync(bitmap);
                        if (ocrRes != null && ocrRes.IsSuccess)
                        {
                            searchText = ocrRes.Text;
                        }
                        else
                        {
                            ShowSmartStatusBadge($"⚠️ {ocrRes?.ErrorMessage ?? "Không tìm thấy chữ trong vùng chọn."}");
                            return string.Empty;
                        }
                    }
                }

                if (!string.IsNullOrWhiteSpace(searchText))
                {
                    ShowSmartStatusBadge($"☑ Nhận diện OCR thành công: \"{searchText.Trim()}\"");
                }
                else
                {
                    ShowSmartStatusBadge("⚠️ Không tìm thấy chữ viết rõ ràng trong vùng được chọn");
                }

                return searchText ?? string.Empty;
            }
            catch (Exception ex)
            {
                ShowSmartStatusBadge($"❌ Lỗi nhận diện OCR: {ex.Message}");
                return string.Empty;
            }
        }

