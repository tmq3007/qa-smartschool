            if (_activeSubMenu != null && _activeSubMenuButton == button)
            {
                CloseActiveSubMenu();
                return;
            }

            // Preserving active selection when opening selection/recognition submenu
            bool hasSelection = _selectionManager != null && _selectionManager.SelectedObjects.Count > 0;
            if (hasSelection)
            {
                CloseActiveSubMenu();
                if (_selectedTool != null && _selectedTool != button)
                {
                    _selectedTool.Background = new SolidColorBrush((Color)ColorConverter.ConvertFromString("#F1F2F6"));
                }
                _selectedTool = button;
                _selectedTool.Background = new SolidColorBrush((Color)ColorConverter.ConvertFromString("#2E86DE"));
                UpdateIconColor(_selectedTool, Colors.White);
            }
            else
            {
                SelectTool(button);
            }

            HideWelcomeState();

            var selectionMenu = new Form2_6_SubMenuSelectionRecognition(this);
            selectionMenu.Owner = this;
            _activeSubMenu = selectionMenu;
            _activeSubMenuButton = button;

            var windowPosition = this.PointToScreen(new Point(0, 0));
            var windowWidth = this.ActualWidth;
            var windowHeight = this.ActualHeight;
            var toolbarHeight = 80;

            selectionMenu.Left = windowPosition.X + (windowWidth - selectionMenu.Width) / 2;
            selectionMenu.Top = windowPosition.Y + windowHeight - toolbarHeight - selectionMenu.Height - 10;

            selectionMenu.Closed += (s, args) =>
            {
                try
                {
                    this.Activate();
                    this.Focus();
                    MainInteractiveBoard.Focus();
                }
                catch { }

                if (ReferenceEquals(_activeSubMenu, selectionMenu))
                {
                    _activeSubMenu = null;
                    _activeSubMenuButton = null;

                    if (button != null)
                    {
                        button.Background = new SolidColorBrush(Color.FromRgb(241, 242, 246)); // #F1F2F6
                        UpdateIconColor(button, Color.FromRgb(0x2F, 0x35, 0x42));
                    }
                    _selectedTool = null;
                }
            };

            selectionMenu.Show();
            try { selectionMenu.Activate(); } catch { }
        }

        /// <summary>
        /// Chèn văn bản nhận diện từ OCR lên bảng dưới dạng thẻ chữ in đẹp
        /// </summary>
        public void InsertTextFromOCR(string text)
        {
            if (string.IsNullOrWhiteSpace(text)) return;

            Point pos = new Point(300, 200);
            var selectedObjects = _selectionManager?.SelectedObjects;
            if (selectedObjects != null && selectedObjects.Count > 0)
            {
                var first = selectedObjects[0];
                pos = new Point(first.Position.X, first.Position.Y);
            }

            var textBlock = new TextBlock
            {
                Text = text,
                FontFamily = new System.Windows.Media.FontFamily("Inter, Outfit, Segoe UI"),
                FontSize = 24,
                FontWeight = FontWeights.Medium,
                Foreground = new SolidColorBrush(Color.FromRgb(47, 53, 66)),
                TextWrapping = TextWrapping.Wrap,
                Padding = new Thickness(10, 5, 10, 5)
            };

            var border = new Border
            {
                Child = textBlock,
                Background = new SolidColorBrush(Color.FromArgb(240, 255, 255, 255)),
                BorderBrush = new SolidColorBrush(Color.FromRgb(46, 134, 222)),
                BorderThickness = new Thickness(2),
                CornerRadius = new CornerRadius(10),
                Padding = new Thickness(5),
                Effect = new System.Windows.Media.Effects.DropShadowEffect
                {
                    Color = Colors.Black,
                    Direction = 270,
                    ShadowDepth = 2,
                    BlurRadius = 8,
                    Opacity = 0.2
                }
            };

            Canvas.SetLeft(border, pos.X);
            Canvas.SetTop(border, pos.Y);
            Canvas.SetZIndex(border, 1000);

            MainInteractiveBoard.Children.Add(border);
            RecordAddAction(border, "OCRText");
            RefreshSelectableObjects();

            ShowSmartStatusBadge("📝 Đã chèn chữ nhận diện OCR lên bảng thành công!");
        }

