        /// <summary>
        /// Apply zoom to canvas based on mode
        /// </summary>
        private void ApplyZoom(string mode, double level)
        {
            System.Diagnostics.Debug.WriteLine($"🔍 Applying Zoom: Mode={mode}, Level={level}, Current={_currentZoomLevel}x");
            
            double newZoomLevel = _currentZoomLevel;
            
            switch (mode)
            {
                case "Fixed":
                    // Set zoom to exact level (1x = reset to 100%, 2x = 200%, etc.)
                    newZoomLevel = level;
                    System.Diagnostics.Debug.WriteLine($"📌 Fixed zoom to {newZoomLevel}x");
                    break;
                    
                case "Increment":
                    // Increase zoom by level amount (e.g., +0.25)
                    newZoomLevel = _currentZoomLevel + level;
                    // Limit max zoom to 4x
                    if (newZoomLevel > 4.0)
                        newZoomLevel = 4.0;
                    System.Diagnostics.Debug.WriteLine($"➕ Increment zoom: {_currentZoomLevel}x → {newZoomLevel}x");
                    break;
                    
                case "Decrement":
                    // Decrease zoom by level amount (e.g., -0.25)
                    newZoomLevel = _currentZoomLevel - level;
                    // Limit min zoom to 0.5x
                    if (newZoomLevel < 0.5)
                        newZoomLevel = 0.5;
                    System.Diagnostics.Debug.WriteLine($"➖ Decrement zoom: {_currentZoomLevel}x → {newZoomLevel}x");
                    break;
                    
                case "Area":
                    // Enable area selection mode for zooming
                    EnableZoomAreaSelectionMode();
                    System.Diagnostics.Debug.WriteLine("🎯 Zoom Area Selection mode enabled");
                    return; // Exit early, no zoom applied yet
            }
            
            // Apply the new zoom level
            _currentZoomLevel = newZoomLevel;
            
            // If zoom level is 1.0, reset both transforms to original state
            if (Math.Abs(_currentZoomLevel - 1.0) < 0.001)
            {
                MainInteractiveBoard.LayoutTransform = null;
                MainInteractiveBoard.RenderTransform = null;
                _panTransform = null;
                
                // Reset canvas size to auto
                MainInteractiveBoard.Width = double.NaN;
                MainInteractiveBoard.Height = double.NaN;
                
                MainInteractiveBoard.Cursor = Cursors.Arrow;
                System.Diagnostics.Debug.WriteLine($"✅ Canvas RESET to original view (1x) - All transforms cleared");
            }
            else
            {
                // Get current canvas actual size
                double canvasWidth = MainInteractiveBoard.ActualWidth;
                double canvasHeight = MainInteractiveBoard.ActualHeight;
                
                // Set canvas size explicitly for proper zoom behavior
                if (double.IsNaN(MainInteractiveBoard.Width))
                {
                    MainInteractiveBoard.Width = canvasWidth;
                    MainInteractiveBoard.Height = canvasHeight;
                }
                
                // Create transform group with scale and translate
                var transformGroup = new TransformGroup();
                
                // Scale transform (zoom)
                var scaleTransform = new ScaleTransform(_currentZoomLevel, _currentZoomLevel);
                transformGroup.Children.Add(scaleTransform);
                
                // Translate transform (pan) - initialize at (0, 0)
                _panTransform = new TranslateTransform(0, 0);
                transformGroup.Children.Add(_panTransform);
                
                // Apply combined transform to RenderTransform (better quality than LayoutTransform)
                MainInteractiveBoard.RenderTransform = transformGroup;
                
                // Update RenderTransformOrigin to center (0.5, 0.5) for better zoom experience
                MainInteractiveBoard.RenderTransformOrigin = new Point(0.5, 0.5);
                
                // Change cursor to indicate panning is available
                MainInteractiveBoard.Cursor = Cursors.Hand;
                
                System.Diagnostics.Debug.WriteLine($"✅ Canvas zoomed to {_currentZoomLevel}x (High Quality DPI)");
                System.Diagnostics.Debug.WriteLine($"👆 You can now drag canvas to pan (Press 1x to reset)");
            }

            // Đồng bộ hiển thị % Zoom lên HUD
            UpdateZoomHudDisplay();
        }

