        /// <summary>
        /// Zoom to specific area of canvas
        /// </summary>
        private void ZoomToArea(double left, double top, double width, double height)
        {
            // Create HIGH DPI snapshot by capturing the entire canvas first
            // Use 2x DPI (192) for better quality when zooming
            var highDPI = 192.0;
            var scaleFactor = highDPI / 96.0; // 2.0
            
            var fullCanvasSnapshot = new RenderTargetBitmap(
                (int)(MainInteractiveBoard.ActualWidth * scaleFactor),
                (int)(MainInteractiveBoard.ActualHeight * scaleFactor),
                highDPI, highDPI,
                PixelFormats.Pbgra32);
            
            // Apply scale transform to canvas for high DPI rendering
            var originalTransform = MainInteractiveBoard.LayoutTransform;
            MainInteractiveBoard.LayoutTransform = new ScaleTransform(scaleFactor, scaleFactor);
            
            // Render entire canvas to bitmap with high DPI
            fullCanvasSnapshot.Render(MainInteractiveBoard);
            
            // Restore original transform
            MainInteractiveBoard.LayoutTransform = originalTransform;
            
            // Create cropped bitmap for selected area (use original coordinates, bitmap is already scaled)
            var croppedBitmap = new CroppedBitmap(fullCanvasSnapshot, 
                new Int32Rect(
                    (int)(left * scaleFactor), 
                    (int)(top * scaleFactor), 
                    (int)(width * scaleFactor), 
                    (int)(height * scaleFactor)
                ));
            
            // Store the cropped bitmap directly as our snapshot
            _zoomAreaSnapshot = croppedBitmap;
            
            // Create overlay with snapshot and controls
            CreateZoomAreaOverlay(left, top, width, height);
            
            System.Diagnostics.Debug.WriteLine($"✅ Created HIGH DPI zoom area overlay at ({left:F0}, {top:F0}) size {width:F0}x{height:F0} (DPI: {highDPI})");
        }
        
