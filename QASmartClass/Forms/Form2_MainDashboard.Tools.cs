        }
        
        /// <summary>
        /// Drag overlay to new position
        /// </summary>
        private void ZoomAreaOverlay_MouseMove(object sender, MouseEventArgs e)
        {
            if (_isDraggingOverlay && e.LeftButton == MouseButtonState.Pressed && _zoomAreaOverlay != null)
            {
                Point currentPoint = e.GetPosition(MainInteractiveBoard);
                double deltaX = currentPoint.X - _overlayDragStartPoint.X;
                double deltaY = currentPoint.Y - _overlayDragStartPoint.Y;
                
                // Get current position
                double currentLeft = Canvas.GetLeft(_zoomAreaOverlay);
                double currentTop = Canvas.GetTop(_zoomAreaOverlay);
                
                // Apply new position
                Canvas.SetLeft(_zoomAreaOverlay, currentLeft + deltaX);
                Canvas.SetTop(_zoomAreaOverlay, currentTop + deltaY);
                
                _overlayDragStartPoint = currentPoint;
                
                System.Diagnostics.Debug.WriteLine($"📍 Dragging overlay to ({currentLeft + deltaX:F0}, {currentTop + deltaY:F0})");
                e.Handled = true;
            }
        }
        
        /// <summary>
        /// End dragging overlay
        /// </summary>
        private void ZoomAreaOverlay_MouseUp(object sender, MouseButtonEventArgs e)
        {
            if (_isDraggingOverlay)
            {
                _isDraggingOverlay = false;
                
                if (_zoomAreaOverlay is UIElement element)
                {
                    element.ReleaseMouseCapture();
                }
                
                System.Diagnostics.Debug.WriteLine("✅ Finished dragging zoom overlay");
                e.Handled = true;
            }
        }

