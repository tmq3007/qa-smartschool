        {
            _isWindowMode = false;
            
            // Reset button appearance
            if (btn10_WindowMode != null)
            {
                btn10_WindowMode.Background = new SolidColorBrush(Color.FromRgb(241, 242, 246)); // #F1F2F6
                UpdateIconColor(btn10_WindowMode, Color.FromRgb(0x2F, 0x35, 0x42)); // default path fill #2F3542
            }
            
            if (_selectedTool == btn10_WindowMode)
            {
                _selectedTool = null;
            }
        }

