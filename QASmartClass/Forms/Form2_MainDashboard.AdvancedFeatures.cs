                    dashArray == null ? "Solid" : string.Join(",", dashArray), "Change stroke style");
            }
        }

        /// <summary>
        /// Sprint 5 Module 5.3: Align selected objects
        /// </summary>
        private void AlignObjects(string alignment)
        {
            System.Diagnostics.Debug.WriteLine($"📐 Align {alignment} clicked");

            try
            {
                var selectedObjects = _selectionManager?.SelectedObjects;
                
                if (selectedObjects == null || selectedObjects.Count < 2)
                {
                    MessageBox.Show(
                        "Please select at least 2 objects to align.",
                        "Align Objects",
                        MessageBoxButton.OK,
                        MessageBoxImage.Information
                    );
                    return;
                }

                double referenceValue = 0;

                switch (alignment.ToLower())
                {
                    case "left":
                        referenceValue = selectedObjects.Min(o => o.Position.X);
                        foreach (var obj in selectedObjects)
                        {
                            Canvas.SetLeft(obj.Element, referenceValue);
                            obj.Position = new Point(referenceValue, obj.Position.Y);
                            obj.UpdateBounds();
                        }
                        break;

                    case "center":
                        double minX = selectedObjects.Min(o => o.Position.X);
                        double maxX = selectedObjects.Max(o => o.Position.X + o.Size.Width);
                        referenceValue = (minX + maxX) / 2;
                        foreach (var obj in selectedObjects)
                        {
                            double newX = referenceValue - (obj.Size.Width / 2);
                            Canvas.SetLeft(obj.Element, newX);
                            obj.Position = new Point(newX, obj.Position.Y);
                            obj.UpdateBounds();
                        }
                        break;

                    case "right":
                        referenceValue = selectedObjects.Max(o => o.Position.X + o.Size.Width);
                        foreach (var obj in selectedObjects)
                        {
                            double newX = referenceValue - obj.Size.Width;
                            Canvas.SetLeft(obj.Element, newX);
                            obj.Position = new Point(newX, obj.Position.Y);
                            obj.UpdateBounds();
                        }
                        break;

                    case "top":
                        referenceValue = selectedObjects.Min(o => o.Position.Y);
                        foreach (var obj in selectedObjects)
                        {
                            Canvas.SetTop(obj.Element, referenceValue);
                            obj.Position = new Point(obj.Position.X, referenceValue);
                            obj.UpdateBounds();
                        }
                        break;

                    case "middle":
                        double minY = selectedObjects.Min(o => o.Position.Y);
                        double maxY = selectedObjects.Max(o => o.Position.Y + o.Size.Height);
                        referenceValue = (minY + maxY) / 2;
                        foreach (var obj in selectedObjects)
                        {
                            double newY = referenceValue - (obj.Size.Height / 2);
                            Canvas.SetTop(obj.Element, newY);
                            obj.Position = new Point(obj.Position.X, newY);
                            obj.UpdateBounds();
                        }
                        break;

                    case "bottom":
                        referenceValue = selectedObjects.Max(o => o.Position.Y + o.Size.Height);
                        foreach (var obj in selectedObjects)
                        {
                            double newY = referenceValue - obj.Size.Height;
                            Canvas.SetTop(obj.Element, newY);
                            obj.Position = new Point(obj.Position.X, newY);
                            obj.UpdateBounds();
                        }
                        break;
                }

                System.Diagnostics.Debug.WriteLine($"📐 Aligned {selectedObjects.Count} objects to {alignment}");
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"❌ Align Error: {ex.Message}");
                MessageBox.Show($"Failed to align objects: {ex.Message}", "Error", 
                    MessageBoxButton.OK, MessageBoxImage.Error);
            }
        }

        /// <summary>
        /// Sprint 5 Module 5.4: Apply same property to all selected objects
        /// </summary>
        private void ApplyToAllSelected(string property, object value)
        {
            System.Diagnostics.Debug.WriteLine($"🎨 Apply {property} to all selected");

            try
            {
                var selectedObjects = _selectionManager?.SelectedObjects;
                
                if (selectedObjects == null || selectedObjects.Count == 0)
                {
                    MessageBox.Show(
                        "Please select objects first.",
                        "Batch Operation",
                        MessageBoxButton.OK,
                        MessageBoxImage.Information
                    );
                    return;
                }

                int appliedCount = 0;

                foreach (var obj in selectedObjects)
                {
                    if (obj.Element == null) continue;

                    switch (property.ToLower())
                    {
                        case "color":
                            if (value is Color color)
                            {
                                obj.StrokeColor = color;
                                
                                if (obj.Element is System.Windows.Shapes.Shape shape)
                                {
                                    shape.Stroke = new SolidColorBrush(color);
                                    appliedCount++;
                                }
                                else if (obj.Element is Border border)
                                {
                                    border.BorderBrush = new SolidColorBrush(color);
                                    appliedCount++;
                                }
                            }
                            break;

                        case "thickness":
                            if (value is double thickness)
                            {
                                obj.StrokeThickness = thickness;
                                
                                if (obj.Element is System.Windows.Shapes.Shape shape)
                                {
                                    shape.StrokeThickness = thickness;
                                    appliedCount++;
                                }
                                else if (obj.Element is Border border)
                                {
                                    border.BorderThickness = new Thickness(thickness);
                                    appliedCount++;
                                }
                                else if (obj.Element is System.Windows.Shapes.Polyline polyline)
                                {
                                    polyline.StrokeThickness = thickness;
                                    appliedCount++;
                                }
                            }
                            break;

                        case "rotation":
                            if (value is double angle)
                            {
                                obj.RotationAngle = angle;
                                
                                var rotateTransform = new RotateTransform(angle, 
                                    obj.Size.Width / 2, obj.Size.Height / 2);
                                obj.Element.RenderTransform = rotateTransform;
                                appliedCount++;
                            }
                            break;
                    }
                }

                System.Diagnostics.Debug.WriteLine($"🎨 Applied {property} to {appliedCount}/{selectedObjects.Count} objects");
                
                if (appliedCount > 0)
                {
                    MessageBox.Show(
                        $"Successfully applied {property} to {appliedCount} object(s)!",
                        "Batch Operation Complete",
                        MessageBoxButton.OK,
                        MessageBoxImage.Information
                    );
                }
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"❌ Batch Operation Error: {ex.Message}");
                MessageBox.Show($"Failed to apply batch operation: {ex.Message}", "Error", 
                    MessageBoxButton.OK, MessageBoxImage.Error);
            }
        }

