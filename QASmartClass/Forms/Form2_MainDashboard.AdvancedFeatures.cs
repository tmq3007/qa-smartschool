        /// <summary>
        /// Apply dash style to a shape / stroke element
        /// </summary>
        private void ApplyStrokeDashStyle(SelectableObject obj, DoubleCollection? dashArray)
        {
            if (obj.Element is System.Windows.Shapes.Shape shape)
            {
                shape.StrokeDashArray = dashArray ?? new DoubleCollection();
