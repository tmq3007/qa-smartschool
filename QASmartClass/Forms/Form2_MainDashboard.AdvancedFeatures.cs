        /// <summary>
        /// Xuất thành ảnh — render selected object(s) to PNG
        /// </summary>
        private void OnMoreMenuExportImage(object? sender, EventArgs e)
        {
            System.Diagnostics.Debug.WriteLine("💾 Export Image clicked");
            var obj = _selectionManager?.SelectedObject;
            if (obj?.Element == null)
            {
                _moreMenu?.Hide();
                return;
            }

            try
            {
                var element = obj.Element as FrameworkElement;
                if (element == null) return;

                // Render element to bitmap
                var bounds = obj.Bounds;
                double dpi = 192; // 2x for high quality
                int width = (int)(bounds.Width * dpi / 96);
                int height = (int)(bounds.Height * dpi / 96);
                if (width <= 0 || height <= 0) return;

                var renderBitmap = new System.Windows.Media.Imaging.RenderTargetBitmap(
                    width, height, dpi, dpi, PixelFormats.Pbgra32);

                // Create a visual brush of the element
                var drawingVisual = new DrawingVisual();
                using (var dc = drawingVisual.RenderOpen())
                {
                    var visualBrush = new VisualBrush(element);
                    dc.DrawRectangle(visualBrush, null, new Rect(0, 0, bounds.Width, bounds.Height));
                }
                renderBitmap.Render(drawingVisual);

                // Save dialog
                var saveDialog = new Microsoft.Win32.SaveFileDialog
                {
                    Title = "Xuất thành ảnh",
                    Filter = "PNG Image|*.png|JPEG Image|*.jpg|BMP Image|*.bmp",
                    DefaultExt = ".png",
                    FileName = $"Export_{DateTime.Now:yyyyMMdd_HHmmss}"
                };

                if (saveDialog.ShowDialog() == true)
                {
                    System.Windows.Media.Imaging.BitmapEncoder encoder;
                    string ext = System.IO.Path.GetExtension(saveDialog.FileName).ToLower();
                    switch (ext)
                    {
                        case ".jpg":
                        case ".jpeg":
                            encoder = new System.Windows.Media.Imaging.JpegBitmapEncoder { QualityLevel = 95 };
                            break;
                        case ".bmp":
                            encoder = new System.Windows.Media.Imaging.BmpBitmapEncoder();
                            break;
                        default:
                            encoder = new System.Windows.Media.Imaging.PngBitmapEncoder();
                            break;
                    }
                    encoder.Frames.Add(System.Windows.Media.Imaging.BitmapFrame.Create(renderBitmap));

                    using (var fs = System.IO.File.Create(saveDialog.FileName))
                    {
                        encoder.Save(fs);
                    }

                    System.Diagnostics.Debug.WriteLine($"💾 Exported to: {saveDialog.FileName}");
                    MessageBox.Show($"Đã xuất thành công!\n\n📁 {saveDialog.FileName}",
                        "Xuất ảnh", MessageBoxButton.OK, MessageBoxImage.Information);
                }
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"❌ Export Error: {ex.Message}");
                MessageBox.Show($"Lỗi khi xuất ảnh: {ex.Message}", "Lỗi",
                    MessageBoxButton.OK, MessageBoxImage.Error);
            }
            finally
            {
                _moreMenu?.Hide();
            }
        }

