        /// <summary>
        /// Clone a UIElement (supports Polyline, Path, Line, Shape, Image, TextBlock, Border)
        /// </summary>
        private UIElement? CloneUIElement(FrameworkElement source)
        {
            try
            {
                if (source is Polyline polyline)
                {
                    var clone = new Polyline
                    {
                        Stroke = polyline.Stroke?.Clone(),
                        StrokeThickness = polyline.StrokeThickness,
                        StrokeLineJoin = polyline.StrokeLineJoin,
                        StrokeStartLineCap = polyline.StrokeStartLineCap,
                        StrokeEndLineCap = polyline.StrokeEndLineCap,
                        Opacity = polyline.Opacity
                    };
                    foreach (var pt in polyline.Points) clone.Points.Add(pt);
                    return clone;
                }
                else if (source is System.Windows.Shapes.Path path && path.Data != null)
                {
                    var clone = new System.Windows.Shapes.Path
                    {
                        Data = path.Data.Clone(),
                        Stroke = path.Stroke?.Clone(),
                        StrokeThickness = path.StrokeThickness,
                        StrokeLineJoin = path.StrokeLineJoin,
                        StrokeStartLineCap = path.StrokeStartLineCap,
                        StrokeEndLineCap = path.StrokeEndLineCap,
                        Fill = path.Fill?.Clone(),
                        Opacity = path.Opacity
                    };
                    return clone;
                }
                else if (source is System.Windows.Shapes.Line line)
                {
                    return new System.Windows.Shapes.Line
                    {
                        X1 = line.X1, Y1 = line.Y1, X2 = line.X2, Y2 = line.Y2,
                        Stroke = line.Stroke?.Clone(),
                        StrokeThickness = line.StrokeThickness,
                        Opacity = line.Opacity
                    };
                }
                else if (source is System.Windows.Shapes.Rectangle rect)
                {
                    return new System.Windows.Shapes.Rectangle
                    {
                        Width = rect.Width, Height = rect.Height,
                        Stroke = rect.Stroke?.Clone(), Fill = rect.Fill?.Clone(),
                        StrokeThickness = rect.StrokeThickness,
                        RadiusX = rect.RadiusX, RadiusY = rect.RadiusY,
                        Opacity = rect.Opacity
                    };
                }
                else if (source is System.Windows.Shapes.Ellipse ellipse)
                {
                    return new System.Windows.Shapes.Ellipse
                    {
                        Width = ellipse.Width, Height = ellipse.Height,
                        Stroke = ellipse.Stroke?.Clone(), Fill = ellipse.Fill?.Clone(),
                        StrokeThickness = ellipse.StrokeThickness,
                        Opacity = ellipse.Opacity
                    };
                }
                else if (source is System.Windows.Controls.Image img && img.Source != null)
                {
                    return new System.Windows.Controls.Image
                    {
                        Source = img.Source.Clone(),
                        Width = img.Width, Height = img.Height,
                        Stretch = img.Stretch,
                        Opacity = img.Opacity
                    };
                }
                else if (source is System.Windows.Controls.TextBlock tb)
                {
                    return new System.Windows.Controls.TextBlock
                    {
                        Text = tb.Text,
                        FontSize = tb.FontSize, FontFamily = tb.FontFamily,
                        FontWeight = tb.FontWeight, FontStyle = tb.FontStyle,
                        Foreground = tb.Foreground?.Clone(),
                        Background = tb.Background?.Clone(),
                        Opacity = tb.Opacity
                    };
                }

                // Fallback: use XamlWriter/XamlReader
                string xaml = System.Windows.Markup.XamlWriter.Save(source);
                var cloned = System.Windows.Markup.XamlReader.Parse(xaml) as UIElement;
                return cloned;
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"âš ï¸ CloneUIElement failed: {ex.Message}");
                return null;
            }
        }

