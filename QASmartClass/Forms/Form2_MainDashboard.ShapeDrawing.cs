        private void DrawCurvedArrow(Polygon polygon, double left, double top, double width, double height, string direction)
        {
            polygon.Points.Clear();
            int curvePoints = 30;
            
            if (direction == "CurvedRightArrow")
            {
                // Curved right arrow using Bezier-like curve
                for (int i = 0; i <= curvePoints; i++)
                {
                    double t = i / (double)curvePoints;
                    double x = left + width * 0.7 * t;
                    double y = top + height * 0.2 + height * 0.3 * Math.Sin(t * Math.PI);
                    polygon.Points.Add(new Point(x, y));
                }
                // Arrow head
                polygon.Points.Add(new Point(left + width * 0.7, top + height * 0.2));
                polygon.Points.Add(new Point(left + width, top + height * 0.5));
                polygon.Points.Add(new Point(left + width * 0.7, top + height * 0.8));
                
                // Return curve (bottom)
                for (int i = curvePoints; i >= 0; i--)
                {
                    double t = i / (double)curvePoints;
                    double x = left + width * 0.7 * t;
                    double y = top + height * 0.8 + height * 0.1 * Math.Sin(t * Math.PI);
                    polygon.Points.Add(new Point(x, y));
                }
            }
            else if (direction == "CurvedLeftArrow")
            {
                // Mirror of right
                for (int i = 0; i <= curvePoints; i++)
                {
                    double t = i / (double)curvePoints;
                    double x = left + width - width * 0.7 * t;
                    double y = top + height * 0.2 + height * 0.3 * Math.Sin(t * Math.PI);
                    polygon.Points.Add(new Point(x, y));
                }
                polygon.Points.Add(new Point(left + width * 0.3, top + height * 0.2));
                polygon.Points.Add(new Point(left, top + height * 0.5));
                polygon.Points.Add(new Point(left + width * 0.3, top + height * 0.8));
                
                for (int i = curvePoints; i >= 0; i--)
                {
                    double t = i / (double)curvePoints;
                    double x = left + width - width * 0.7 * t;
                    double y = top + height * 0.8 + height * 0.1 * Math.Sin(t * Math.PI);
                    polygon.Points.Add(new Point(x, y));
                }
            }
            else if (direction == "CurvedUpArrow")
            {
                // Vertical curved arrow (up)
                for (int i = 0; i <= curvePoints; i++)
                {
                    double t = i / (double)curvePoints;
                    double y = top + height - height * 0.7 * t;
                    double x = left + width * 0.2 + width * 0.3 * Math.Sin(t * Math.PI);
                    polygon.Points.Add(new Point(x, y));
                }
                polygon.Points.Add(new Point(left + width * 0.2, top + height * 0.3));
                polygon.Points.Add(new Point(left + width * 0.5, top));
                polygon.Points.Add(new Point(left + width * 0.8, top + height * 0.3));
                
                for (int i = curvePoints; i >= 0; i--)
                {
                    double t = i / (double)curvePoints;
                    double y = top + height - height * 0.7 * t;
                    double x = left + width * 0.8 + width * 0.1 * Math.Sin(t * Math.PI);
                    polygon.Points.Add(new Point(x, y));
                }
            }
            else // CurvedDownArrow
            {
                for (int i = 0; i <= curvePoints; i++)
                {
                    double t = i / (double)curvePoints;
                    double y = top + height * 0.7 * t;
                    double x = left + width * 0.2 + width * 0.3 * Math.Sin(t * Math.PI);
                    polygon.Points.Add(new Point(x, y));
                }
                polygon.Points.Add(new Point(left + width * 0.2, top + height * 0.7));
                polygon.Points.Add(new Point(left + width * 0.5, top + height));
                polygon.Points.Add(new Point(left + width * 0.8, top + height * 0.7));
                
                for (int i = curvePoints; i >= 0; i--)
                {
                    double t = i / (double)curvePoints;
                    double y = top + height * 0.7 * t;
                    double x = left + width * 0.8 + width * 0.1 * Math.Sin(t * Math.PI);
                    polygon.Points.Add(new Point(x, y));
                }
            }
        }
        
