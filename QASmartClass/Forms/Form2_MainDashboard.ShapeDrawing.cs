        // Helper: Create integral symbol (âˆ«)
        private Geometry CreateIntegralSymbol(double x, double y, double width, double height)
        {
            PathGeometry pathGeo = new PathGeometry();
            PathFigure figure = new PathFigure();
            
            double midX = x + width * 0.5;
            
            // âˆ« shape using Bezier curve
            figure.StartPoint = new Point(midX + width * 0.2, y);
            figure.Segments.Add(new BezierSegment(
                new Point(midX - width * 0.1, y + height * 0.2),
                new Point(midX - width * 0.1, y + height * 0.4),
                new Point(midX, y + height * 0.5),
                true));
            figure.Segments.Add(new BezierSegment(
                new Point(midX + width * 0.1, y + height * 0.6),
                new Point(midX + width * 0.1, y + height * 0.8),
                new Point(midX - width * 0.2, y + height),
                true));
            
            // Add thickness by creating return path
            figure.Segments.Add(new LineSegment(new Point(midX - width * 0.15, y + height), true));
            figure.Segments.Add(new BezierSegment(
                new Point(midX + width * 0.15, y + height * 0.8),
                new Point(midX + width * 0.15, y + height * 0.6),
                new Point(midX + width * 0.05, y + height * 0.5),
                true));
            figure.Segments.Add(new BezierSegment(
                new Point(midX - width * 0.05, y + height * 0.4),
                new Point(midX - width * 0.05, y + height * 0.2),
                new Point(midX + width * 0.15, y),
                true));
            
            figure.IsClosed = true;
            pathGeo.Figures.Add(figure);
            return pathGeo;
        }
        
