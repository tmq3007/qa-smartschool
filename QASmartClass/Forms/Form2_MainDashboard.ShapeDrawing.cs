        /// <summary>
        /// Trims canvas to a rectangle for prism
        /// Rectangle: width = base diagonal, height = hypotenuse of triangle(diagonal, prism height)
        /// hypotenuse = √(diagonal² + height²)
        /// </summary>
        private void TrimCanvasToPrismRectangle(Canvas canvas, double baseSize, double prismHeight, string baseType, double padding = 10)
        {
            if (canvas.Children.Count == 0) return;

            // Get number of sides from base type
            int sides = baseType switch
            {
                "Triangle" => 3,
                "Square" => 4,
                "Pentagon" => 5,
                "Hexagon" => 6,
                _ => 4
            };

            double minX = double.MaxValue;
            double minY = double.MaxValue;
            double maxX = double.MinValue;
            double maxY = double.MinValue;

            // Calculate bounding box including stroke thickness
            foreach (UIElement child in canvas.Children)
            {
                if (child is Shape shape)
                {
                    double strokeThickness = shape.StrokeThickness;
                    double halfStroke = strokeThickness / 2.0;

                    if (shape is Line line)
                    {
                        minX = Math.Min(minX, Math.Min(line.X1, line.X2) - halfStroke);
                        minY = Math.Min(minY, Math.Min(line.Y1, line.Y2) - halfStroke);
                        maxX = Math.Max(maxX, Math.Max(line.X1, line.X2) + halfStroke);
                        maxY = Math.Max(maxY, Math.Max(line.Y1, line.Y2) + halfStroke);
                    }
                    else if (shape is Polygon polygon)
                    {
                        foreach (Point pt in polygon.Points)
                        {
                            minX = Math.Min(minX, pt.X - halfStroke);
                            minY = Math.Min(minY, pt.Y - halfStroke);
                            maxX = Math.Max(maxX, pt.X + halfStroke);
                            maxY = Math.Max(maxY, pt.Y + halfStroke);
                        }
                    }
                    else if (shape is Ellipse ellipse)
                    {
                        double left = Canvas.GetLeft(ellipse);
                        double top = Canvas.GetTop(ellipse);
                        if (double.IsNaN(left)) left = 0;
                        if (double.IsNaN(top)) top = 0;

                        double width = ellipse.ActualWidth > 0 ? ellipse.ActualWidth : ellipse.Width;
                        double height = ellipse.ActualHeight > 0 ? ellipse.ActualHeight : ellipse.Height;

                        minX = Math.Min(minX, left - halfStroke);
                        minY = Math.Min(minY, top - halfStroke);
                        maxX = Math.Max(maxX, left + width + halfStroke);
                        maxY = Math.Max(maxY, top + height + halfStroke);
                    }
                }
            }

            if (minX == double.MaxValue || minY == double.MaxValue || 
                maxX == double.MinValue || maxY == double.MinValue)
                return;

            // Calculate center of current content
            double centerX = (minX + maxX) / 2.0;
            double centerY = (minY + maxY) / 2.0;

            // Calculate actual content dimensions
            double contentWidth = maxX - minX;
            double contentHeight = maxY - minY;

            // For prism base diagonal calculation
            // For regular polygon: diagonal depends on number of sides
            // For n-sided polygon inscribed in circle of radius r:
            // Maximum diagonal â‰ˆ 2 × r (for opposite vertices)
            double circumradius = baseSize / (2.0 * Math.Sin(Math.PI / sides));
            double baseDiagonal = 2.0 * circumradius;

            // Calculate hypotenuse: √(diagonal² + height²)
            double hypotenuse = Math.Sqrt(baseDiagonal * baseDiagonal + prismHeight * prismHeight);

            // Account for projection
            double theoreticalWidth = baseDiagonal * 1.2;
            double theoreticalHeight = hypotenuse * 1.2;

            double targetWidth = Math.Max(contentWidth, theoreticalWidth);
            double targetHeight = Math.Max(contentHeight, theoreticalHeight);

            // Create rectangle bounds centered on prism
            double rectMinX = centerX - (targetWidth / 2.0);
            double rectMinY = centerY - (targetHeight / 2.0);

            // Adjust all children to new origin
            double offsetX = rectMinX - padding;
            double offsetY = rectMinY - padding;

            foreach (UIElement child in canvas.Children)
            {
                if (child is Shape shape)
                {
                    if (shape is Line line)
                    {
                        line.X1 -= offsetX;
                        line.Y1 -= offsetY;
                        line.X2 -= offsetX;
                        line.Y2 -= offsetY;
                    }
                    else if (shape is Polygon polygon)
                    {
                        var newPoints = new PointCollection();
                        foreach (Point pt in polygon.Points)
                        {
                            newPoints.Add(new Point(pt.X - offsetX, pt.Y - offsetY));
                        }
                        polygon.Points = newPoints;
                    }
                    else
                    {
                        double left = Canvas.GetLeft(shape);
                        double top = Canvas.GetTop(shape);
                        if (!double.IsNaN(left)) Canvas.SetLeft(shape, left - offsetX);
                        if (!double.IsNaN(top)) Canvas.SetTop(shape, top - offsetY);
                    }
                }
                else
                {
                    double left = Canvas.GetLeft(child);
                    double top = Canvas.GetTop(child);
                    if (!double.IsNaN(left)) Canvas.SetLeft(child, left - offsetX);
                    if (!double.IsNaN(top)) Canvas.SetTop(child, top - offsetY);
                }
            }

            // Set canvas to rectangle
            canvas.Width = Math.Max(targetWidth + (padding * 2), 10);
            canvas.Height = Math.Max(targetHeight + (padding * 2), 10);
        }

