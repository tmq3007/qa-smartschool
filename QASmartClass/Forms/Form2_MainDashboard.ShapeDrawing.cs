        private void UpdatePathEquationShape(System.Windows.Shapes.Path path, Point startPoint, Point currentPoint)
        {
            double left = Math.Min(startPoint.X, currentPoint.X);
            double top = Math.Min(startPoint.Y, currentPoint.Y);
            double width = Math.Abs(currentPoint.X - startPoint.X);
            double height = Math.Abs(currentPoint.Y - startPoint.Y);
            
            GeometryGroup geometryGroup = new GeometryGroup();
            
            if (_currentShape == "Approximately")
            {
                // â‰ˆ symbol - TWO wavy lines
                geometryGroup.Children.Add(CreateWavyLine(left, top + height * 0.35, width, height * 0.08));
                geometryGroup.Children.Add(CreateWavyLine(left, top + height * 0.65, width, height * 0.08));
            }
            else if (_currentShape == "Equal")
            {
                // = symbol - TWO horizontal lines
                double lineThickness = height * 0.08;
                geometryGroup.Children.Add(CreateRectangle(left, top + height * 0.35, width, lineThickness));
                geometryGroup.Children.Add(CreateRectangle(left, top + height * 0.65, width, lineThickness));
            }
            else if (_currentShape == "Minus")
            {
                // − symbol - ONE horizontal line
                double lineThickness = height * 0.08;
                geometryGroup.Children.Add(CreateRectangle(left, top + height * 0.46, width, lineThickness));
            }
            else if (_currentShape == "Multiply")
            {
                // × symbol - TWO diagonal lines with white intersection gap
                double lineThickness = height * 0.12; // Thicker for visibility
                
                // Create path with two crossing lines
                PathGeometry pathGeo = new PathGeometry();
                
                // First diagonal (top-left to bottom-right)
                PathFigure line1 = new PathFigure();
                line1.StartPoint = new Point(left + width * 0.15, top + height * 0.15);
                line1.Segments.Add(new LineSegment(new Point(left + width * 0.85, top + height * 0.85), true));
                pathGeo.Figures.Add(line1);
                
                // Second diagonal (top-right to bottom-left)
                PathFigure line2 = new PathFigure();
                line2.StartPoint = new Point(left + width * 0.85, top + height * 0.15);
                line2.Segments.Add(new LineSegment(new Point(left + width * 0.15, top + height * 0.85), true));
                pathGeo.Figures.Add(line2);
                
                geometryGroup.Children.Add(pathGeo);
            }
            else if (_currentShape == "Divide")
            {
                // Ã· symbol - Line + TWO dots
                double lineThickness = height * 0.05;
                double dotRadius = height * 0.08;
                double midX = left + width * 0.5;
                double midY = top + height * 0.5;
                
                geometryGroup.Children.Add(CreateRectangle(left, midY - lineThickness / 2, width, lineThickness));
                geometryGroup.Children.Add(CreateCircle(midX, midY - height * 0.25, dotRadius));
                geometryGroup.Children.Add(CreateCircle(midX, midY + height * 0.25, dotRadius));
            }
            else if (_currentShape == "NotEqual")
            {
                // â‰  symbol - TWO lines + diagonal slash with white intersections
                double lineThickness = height * 0.12;
                
                // Create path with three lines
                PathGeometry pathGeo = new PathGeometry();
                
                // Top horizontal line
                PathFigure line1 = new PathFigure();
                line1.StartPoint = new Point(left, top + height * 0.35);
                line1.Segments.Add(new LineSegment(new Point(left + width, top + height * 0.35), true));
                pathGeo.Figures.Add(line1);
                
                // Bottom horizontal line
                PathFigure line2 = new PathFigure();
                line2.StartPoint = new Point(left, top + height * 0.65);
                line2.Segments.Add(new LineSegment(new Point(left + width, top + height * 0.65), true));
                pathGeo.Figures.Add(line2);
                
                // Diagonal slash
                PathFigure line3 = new PathFigure();
                line3.StartPoint = new Point(left + width * 0.3, top);
                line3.Segments.Add(new LineSegment(new Point(left + width * 0.7, top + height), true));
                pathGeo.Figures.Add(line3);
                
                geometryGroup.Children.Add(pathGeo);
            }
            else if (_currentShape == "LessOrEqual")
            {
                // â‰¤ symbol - < V-shape + horizontal line below
                double lineThickness = height * 0.08;
                geometryGroup.Children.Add(CreateVShape(left, top + height * 0.25, width, height * 0.4, true)); // pointing left
                geometryGroup.Children.Add(CreateRectangle(left + width * 0.1, top + height * 0.75, width * 0.8, lineThickness));
            }
            else if (_currentShape == "GreaterOrEqual")
            {
                // â‰¥ symbol - > V-shape + horizontal line below
                double lineThickness = height * 0.08;
                geometryGroup.Children.Add(CreateVShape(left, top + height * 0.25, width, height * 0.4, false)); // pointing right
                geometryGroup.Children.Add(CreateRectangle(left + width * 0.1, top + height * 0.75, width * 0.8, lineThickness));
            }
            else if (_currentShape == "LessThan")
            {
                // < symbol - V-shape pointing left
                geometryGroup.Children.Add(CreateVShape(left, top, width, height, true));
            }
            else if (_currentShape == "GreaterThan")
            {
                // > symbol - V-shape pointing right
                geometryGroup.Children.Add(CreateVShape(left, top, width, height, false));
            }
            else if (_currentShape == "Plus")
            {
                // + symbol - Vertical + Horizontal lines with white intersection gap
                double lineThickness = height * 0.12;
                
                // Create path with two crossing lines
                PathGeometry pathGeo = new PathGeometry();
                
                // Vertical line
                PathFigure vLine = new PathFigure();
                vLine.StartPoint = new Point(left + width * 0.5, top);
                vLine.Segments.Add(new LineSegment(new Point(left + width * 0.5, top + height), true));
                pathGeo.Figures.Add(vLine);
                
                // Horizontal line
                PathFigure hLine = new PathFigure();
                hLine.StartPoint = new Point(left, top + height * 0.5);
                hLine.Segments.Add(new LineSegment(new Point(left + width, top + height * 0.5), true));
                pathGeo.Figures.Add(hLine);
                
                geometryGroup.Children.Add(pathGeo);
            }
            else if (_currentShape == "Infinity")
            {
                geometryGroup.Children.Add(CreateInfinitySymbol(left, top, width, height));
            }
            else if (_currentShape == "Radical")
            {
                geometryGroup.Children.Add(CreateRadicalSymbol(left, top, width, height));
            }
            else if (_currentShape == "Summation")
            {
                geometryGroup.Children.Add(CreateSummationSymbol(left, top, width, height));
            }
            else if (_currentShape == "Integral")
            {
                geometryGroup.Children.Add(CreateIntegralSymbol(left, top, width, height));
            }
            
            path.Data = geometryGroup;
            
            // BUGFIX: Store intersection data for white overlay (to be drawn after finalization)
            if (_currentShape == "Plus" || _currentShape == "Multiply" || _currentShape == "NotEqual")
            {
                // Store shape type and bounds for later white intersection drawing
                path.Tag = new
                {
                    ShapeType = _currentShape,
                    Left = left,
                    Top = top,
                    Width = width,
                    Height = height,
                    LineThickness = height * 0.08,
                    NeedsWhiteIntersection = true
                };
            }
        }
        
        // Helper: Create wavy line geometry
        private Geometry CreateWavyLine(double x, double y, double width, double thickness)
        {
            PathGeometry pathGeo = new PathGeometry();
            PathFigure figure = new PathFigure();
            figure.StartPoint = new Point(x, y);
            
            int waves = 4;
            double waveHeight = thickness * 2;
            
            for (int i = 0; i <= 30; i++)
            {
                double t = (double)i / 30;
                double px = x + width * t;
                double py = y + waveHeight * Math.Sin(t * Math.PI * waves);
                figure.Segments.Add(new LineSegment(new Point(px, py), true));
            }
            
            // Return path for thickness
            for (int i = 30; i >= 0; i--)
            {
                double t = (double)i / 30;
                double px = x + width * t;
                double py = y + waveHeight * Math.Sin(t * Math.PI * waves) + thickness;
                figure.Segments.Add(new LineSegment(new Point(px, py), true));
            }
            
            figure.IsClosed = true;
            pathGeo.Figures.Add(figure);
            return pathGeo;
        }
        
