        // Helper: Create V-shape (< or >)
        private Geometry CreateVShape(double x, double y, double width, double height, bool pointingLeft)
        {
            PathGeometry pathGeo = new PathGeometry();
            PathFigure figure = new PathFigure();
            
            double thickness = Math.Min(width, height) * 0.08;
            double midY = y + height * 0.5;
            
            if (pointingLeft)
            {
                // < shape
                figure.StartPoint = new Point(x + width * 0.8, y + height * 0.1);
                figure.Segments.Add(new LineSegment(new Point(x + width * 0.2, midY), true));
                figure.Segments.Add(new LineSegment(new Point(x + width * 0.8, y + height * 0.9), true));
                figure.Segments.Add(new LineSegment(new Point(x + width, y + height * 0.9), true));
                figure.Segments.Add(new LineSegment(new Point(x + width * 0.4, midY), true));
                figure.Segments.Add(new LineSegment(new Point(x + width, y + height * 0.1), true));
            }
            else
            {
                // > shape
                figure.StartPoint = new Point(x + width * 0.2, y + height * 0.1);
                figure.Segments.Add(new LineSegment(new Point(x + width * 0.8, midY), true));
                figure.Segments.Add(new LineSegment(new Point(x + width * 0.2, y + height * 0.9), true));
                figure.Segments.Add(new LineSegment(new Point(x, y + height * 0.9), true));
                figure.Segments.Add(new LineSegment(new Point(x + width * 0.6, midY), true));
                figure.Segments.Add(new LineSegment(new Point(x, y + height * 0.1), true));
            }
            
            figure.IsClosed = true;
            pathGeo.Figures.Add(figure);
            return pathGeo;
        }
        
        // Helper: Create infinity symbol (âˆž)
        private Geometry CreateInfinitySymbol(double x, double y, double width, double height)
        {
            // Create infinity using two ellipse loops
            GeometryGroup group = new GeometryGroup();
            
            double loopWidth = width * 0.45;
            double loopHeight = height * 0.8;
            
            // Left loop
            EllipseGeometry leftLoop = new EllipseGeometry(
                new Point(x + width * 0.25, y + height * 0.5),
                loopWidth / 2,
                loopHeight / 2
            );
            
            // Right loop
            EllipseGeometry rightLoop = new EllipseGeometry(
                new Point(x + width * 0.75, y + height * 0.5),
                loopWidth / 2,
                loopHeight / 2
            );
            
            group.Children.Add(leftLoop);
            group.Children.Add(rightLoop);
            
            return group;
        }
        
