        /// <summary>
        /// Gom nhóm các nét vẽ tự do nằm gần hoặc đè lên nhau thành từng cụm ký tự (ví dụ: 2 nét của số 4, chữ T, A, E, +)
        /// Sắp xếp nghiêm ngặt các cụm từ trái sang phải theo trục X
        /// </summary>
        private List<List<SelectableObject>> ClusterDrawingObjects(List<SelectableObject> drawingObjs)
        {
            var clusters = new List<List<SelectableObject>>();
            if (drawingObjs == null || drawingObjs.Count == 0) return clusters;

            var sorted = drawingObjs.OrderBy(o => o.Bounds.X).ToList();

            foreach (var obj in sorted)
            {
                bool addedToCluster = false;

                foreach (var cluster in clusters)
                {
                    double clusterLeft = cluster.Min(o => o.Bounds.Left);
                    double clusterRight = cluster.Max(o => o.Bounds.Right);
                    double clusterTop = cluster.Min(o => o.Bounds.Top);
                    double clusterBottom = cluster.Max(o => o.Bounds.Bottom);
                    Rect clusterRect = new Rect(clusterLeft, clusterTop, Math.Max(1, clusterRight - clusterLeft), Math.Max(1, clusterBottom - clusterTop));

                    // Ngưỡng 12px theo chiều ngang để gom các nét cùng 1 ký tự mà không làm dính chữ bên cạnh
                    Rect expandedCluster = new Rect(clusterRect.X - 12, clusterRect.Y - 20, clusterRect.Width + 24, clusterRect.Height + 40);

                    if (expandedCluster.IntersectsWith(obj.Bounds))
                    {
                        cluster.Add(obj);
                        addedToCluster = true;
                        break;
                    }
                }

                if (!addedToCluster)
                {
                    clusters.Add(new List<SelectableObject> { obj });
                }
            }

            // Sắp xếp các cụm từ trái qua phải theo chiều ngang
            return clusters.OrderBy(c => c.Min(o => o.Bounds.X)).ToList();
        }

