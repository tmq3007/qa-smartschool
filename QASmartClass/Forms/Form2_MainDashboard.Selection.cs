        private void OnToolbarSpotlightClicked(object? sender, EventArgs e)
        {
            try
            {
                System.Diagnostics.Debug.WriteLine("OnToolbarSpotlightClicked called");
                
                // Toggle Spotlight Mode
                if (_currentSpotlightOverlay != null)
                {
                    // Turn off if already on
                    MainInteractiveBoard.Children.Remove(_currentSpotlightOverlay);
                    _currentSpotlightOverlay = null;
                    System.Diagnostics.Debug.WriteLine("Spotlight Mode deactivated");
                    return;
                }

                // Turn on Spotlight Mode for selected object
                var selectedObj = _selectionManager?.SelectedObject;
                if (selectedObj == null)
                {
                    var list = _selectionManager?.GetSelectedObjects();
                    if (list != null && list.Count > 0)
                    {
                        selectedObj = list[0];
                    }
                }

                if (selectedObj == null)
                {
                    MessageBox.Show("Vui lòng chọn một đối tượng để bật chế độ tiêu điểm (Spotlight).", "Thông báo", MessageBoxButton.OK, MessageBoxImage.Information);
                    return;
                }

                // Get selected object's bounds
                Rect bounds = selectedObj.Bounds;
                
                // Create the geometry for the overlay: whole canvas minus the selected bounds
                var outerGeometry = new System.Windows.Media.RectangleGeometry(new Rect(0, 0, MainInteractiveBoard.ActualWidth, MainInteractiveBoard.ActualHeight));
                var innerGeometry = new System.Windows.Media.RectangleGeometry(bounds, 8, 8);
                var combined = new System.Windows.Media.CombinedGeometry(System.Windows.Media.GeometryCombineMode.Exclude, outerGeometry, innerGeometry);
                
                var path = new System.Windows.Shapes.Path
                {
                    Fill = new System.Windows.Media.SolidColorBrush(System.Windows.Media.Color.FromArgb(180, 0, 0, 0)), // 70% opacity black
                    Data = combined,
                    IsHitTestVisible = true
                };
                
                path.MouseLeftButtonDown += (s, args) =>
                {
                    MainInteractiveBoard.Children.Remove(path);
                    if (_currentSpotlightOverlay == path)
                    {
                        _currentSpotlightOverlay = null;
                    }
                    args.Handled = true;
                };

                MainInteractiveBoard.Children.Add(path);
                _currentSpotlightOverlay = path;
                
                System.Diagnostics.Debug.WriteLine("Spotlight Mode activated");
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"[Spotlight Error] {ex.Message}");
            }
        }

