        {
            if (!_objectSelectionMode || _isLassoMode)
                return;

            Point currentPoint = e.GetPosition(MainInteractiveBoard);
            
            // 1. Handle object drag & drop (moving ALREADY SELECTED objects)
            if (_draggedSelectionObject != null && e.LeftButton == MouseButtonState.Pressed)
            {
                Vector dragVector = currentPoint - _selectionDragStartPoint;
                if (!_isDraggingSelection && (Math.Abs(dragVector.X) > 3 || Math.Abs(dragVector.Y) > 3))
                {
                    _isDraggingSelection = true;
                    System.Diagnostics.Debug.WriteLine($"🎯 Started dragging object: {_draggedSelectionObject.Type}");
                }
                
                if (_isDraggingSelection && _draggedSelectionObject.Element != null)
                {
                    var selectedObjects = _selectionManager?.GetSelectedObjects();
                    bool isMultiDrag = selectedObjects != null && selectedObjects.Count > 1;
                    
                    if (isMultiDrag)
                    {
                        foreach (var obj in selectedObjects!)
                        {
                            MoveSelectableObject(obj, dragVector);
                        }
                        System.Diagnostics.Debug.WriteLine(
                            $"🎯 Group moved: {selectedObjects.Count} objects by ({dragVector.X:F0}, {dragVector.Y:F0})");
                    }
                    else
                    {
                        MoveSelectableObject(_draggedSelectionObject, dragVector);
                        System.Diagnostics.Debug.WriteLine(
                            $"🎯 {_draggedSelectionObject.Type} moved by ({dragVector.X:F0}, {dragVector.Y:F0})");
                    }
                    
                    _selectionDragStartPoint = currentPoint;
                    
                    if (isMultiDrag)
                    {
                        _selectionManager?.RefreshGroupAdorner();
                        
                        double gMinX = double.MaxValue, gMinY = double.MaxValue;
                        double gMaxX = double.MinValue, gMaxY = double.MinValue;
                        foreach (var obj in selectedObjects!)
                        {
                            var b = obj.Bounds;
                            gMinX = Math.Min(gMinX, b.Left);  gMinY = Math.Min(gMinY, b.Top);
                            gMaxX = Math.Max(gMaxX, b.Right);  gMaxY = Math.Max(gMaxY, b.Bottom);
                        }
                        var groupRect = new Rect(gMinX, gMinY, gMaxX - gMinX, gMaxY - gMinY);

                        // ✅ QC_4.2_TOUCH_MOVE_FIX: Cập nhật vị trí & kích thước cho groupObject đang được attach với _selectionBox
                        if (_selectionBox != null && _selectionBox.Visibility == Visibility.Visible)
                        {
                            var attachedGroup = _selectionBox.AttachedObject;
                            if (attachedGroup != null && (attachedGroup.IsGroup || attachedGroup.Type == ObjectType.Group))
                            {
                                attachedGroup.Position = new Point(gMinX, gMinY);
                                attachedGroup.Size = new Size(groupRect.Width, groupRect.Height);
                                attachedGroup.Bounds = groupRect;
                            }
                            _selectionBox.UpdatePosition();
                        }

                        var toolbarPos = CalculateOptimalToolbarPosition(groupRect);
                        _contextToolbar?.ShowAt(toolbarPos, _draggedSelectionObject);
                    }
                    else
                    {
                        _selectionBox?.UpdatePosition();
                        if (_draggedSelectionObject.Bounds != Rect.Empty)
                        {
                            var bounds = _draggedSelectionObject.Bounds;
                            var toolbarPosition = CalculateOptimalToolbarPosition(bounds);
                            _contextToolbar?.ShowAt(toolbarPosition, _draggedSelectionObject);
                        }
                    }
                }
                return;
            }

            // ✅ QC_4.2_WIDGET_DRAG_FIX: Chỉ kiểm tra IsEventFromInteractiveControl nếu KHÔNG đang kéo di chuyển đối tượng
            if (QASmartTouch.Utilities.InputValidationHelper.IsEventFromInteractiveControl(e.OriginalSource, MainInteractiveBoard))
            {
                _isDraggingSelection = false;
                _draggedSelectionObject = null;
                if (MainInteractiveBoard.IsMouseCaptured)
                    MainInteractiveBoard.ReleaseMouseCapture();
                return;
            }
            
            // 2. Handle Rectangle Selection Drag (when dragging on canvas)
            if (e.LeftButton == MouseButtonState.Pressed && _draggedSelectionObject == null && _isPreparingRectangleSelection)
            {
                // ✅ CRITICAL FIX: Đang kéo chốt resize hoặc xoay SelectionBox -> Không tạo khung khoanh vùng chọn rectangle
                if (_selectionBox != null && _selectionBox.IsTransforming)
                {
                    if (_rectangleSelectionPreview != null)
                    {
                        MainInteractiveBoard.Children.Remove(_rectangleSelectionPreview);
                        _rectangleSelectionPreview = null;
                    }
                    _isRectangleSelecting = false;
                    return;
                }

                Vector dragVector = currentPoint - _rectangleSelectionStartPoint;
                if (!_isRectangleSelecting && (Math.Abs(dragVector.X) > 5 || Math.Abs(dragVector.Y) > 5))
                {
                    _isRectangleSelecting = true;
                    
                    // Create preview rectangle if needed
                    if (_rectangleSelectionPreview == null)
                    {
                        _rectangleSelectionPreview = new Rectangle
                        {
                            Stroke = new SolidColorBrush(Color.FromRgb(52, 152, 219)), // Dodger blue
                            StrokeThickness = 2,
                            StrokeDashArray = new DoubleCollection { 5, 3 },
                            Fill = new SolidColorBrush(Color.FromArgb(30, 52, 152, 219)),
                            RadiusX = 3,
                            RadiusY = 3
                        };
                        MainInteractiveBoard.Children.Add(_rectangleSelectionPreview);
                        Canvas.SetZIndex(_rectangleSelectionPreview, 9999);
                    }
                }
                
                if (_isRectangleSelecting && _rectangleSelectionPreview != null)
                {
                    double left = Math.Min(_rectangleSelectionStartPoint.X, currentPoint.X);
                    double top = Math.Min(_rectangleSelectionStartPoint.Y, currentPoint.Y);
                    double width = Math.Abs(currentPoint.X - _rectangleSelectionStartPoint.X);
                    double height = Math.Abs(currentPoint.Y - _rectangleSelectionStartPoint.Y);
                    
                    Canvas.SetLeft(_rectangleSelectionPreview, left);
                    Canvas.SetTop(_rectangleSelectionPreview, top);
                    _rectangleSelectionPreview.Width = width;
                    _rectangleSelectionPreview.Height = height;
                }
            }
        }
        
        /// <summary>
        /// Handle mouse up to complete drag operation or rectangle selection
        /// </summary>
        private void MainBoard_SelectionMouseUp(object sender, MouseButtonEventArgs e)
        {
            if (_isLassoMode)
                return;
            // 1. Handle Rectangle Selection completion
            if (_rectangleSelectionPreview != null || _isRectangleSelecting)
            {
                Point endPoint = e.GetPosition(MainInteractiveBoard);
                
                double left = Math.Min(_rectangleSelectionStartPoint.X, endPoint.X);
                double top = Math.Min(_rectangleSelectionStartPoint.Y, endPoint.Y);
                double right = Math.Max(_rectangleSelectionStartPoint.X, endPoint.X);
                double bottom = Math.Max(_rectangleSelectionStartPoint.Y, endPoint.Y);
                Rect selectionRect = new Rect(left, top, right - left, bottom - top);
                _lastDraggedSelectionRect = selectionRect;
                
                double rectW = right - left;
                double rectH = bottom - top;

                // Remove preview rectangle
                if (_rectangleSelectionPreview != null)
                {
                    MainInteractiveBoard.Children.Remove(_rectangleSelectionPreview);
                    _rectangleSelectionPreview = null;
                }
                _isRectangleSelecting = false;

                if (rectW > 5 || rectH > 5)
                {
                    // Dragged rectangle selection
                    var objectsInRect = _selectionManager?.GetObjectsInRect(selectionRect);
                    if (objectsInRect != null && objectsInRect.Count > 0)
                    {
                        _selectionManager?.SelectMultiple(objectsInRect);
                        System.Diagnostics.Debug.WriteLine($"📐 Rectangle selection: {objectsInRect.Count} object(s) selected");
                    }
                    else
                    {
                        _selectionManager?.DeselectAll();
                        System.Diagnostics.Debug.WriteLine("📐 Rectangle selection: No objects found, deselected all");
                    }
                    _pendingHitObject = null;

                    // Trigger pending smart action if user initiated OCR/Translate/Read/Search/AIChat
                    if (_pendingSmartAction.HasValue)
                    {
                        var pendingAction = _pendingSmartAction.Value;
                        _pendingSmartAction = null;
                        _ = Dispatcher.BeginInvoke(new Action(async () =>
                        {
                            await ExecuteSmartActionAsync(pendingAction);
                        }), System.Windows.Threading.DispatcherPriority.Background);
                    }

                    return;
                }
            }
            
            // 2. Xử lý kết thúc thao tác với đối tượng đã chọn (Kéo di chuyển hoặc Chạm giữ)
            if (_draggedSelectionObject != null)
            {
                if (_isDraggingSelection)
                {
                    // ✅ N23 FIX: Rebuild QuadTree spatial index ngay khi kết thúc kéo di chuyển
                    _selectionManager?.RebuildQuadTree();
                    var finalStates = CaptureSelectedObjectsTransformStates();
                    RecordTransformAction(_canvasDragInitialStates, finalStates, "Move object(s)");
                    System.Diagnostics.Debug.WriteLine("🌳 Selection drag ended: Rebuilt QuadTree & recorded Undo action.");
                }

                // Reset toàn bộ cờ kéo di chuyển
                _isDraggingSelection = false;
                _draggedSelectionObject = null;
                _isPreparingRectangleSelection = false;
                _pendingHitObject = null;
                _canvasDragInitialStates.Clear();

                // ✅ FIX TRIỆT ĐỂ: Thao tác trên đối tượng đã chọn xong thì RETURN NGAY,
                // TUYỆT ĐỐI KHÔNG để rơi xuống nhánh DeselectAll() bên dưới!
                return;
            }

            if (_isMagicWandMode && !_isRectangleSelecting)
            {
                Point clickPoint = e.GetPosition(MainInteractiveBoard);
                PerformMagicWandSelection(clickPoint);
                return;
            }

            // 3. Xử lý Single Click Selection (khi người dùng click chọn đối tượng mới hoặc click ra ngoài để hủy chọn)
            if (_pendingHitObject != null)
            {
                if (_pendingIsCtrl)
                {
                    _selectionManager?.ToggleSelection(_pendingHitObject);
                }
                else
                {
                    _selectionManager?.SelectObject(_pendingHitObject);
                }
            }
            else
            {
                if (!_pendingIsCtrl)
                {
                    _selectionManager?.DeselectAll();
                }
            }
            
            // Cleanup drag states
            _isDraggingSelection = false;
            _draggedSelectionObject = null;
            _pendingHitObject = null;
            _isPreparingRectangleSelection = false; // ✅ Khóa lại cờ hiệu sau khi xong việc
        }

