        private async void OnToolbarRecognizeHandwritingClicked(object? sender, EventArgs e)
        {
            System.Diagnostics.Debug.WriteLine($"✍️ OnToolbarRecognizeHandwritingClicked called");
            
            try
            {
                if (_captureService == null)
                {
                    _captureService = new SelectionCaptureService();
                }

                // Get selection bounds
                Rect selectionBounds;
                if (_selectionManager?.SelectedObject != null)
                {
                    // Single object selected
                    selectionBounds = _selectionManager.SelectedObject.Bounds;
                }
                else if (_selectionManager?.GetSelectedObjects()?.Count > 0)
                {
                    // Multiple objects selected - get combined bounds
                    selectionBounds = _selectionManager.GetMultiSelectionBounds();
                }
                else
                {
                    MessageBox.Show(
                        "Vui lòng chọn vùng chứa chữ viết trước.",
                        "Thông báo",
                        MessageBoxButton.OK,
                        MessageBoxImage.Information);
                    return;
                }

                if (selectionBounds.IsEmpty || selectionBounds.Width <= 0 || selectionBounds.Height <= 0)
                {
                    MessageBox.Show("Vùng chọn không hợp lệ.", "Thông báo", MessageBoxButton.OK, MessageBoxImage.Warning);
                    return;
                }

                System.Diagnostics.Debug.WriteLine($"📐 Selection bounds: {selectionBounds}");

                // Create and show dialog
                var dialog = new HandwritingRecognitionDialog
                {
                    Owner = this
                };
                dialog.ShowLoading();

                // Sử dụng TaskCompletionSource để chờ user đóng dialog trong chế độ non-modal
                var dialogClosedTcs = new TaskCompletionSource<bool>();
                dialog.Closed += (s, args) => dialogClosedTcs.TrySetResult(dialog.UserAccepted);
                dialog.Show();

                // Capture selection area as clean image (temporarily hides SelectionBox & ContextToolbar for pure stroke image)
                var (bitmap, imageBytes) = CaptureCleanSelectionArea(selectionBounds);
                if (bitmap == null && imageBytes == null)
                {
                    dialog.Close();
                    MessageBox.Show("Lỗi khi capture vùng chọn.", "Lỗi", MessageBoxButton.OK, MessageBoxImage.Error);
                    return;
                }

                List<HandwritingRecognitionResult> results = new List<HandwritingRecognitionResult>();

                // 1. Thử Google Cloud Vision API nếu service đã được khởi tạo
                if (_handwritingService != null && _handwritingService.IsInitialized && imageBytes != null)
                {
                    try
                    {
                        results = await _handwritingService.RecognizeHandwritingAsync(imageBytes, maxResults: 5);
                    }
                    catch (Exception gEx)
                    {
                        System.Diagnostics.Debug.WriteLine($"⚠️ Google Vision API error ({gEx.Message}). Falling back to Windows OCR Service...");
                    }
                }

                // 2. Nếu Google Vision API không trả kết quả hoặc gặp lỗi (PermissionDenied / Cloud Vision API disabled) -> Tự động chuyển sang Windows OCR Offline
                if ((results == null || results.Count == 0) && bitmap != null)
                {
                    if (_windowsOcrService == null)
                    {
                        _windowsOcrService = new WindowsOCRService();
                    }

                    var ocrRes = await _windowsOcrService.RecognizeTextAsync(bitmap);
                    if (ocrRes != null && ocrRes.IsSuccess && !string.IsNullOrWhiteSpace(ocrRes.Text))
                    {
                        results = new List<HandwritingRecognitionResult>
                        {
                            new HandwritingRecognitionResult
                            {
                                Text = ocrRes.Text.Trim(),
                                Confidence = 0.95f,
                                Rank = 0,
                                DetectedLanguage = "vi"
                            }
                        };
                    }
                }

                // 3. Thử Heuristic / Geometry Recognition fallback nếu cả 2 công cụ OCR không nhận diện được (ví dụ: chữ số 1 hoặc dấu đơn)
                if (results == null || results.Count == 0)
                {
                    var targetObject = _selectionManager?.SelectedObject ?? _selectionManager?.GetSelectedObjects()?.FirstOrDefault();
                    results = RecognizeStrokeGeometryFallback(targetObject);
                }

                if (results == null || results.Count == 0)
                {
                    dialog.ShowError("Không tìm thấy chữ viết rõ ràng trong vùng chọn.");
                    return;
                }

                // Kiểm tra nếu user đã đóng dialog trong lúc chờ
                if (dialogClosedTcs.Task.IsCompleted)
                {
                    return;
                }

                // Hiển thị ứng viên từ loại và kết quả trên dialog
                var candidates = _smartHandwritingRecognitionService.GenerateSpacingCandidates(results[0].Text);
                if (candidates.Count > 0 && _contextToolbar != null)
                {
                    _contextToolbar.ShowHandwritingCandidates(candidates);
                }

                // Show results in dialog
                dialog.ShowResults(results);

                // Chờ user bấm Insert hoặc Cancel (đóng dialog)
                bool userAccepted = await dialogClosedTcs.Task;
                
                if (userAccepted && dialog.SelectedResult != null)
                {
                    // User selected a result - insert text
                    InsertRecognizedText(
                        dialog.SelectedResult.Text,
                        selectionBounds,
                        dialog.ReplaceStrokes);
                    
                    System.Diagnostics.Debug.WriteLine($"✅ Inserted text: {dialog.SelectedResult.Text}");
                    ShowSmartStatusBadge($"☑ Đã chèn văn bản: \"{dialog.SelectedResult.Text}\"");
                }
            }
            catch (Exception ex)
            {
                ShowSmartStatusBadge($"❌ Lỗi nhận diện chữ viết: {ex.Message}");
            }
        }

        private void OnCandidateSelected(object? sender, string selectedText)
        {
            try
            {
                var selectedObjects = _selectionManager?.GetSelectedObjects();
                if (selectedObjects == null || selectedObjects.Count == 0) return;

                Rect bounds;
                if (_selectionManager?.SelectedObject != null)
                {
                    bounds = _selectionManager.SelectedObject.Bounds;
                }
                else
                {
                    bounds = _selectionManager?.GetMultiSelectionBounds() ?? Rect.Empty;
                }

                if (bounds.IsEmpty || bounds.Width <= 0 || bounds.Height <= 0) return;

                Color originalColor = _smartHandwritingRecognitionService.ExtractElementColor(selectedObjects[0].Element);
                double autoFontSize = _smartHandwritingRecognitionService.CalculateAutoFontSize(bounds.Height);

                // Remove original stroke elements
                foreach (var obj in selectedObjects)
                {
                    if (obj.Element != null && MainInteractiveBoard.Children.Contains(obj.Element))
                    {
                        MainInteractiveBoard.Children.Remove(obj.Element);
                        RecordRemoveAction(obj.Element, "Stroke");
                    }
                }

                // Create new TextBlock with matching original ink color & auto font size
                var textBlock = new TextBlock
                {
                    Text = selectedText,
                    FontSize = autoFontSize,
                    FontFamily = new FontFamily("Segoe UI"),
                    FontWeight = FontWeights.Medium,
                    Foreground = new SolidColorBrush(originalColor),
                    VerticalAlignment = VerticalAlignment.Center,
                    HorizontalAlignment = HorizontalAlignment.Center
                };

                Canvas.SetLeft(textBlock, bounds.Left);
                Canvas.SetTop(textBlock, bounds.Top);

                MainInteractiveBoard.Children.Add(textBlock);
                RecordAddAction(textBlock, "Text");

                _selectionManager?.DeselectAll();
                _selectionBox?.Detach();
                _contextToolbar?.Hide();
                RefreshSelectableObjects();

                System.Diagnostics.Debug.WriteLine($"✅ OCR candidate selected: '{selectedText}' with color {originalColor}");
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"❌ OnCandidateSelected error: {ex.Message}");
            }
        }

