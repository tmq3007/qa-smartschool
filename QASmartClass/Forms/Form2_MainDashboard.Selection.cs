        /// <summary>
        /// ✅ GĐ1-FIX: Helper method di chuyển 1 SelectableObject theo dragVector
        /// Hỗ trợ Polyline, Line, FrameworkElement (Rectangle, Ellipse, Image, TextBlock, Border)
        /// </summary>
        private void MoveSelectableObject(SelectableObject obj, Vector dragVector)
        {
            if (obj == null) return;
            
            // Xử lý nhóm đối tượng (Group / Multi-selection) kể cả khi Element == null
            if (obj.IsGroup || obj.Type == ObjectType.Group || (obj.GroupMembers != null && obj.GroupMembers.Count > 0))
            {
                foreach (var member in obj.GroupMembers)
                {
                    if (member == null || member.IsLocked) continue;
                    MoveSelectableObject(member, dragVector);
                }
                obj.UpdateBounds();
                return;
            }

            if (obj.Element == null) return;
            
            if (obj.Element is Polyline polyline)
            {
                // Di chuyển tất cả points
                for (int i = 0; i < polyline.Points.Count; i++)
                {
                    Point oldPoint = polyline.Points[i];
                    polyline.Points[i] = new Point(oldPoint.X + dragVector.X, oldPoint.Y + dragVector.Y);
                }
                // Recalculate bounds
                if (polyline.Points.Count > 0)
                {
                    double minX = double.MaxValue, minY = double.MaxValue;
                    double maxX = double.MinValue, maxY = double.MinValue;
                    foreach (var p in polyline.Points)
                    {
                        minX = Math.Min(minX, p.X); minY = Math.Min(minY, p.Y);
                        maxX = Math.Max(maxX, p.X); maxY = Math.Max(maxY, p.Y);
                    }
                    obj.Position = new Point(minX, minY);
                    obj.Size = new Size(maxX - minX, maxY - minY);
                }
            }
            else if (obj.Element is Polygon polygon)
            {
                if (polygon.Points != null && polygon.Points.Count > 0)
                {
                    for (int i = 0; i < polygon.Points.Count; i++)
                    {
                        Point oldPoint = polygon.Points[i];
                        polygon.Points[i] = new Point(oldPoint.X + dragVector.X, oldPoint.Y + dragVector.Y);
                    }
                    double minX = double.MaxValue, minY = double.MaxValue;
                    double maxX = double.MinValue, maxY = double.MinValue;
                    foreach (var p in polygon.Points)
                    {
                        minX = Math.Min(minX, p.X); minY = Math.Min(minY, p.Y);
                        maxX = Math.Max(maxX, p.X); maxY = Math.Max(maxY, p.Y);
                    }
                    if (!double.IsNaN(Canvas.GetLeft(polygon))) Canvas.SetLeft(polygon, double.NaN);
                    if (!double.IsNaN(Canvas.GetTop(polygon))) Canvas.SetTop(polygon, double.NaN);

                    obj.Position = new Point(minX, minY);
                    obj.Size = new Size(maxX - minX, maxY - minY);
                    obj.Bounds = new Rect(minX, minY, maxX - minX, maxY - minY);
                }
            }
            else if (obj.Element is System.Windows.Shapes.Line line)
            {
                // Di chuyển Line endpoints
                line.X1 += dragVector.X; line.Y1 += dragVector.Y;
                line.X2 += dragVector.X; line.Y2 += dragVector.Y;
                double minX = Math.Min(line.X1, line.X2);
                double minY = Math.Min(line.Y1, line.Y2);
                double w = Math.Max(Math.Abs(line.X2 - line.X1), line.StrokeThickness);
                double h = Math.Max(Math.Abs(line.Y2 - line.Y1), line.StrokeThickness);

                if (!double.IsNaN(Canvas.GetLeft(line))) Canvas.SetLeft(line, double.NaN);
                if (!double.IsNaN(Canvas.GetTop(line))) Canvas.SetTop(line, double.NaN);

                obj.Position = new Point(minX, minY);
                obj.Size = new Size(w, h);
                obj.Bounds = new Rect(minX, minY, w, h);
            }
            else if (obj.Element is System.Windows.Shapes.Path path && path.Data != null)
            {
                // ✅ QC_4.2_TOUCH_MOVE_FIX: Di chuyển TranslateTransform cho Path
                if (path.RenderTransform is TransformGroup tg)
                {
                    var tt = tg.Children.OfType<TranslateTransform>().FirstOrDefault();
                    if (tt == null)
                    {
                        tt = new TranslateTransform();
                        tg.Children.Add(tt);
                    }
                    tt.X += dragVector.X;
                    tt.Y += dragVector.Y;
                }
                else if (path.RenderTransform is TranslateTransform tt)
                {
                    tt.X += dragVector.X;
                    tt.Y += dragVector.Y;
                }
                else
                {
                    var tgNew = new TransformGroup();
                    if (path.RenderTransform != null && path.RenderTransform != Transform.Identity)
                        tgNew.Children.Add(path.RenderTransform);
                    tgNew.Children.Add(new TranslateTransform(dragVector.X, dragVector.Y));
                    path.RenderTransform = tgNew;
                }
                obj.Position = new Point(obj.Position.X + dragVector.X, obj.Position.Y + dragVector.Y);
            }
            else if (obj.Element is FrameworkElement fe)
            {
                // Di chuyển Canvas position (Rectangle, Ellipse, Image, TextBlock, Border)
                double cX = Canvas.GetLeft(fe), cY = Canvas.GetTop(fe);
                if (double.IsNaN(cX)) cX = 0;
                if (double.IsNaN(cY)) cY = 0;
                double newX = cX + dragVector.X, newY = cY + dragVector.Y;
                Canvas.SetLeft(fe, newX);
                Canvas.SetTop(fe, newY);
                obj.Position = new Point(newX, newY);
            }
            obj.UpdateBounds();
        }

