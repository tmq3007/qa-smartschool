        /// <summary>
        /// Insert recognized text as TextBox on canvas
        /// </summary>
        private void InsertRecognizedText(string text, Rect bounds, bool replaceStrokes)
        {
            try
            {
                // Create TextBox
                var textBox = new TextBox
                {
                    Text = text,
                    FontFamily = new System.Windows.Media.FontFamily("Segoe UI, Arial"),
                    FontSize = Math.Max(16, bounds.Height * 0.6), // Auto-size based on bounds
                    Foreground = Brushes.Black,
                    Background = Brushes.Transparent,
                    BorderThickness = new Thickness(0),
                    TextWrapping = TextWrapping.Wrap,
                    AcceptsReturn = false,
                    Width = Math.Max(100, bounds.Width),
                    MinHeight = Math.Max(30, bounds.Height)
                };

                // Position at selection bounds
                Canvas.SetLeft(textBox, bounds.Left);
                Canvas.SetTop(textBox, bounds.Top);
                Canvas.SetZIndex(textBox, 1000); // Above other elements

                // Add to canvas
                MainInteractiveBoard.Children.Add(textBox);

                // Register with SelectionManager
                RegisterNewObjectWithSelectionManager(textBox);

                // Record undo action
                RecordAddAction(textBox, "Recognized Text");

                // Replace strokes if requested
                if (replaceStrokes && _selectionManager != null)
                {
                    var selectedObjects = _selectionManager.GetSelectedObjects();
                    if (selectedObjects != null && selectedObjects.Count > 0)
                    {
                        foreach (var obj in selectedObjects.ToList())
                        {
                            // Only remove strokes (Polyline), keep other objects
                            if (obj.Type == ObjectType.Stroke && obj.Element is Polyline)
                            {
                                MainInteractiveBoard.Children.Remove(obj.Element);
                                _selectionManager.RemoveObject(obj);
                                System.Diagnostics.Debug.WriteLine($"🗑️ Removed stroke: {obj.Element}");
                            }
                        }
                    }
                }

                // Deselect all
                _selectionManager?.DeselectAll();

                System.Diagnostics.Debug.WriteLine($"✅ Inserted TextBox: \"{text}\" at ({bounds.Left:F0}, {bounds.Top:F0})");
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"❌ Failed to insert text: {ex.Message}");
                throw;
            }
        }

